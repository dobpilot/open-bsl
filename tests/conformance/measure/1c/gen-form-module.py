#!/usr/bin/env python3
"""Генератор модуля управляемой формы из .bsl-скрипта замеров.

Скрипт делится на ОБЪЯВЛЕНИЯ (Процедура/Функция) и ТЕЛО. Обычный скрипт
исполняется на сервере. Скрипт с `Асинх`-объявлениями исполняется на
клиенте: только там платформа разрешает объявлять async-методы.

Вывод: вызовы `Сообщить(` в КОПИИ текста заменяются на `СообщитьВФайл(`,
которая дописывает строку в файл. Затенить саму `Сообщить` нельзя —
платформа молча отказывается компилировать такой модуль (проверено).
Сам скрипт замеров при этом не меняется ни на символ.

Директива `// @onec-server-without-context СУФФИКС` переносит объявления
с указанным суффиксом на сервер без контекста формы. Она нужна составным
сценариям с кодом общего модуля, чьи локальные имена могут совпасть с
полями управляемой формы.
"""
import re, sys, pathlib

nl = chr(10)

src_path, out_module, out_file = sys.argv[1], sys.argv[2], sys.argv[3]
text = pathlib.Path(src_path).read_text(encoding="utf-8")
text = re.sub(r'\bСообщить\s*\(', 'СообщитьВФайл(', text)
async_mode = re.search(r'^\s*Асинх\s+(?:Процедура|Функция)\b', text, re.I | re.M) is not None
contextless_suffixes = re.findall(
    r'^\s*//\s*@onec-server-without-context\s+(\S+)\s*$', text, re.M
)

decls, body, module_vars, depth = [], [], [], 0
start = re.compile(
    r'^\s*(?:Асинх\s+)?(?:Процедура|Функция)\s+'
    r'([A-Za-zА-Яа-яЁё_][\w]*)',
    re.I,
)
end = re.compile(r'^\s*(КонецПроцедуры|КонецФункции)\b', re.I)
# `Перем` на верхнем уровне — объявление переменной МОДУЛЯ, и переносить
# его в тело процедуры нельзя: оно стало бы локальным, а это ровно та
# разница, которую мы и хотим замерить.
var_decl = re.compile(r'^\s*Перем\b', re.I)
for line in text.splitlines():
    declaration = start.match(line) if depth == 0 else None
    if declaration:
        depth = 1
        if async_mode:
            annotation = "&НаКлиенте"
        elif any(declaration.group(1).endswith(s) for s in contextless_suffixes):
            # Составной benchmark может включать код общего модуля. Без
            # контекста его локальные имена не сталкиваются с полями формы.
            annotation = "&НаСервереБезКонтекста"
        else:
            annotation = "&НаСервере"
        decls += [annotation, line]
    elif depth:
        decls.append(line)
        if end.match(line):
            depth = 0
            decls.append("")
    elif var_decl.match(line):
        module_vars.append(line)
    else:
        body.append(line)

indented = nl.join("	" + l if l.strip() else l for l in body)
if async_mode:
    entry = f'''&НаКлиенте
Процедура ПриОткрытии(Отказ)
	ВыполнитьТестНаКлиенте();
КонецПроцедуры

&НаКлиенте
Асинх Процедура ВыполнитьТестНаКлиенте()
	ОчиститьФайлВывода();

{indented}
КонецПроцедуры'''
else:
    entry = f'''&НаКлиенте
Процедура ПриОткрытии(Отказ)
	ВыполнитьТестНаСервере();
	ЗавершитьРаботуСистемы(Ложь);
КонецПроцедуры

&НаСервере
Процедура ВыполнитьТестНаСервере()
	ОчиститьФайлВывода();

{indented}
КонецПроцедуры'''

module = f'''{nl.join(module_vars)}

// Приёмник вывода: дописывает строку в файл. Открытие на каждой строке —
// сознательно: строк меньше сотни, зато нет ни модульных переменных, ни
// зависимости от того, переживает ли что-то серверный вызов.
&НаСервереБезКонтекста
Процедура СообщитьВФайл(Текст)
	Ф = Новый ЗаписьТекста("{out_file}", , , Истина);
	Ф.ЗаписатьСтроку(Строка(Текст));
	Ф.Закрыть();
КонецПроцедуры

&НаСервереБезКонтекста
Процедура ОчиститьФайлВывода()
	// Файл создаётся заново на каждом прогоне — иначе замеры копились бы.
	ФайлВывода = Новый ЗаписьТекста("{out_file}");
	ФайлВывода.Закрыть();
КонецПроцедуры

{nl.join(decls)}
{entry}
'''
pathlib.Path(out_module).write_text(module, encoding="utf-8")
print(f"объявлений: {sum(1 for l in decls if start.match(l))}, строк тела: {len(body)}")
