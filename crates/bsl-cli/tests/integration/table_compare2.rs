//! Сравнение таблиц значений на БОЛЬШИХ реальных данных.
//!
//! Кейсы содержат конфиденциальные данные и в репозитории не хранятся.
//! Тест берёт их из каталога в переменной окружения
//! `OPEN_BSL_TABLE_COMPARE2_CASES`; без неё он пропускается с пометкой в сводке.
//! Ожидаемая структура каталога — по подкаталогу на кейс, в каждом четыре
//! файла с выводом `ЗначениеВФайл`:
//!
//!   <кейс>/externalBaseData.txt   — Таблица0
//!   <кейс>/currentBaseData.txt    — Таблица1
//!   <кейс>/comparisonFields.txt   — Измерения (сериализованная строка)
//!   <кейс>/resultData.txt         — ожидаемый результат с платформы
//!
//! Сам алгоритм (`РазницаТаблицЗначений`, «Свернуть со знаками») дословно
//! совпадает с фикстурой `tests/conformance/fixtures/vt-diff.bsl`, чей
//! эталон снят с платформы, — здесь он гоняется на реальных объёмах
//! (сотни тысяч строк, значения-ссылки чужой конфигурации).
//!
//! Результат сверяется с платформенным КАК МУЛЬТИМНОЖЕСТВО СТРОК: порядок
//! `Сортировать(..., Новый СравнениеЗначений)` использует коллацию
//! платформы, которой здесь пока нет (см. комментарий к
//! `ValueTableData::compare` в `bsl-rt`), поэтому построчное сравнение
//! в исходном порядке осмысленно только после её появления. Ничего из
//! содержимого данных в вывод теста не попадает.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const ALGORITHM: &str = r#"
Функция РазницаТаблицЗначений(Таблица0, Таблица1, Измерения) Экспорт
	ВсеКолонки = "";
	Для Каждого Колонка Из Таблица1.Колонки Цикл
		ВсеКолонки = ВсеКолонки + ", " + Колонка.Имя
	КонецЦикла;
	ВсеКолонки = Сред(ВсеКолонки, 2);
	Таблица = Таблица1.Скопировать();
	Таблица.Колонки.Добавить("Знак", Новый ОписаниеТипов("Число"));
	Таблица.ЗаполнитьЗначения(1, "Знак");
	Для Каждого Строка Из Таблица0 Цикл
		ЗаполнитьЗначенияСвойств(Таблица.Добавить(), Строка)
	КонецЦикла;
	Таблица.Колонки.Добавить("Счет");
	Таблица.ЗаполнитьЗначения(1, "Счет");
	Таблица.Свернуть(ВсеКолонки, "Знак, Счет");
	Ответ = Таблица.Скопировать(Новый Структура("Счет", 1), ВсеКолонки + ", Знак");
	Если ЗначениеЗаполнено(Измерения) Тогда
		Ответ.Сортировать(Измерения, Новый СравнениеЗначений);
	КонецЕсли;
	Возврат Ответ;
КонецФункции

Функция КлючСтроки(Стр, Колонки)
	К = "";
	Для Каждого Кол Из Колонки Цикл
		К = К + Символ(1) + ЗначениеВСтрокуВнутр(Стр[Кол.Имя]);
	КонецЦикла;
	Возврат К;
КонецФункции
"#;

fn case_script(dir: &Path) -> String {
    // Кавычки в пути удваиваются — так экранирует строковый литерал BSL.
    let base = format!("{}/", dir.display()).replace('"', "\"\"");
    let mut s = String::from(ALGORITHM);
    let _ = write!(
        s,
        r#"
База = "{base}";
Таблица0 = ЗначениеИзФайла(База + "externalBaseData.txt");
Таблица1 = ЗначениеИзФайла(База + "currentBaseData.txt");
Измерения = ЗначениеИзФайла(База + "comparisonFields.txt");
Ожидаемый = ЗначениеИзФайла(База + "resultData.txt");
Ответ = РазницаТаблицЗначений(Таблица0, Таблица1, Измерения);

Счётчик = Новый Соответствие;
Для Каждого Стр Из Ответ Цикл
	К = КлючСтроки(Стр, Ожидаемый.Колонки);
	Было = Счётчик.Получить(К);
	Счётчик.Вставить(К, ?(Было = Неопределено, 1, Было + 1));
КонецЦикла;
Для Каждого Стр Из Ожидаемый Цикл
	К = КлючСтроки(Стр, Ожидаемый.Колонки);
	Было = Счётчик.Получить(К);
	Счётчик.Вставить(К, ?(Было = Неопределено, -1, Было - 1));
КонецЦикла;
Ненулевых = 0;
Для Каждого КиЗ Из Счётчик Цикл
	Если КиЗ.Значение <> 0 Тогда
		Ненулевых = Ненулевых + 1;
	КонецЕсли;
КонецЦикла;
Если Ненулевых = 0 Тогда
	Сообщить("СОВПАЛО: строк " + Формат(Ответ.Количество(), "ЧГ=0; ЧН=0"));
Иначе
	Сообщить("РАЗНЫХ СТРОК: " + Формат(Ненулевых, "ЧГ=0; ЧН=0"));
КонецЕсли;
"#
    );
    s
}

#[test]
fn table_compare2_cases_match_the_platform_result_as_a_multiset() {
    let Some(root) = std::env::var_os("OPEN_BSL_TABLE_COMPARE2_CASES") else {
        eprintln!(
            "table_compare2: пропущено — каталог кейсов не задан (OPEN_BSL_TABLE_COMPARE2_CASES)"
        );
        return;
    };
    let root = PathBuf::from(root);
    let bsl_cli = env!("CARGO_BIN_EXE_bsl-cli");

    let mut cases: Vec<PathBuf> = fs::read_dir(&root)
        .unwrap_or_else(|e| panic!("не читается {}: {e}", root.display()))
        .map(|e| e.expect("битая запись каталога").path())
        .filter(|p| p.join("resultData.txt").exists())
        .collect();
    cases.sort();
    assert!(
        !cases.is_empty(),
        "в {} нет ни одного кейса с resultData.txt",
        root.display()
    );

    let mut failures = Vec::new();
    for case in &cases {
        let name = case.file_name().unwrap().to_string_lossy().into_owned();
        let script_path = std::env::temp_dir().join(format!(
            "open-bsl-vt-diff-{}-{}.bsl",
            std::process::id(),
            cases.iter().position(|c| c == case).unwrap()
        ));
        fs::write(&script_path, case_script(case)).expect("скрипт не записался");

        let output = Command::new(bsl_cli)
            .arg(&script_path)
            .output()
            .unwrap_or_else(|e| panic!("не удалось запустить bsl-cli на {name}: {e}"));
        let stdout = String::from_utf8_lossy(&output.stdout);
        let _ = fs::remove_file(&script_path);

        // В сообщении об ошибке — только вердикт интерпретатора, данных в
        // нём нет (скрипт печатает счётчики, не содержимое).
        if !output.status.success() || !stdout.contains("СОВПАЛО") {
            failures.push(format!(
                "{name}: {}{}",
                stdout.trim(),
                String::from_utf8_lossy(&output.stderr).trim()
            ));
        } else {
            eprintln!("table_compare2: {name}: {}", stdout.trim());
        }
    }
    assert!(
        failures.is_empty(),
        "кейсы разошлись с платформенным результатом:\n  {}",
        failures.join("\n  ")
    );
}
