use std::cell::RefCell;
use std::rc::Rc;

use bsl_rt::{BslValue, LibraryRequirement, Shape};

use crate::instr::{ArgMode, Instr};

/// `(начало_pc, конец_pc, обработчик_pc)` на функцию — ноль стоимости, пока
/// исключение не брошено, как и описано в брифе (JVM/CPython делают так
/// же). `end_pc` эксклюзивно.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ExceptionRange {
    pub start_pc: usize,
    pub end_pc: usize,
    pub handler_pc: usize,
}

/// Слот инлайн-кэша `GetProp`/`SetProp`: интернированная форма структуры
/// и номер слота поля в ней (см. `Chunk::prop_cache`).
pub type PropCacheSlot = RefCell<Option<(Rc<Shape>, u32)>>;

/// Слот инлайн-кэша `CallObjectMethod`: адрес статической таблицы методов
/// типа-получателя и разрешённый по ней ДЕСКРИПТОР (`None` — имени в
/// таблице нет, вызов идёт строковым `call_method`). Кэшируется дескриптор
/// целиком, а не голый обработчик: на попадании в кэш VM берёт из него и
/// `arity` для рантаймной проверки числа аргументов, и `call`; ширина
/// ячейки та же — обе величины укладываются в один указатель. Адрес —
/// идентичность типа: таблицы живут в `'static`, у разных конвертированных
/// типов они разные, а мономорфный сайт после первого вызова больше не
/// ходит в карту мемоизации (см. `resolve_component_method` в `bsl-vm`).
pub type MethodCacheSlot = RefCell<Option<(usize, Option<&'static bsl_rt::MethodDescriptor>)>>;

/// Скомпилированное тело одной функции/процедуры либо скрипта верхнего
/// уровня. `n_regs` — пиковое число регистров кадра (параметры + локалы +
/// максимум одновременно живых временных) — столько `BslValue` резервирует
/// VM при входе в кадр.
#[derive(Debug, Clone)]
pub struct Chunk {
    pub instrs: Vec<Instr>,
    pub consts: Vec<BslValue>,
    /// Режимы аргументов для каждой инструкции `Call` в этом чанке,
    /// индексируются полем `arg_modes` той инструкции.
    pub call_arg_modes: Vec<Vec<ArgMode>>,
    /// Диапазоны `Попытка`/`КонецПопытки` в этом чанке — при нескольких
    /// вложенных диапазонах, содержащих один pc, VM выбирает самый узкий.
    pub exception_ranges: Vec<ExceptionRange>,
    /// Параметры занимают слоты `0..n_params` (см. `bsl-sema`), это нужно
    /// VM, чтобы отличить слоты-алиасы (параметры) от собственных слотов
    /// кадра при вычислении абсолютного индекса в стеке значений.
    pub n_params: u8,
    /// Режим передачи каждого параметра: `true` — `Знач` (по значению).
    /// Нужен компилятору ФРАГМЕНТА `Выполнить`, который компилирует вызов
    /// этой функции, не имея её резолвнутого дерева.
    pub param_by_val: Vec<bool>,
    /// Есть ли у каждого параметра значение по умолчанию — там же и затем
    /// же, что `param_by_val`: фрагмент `Выполнить`/`Вычислить` резолвит
    /// вызов этой функции, не имея её дерева, и без этого не отличил бы
    /// опущенный хвостовой необязательный аргумент (`Хвост(1, )`) от
    /// пропущенного обязательного. Прежде фрагмент подставлял заглушку
    /// «умолчаний нет», и `Вычислить("Хвост(1, )")` отвергалось при том,
    /// что тот же текст в модуле компилировался (воспроизведение 4).
    pub param_has_default: Vec<bool>,
    /// Объявлена ли `Процедура` — там же и затем же, что `param_by_val`:
    /// фрагмент `Выполнить`/`Вычислить` резолвится в рантайме и обязан
    /// отвергнуть процедуру в позиции выражения так же, как это сделал бы
    /// статический резолвер (измерено, строка «своя процедура выражением»
    /// в `measure-stmtcall.platform.txt`). В скомпилированном коде другого
    /// следа от вида объявления не остаётся: обе формы возвращают
    /// `Неопределено`, если не сказано иначе. У `chunks[0]` — `false`:
    /// верхний уровень никто не вызывает.
    pub is_procedure: bool,
    pub n_locals: u8,
    pub n_regs: u8,
    /// Инлайн-кэш `(форма, слот)` на каждую инструкцию `GetProp`/`SetProp`
    /// в этом чанке (см. брифовский план оптимизаций №1) — индекс совпадает
    /// с позицией инструкции в `instrs`, остальные позиции просто не
    /// используются. `RefCell`, потому что `Chunk` живёт за `&Program` всё
    /// время исполнения (VM его не мутирует напрямую), а кэш всё равно
    /// должен обновляться при первом попадании.
    pub prop_cache: Vec<PropCacheSlot>,
    /// Инлайн-кэш обработчика на каждую инструкцию `CallObjectMethod` —
    /// устроен как `prop_cache`: длиной со все `instrs`, в текстовый формат
    /// не пишется и создаётся пустым при компиляции и разборе.
    pub method_cache: Vec<MethodCacheSlot>,
    /// Имена слотов `0..n_locals` — МАТЕРИАЛИЗОВАННАЯ таблица «имя ->
    /// слот» этого кадра. Заполняется ТОЛЬКО у чанков, помеченных
    /// `ResolvedFunction::uses_dynamic`, то есть содержащих
    /// `Выполнить`/`Вычислить`: фрагмент видит область видимости по
    /// именам, а после резолвинга имён не остаётся — только номера слотов.
    /// У остальных чанков (99% кода) пусто, и ничего лишнего они не несут.
    ///
    /// Порядок совпадает с раскладкой регистров кадра, поэтому индекс в
    /// этом векторе И ЕСТЬ номер слота — отдельной карты не нужно.
    pub local_names: Vec<String>,
    /// Разметка VLIW-бандлов (см. [`crate::bundle`]): `bundle_len[pc]` —
    /// ширина бандла, начинающегося на `pc`, 0 — середина бандла. Члены
    /// бандла взаимно независимы (без RAW/WAW), и VM исполняет их одним
    /// заходом диспетчера. Таблица производная: в текстовый формат не
    /// пишется и пересчитывается при разборе, как `prop_cache`; пустой
    /// вектор равнозначен поинструкционному исполнению.
    pub bundle_len: Vec<u8>,
    /// Есть ли в чанке обращение к ОБЪЕКТУ — шесть опкодов, у которых
    /// обработчик компонента получает контекст исполнения. Производное
    /// поле, как `bundle_len`: в текстовый формат не пишется и считается
    /// при компиляции и при разборе.
    ///
    /// Живёт здесь, а не считается на месте: считать его должен был бы
    /// `bsl-vm`, а любая новая функция в его `lib.rs` сдвигает укладку
    /// горячего цикла — `empty_for` платил за это 58 -> 95 млн тактов при
    /// неизменном числе инструкций.
    pub touches_objects: bool,
}

/// Весь скомпилированный модуль: `chunks[0]` — скрипт верхнего уровня,
/// `chunks[1..]` — объявленные `Процедура`/`Функция` в порядке резолвинга
/// (индекс `i` в `ResolvedProgram::functions` соответствует `chunks[i+1]`).
///
/// `names`/`shapes` — общие для всего модуля таблицы, интернированные один
/// раз при компиляции (см. `bsl_rt::NameInterner`/`ShapeTable`): доступ к
/// полю ссылается на них по индексу (`NameId`/индекс формы), а не хранит
/// строку или список полей в каждой инструкции.
#[derive(Debug, Clone)]
pub struct Program {
    /// Адресуемые runtime-компоненты и их точные версии. Индекс записи —
    /// операнд `library` универсальных инструкций компонентов.
    pub requirements: Vec<LibraryRequirement>,
    pub chunks: Vec<Chunk>,
    pub names: Vec<String>,
    pub shapes: Vec<Rc<Shape>>,
    /// Слоты верхнего уровня по именам, в порядке — нужно `Выполнить`/
    /// `Вычислить` (см. `bsl-vm`), чтобы резолвить уже объявленные
    /// top-level переменные фрагмента на те же слоты, что и в статическом
    /// коде, а не заводить их заново.
    pub top_level_locals: Vec<String>,
    /// Имена переменных уровня модуля. Их номер — АБСОЛЮТНЫЙ индекс в
    /// стеке значений: они занимают первые слоты кадра верхнего уровня,
    /// который живёт всё исполнение (см. `Instr::GetModuleVar`).
    pub module_vars: Vec<String>,
    /// С какого индекса стека начинается блок модульных переменных.
    /// У обычной программы 0: кадр верхнего уровня стоит в самом низу
    /// стека, и слот модульной переменной — её же абсолютный индекс. У
    /// фрагмента `Выполнить` стек свой, и блок кладётся ЗА его регистрами
    /// — тогда база ненулевая. В текстовый формат не пишется: это свойство
    /// прогона, а не байт-кода.
    pub module_base: u32,
    /// Имена процедур и функций: `function_names[i]` — это `chunks[i+1]`.
    ///
    /// Нужны `Выполнить`/`Вычислить`: ИЗМЕРЕНО, что фрагмент видит функции
    /// модуля (`Вычислить("Удвоить(21)")` -> 42), а резолвить вызов по
    /// имени без имён нельзя. Заодно ими подписан листинг байт-кода —
    /// раньше чанк был безымянным номером.
    pub function_names: Vec<String>,
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Кэш `CallObjectMethod` перешёл с голого обработчика на дескриптор
    /// целиком (ABI-C плана abi-refactor-f), чтобы на попадании в кэш была
    /// доступна `arity`. Дескриптор и обработчик — оба указатели, поэтому
    /// ячейка не должна вырасти: это горячий путь объектных вызовов, и рост
    /// ячейки удорожил бы каждый мономорфный сайт. Значение зафиксировано
    /// намеренно — тест ловит непреднамеренное расширение слота.
    #[test]
    fn method_cache_slot_did_not_grow() {
        assert_eq!(std::mem::size_of::<MethodCacheSlot>(), 32);
    }
}
