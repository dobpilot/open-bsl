use std::rc::Rc;

use bsl_rt::{BslValue, LibraryRequirement, Shape};

use crate::instr::{ArgMode, Instr};

/// `(начало_pc, конец_pc, обработчик_pc)` на функцию — ноль стоимости, пока
/// исключение не брошено, как и описано в брифе (JVM/CPython делают так
/// же). `end_pc` эксклюзивно.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ExceptionRange {
    pub start_pc: usize,
    pub end_pc: usize,
    pub handler_pc: usize,
}

/// Константа таблицы констант чанка.
///
/// Обёртка сужает вход в таблицу до проверяемого преобразования, чтобы
/// непредставимое значение не попадало туда по недосмотру. Полного
/// запрета она НЕ даёт и не притворяется им: рядом есть [`Self::transient`],
/// публичный и безопасный, и внешний Rust-клиент может собрать им
/// печатаемую программу с объектом. Гарантия здесь контрактная, а не
/// типовая — «непредставимое требует явно названного входа», а не
/// «непредставимое невозможно». Прежде
/// `consts` принимал любой `BslValue`, включая объект и тип: образ
/// собирался, проходил проверку и исполнялся, а отказ приходил от печати
/// листинга — команды, к дефекту отношения не имеющей. У объекта беда и
/// вторая: он изменяем и живёт за `Rc`, поэтому «константа»
/// разделялась бы всеми исполнениями своей `LoadConst`, и два прохода
/// цикла видели бы один изменяемый экземпляр.
///
/// Тип ПРОЗРАЧЕН по представлению и разыменовывается в `BslValue`: чтение
/// константы в горячем пути остаётся тем же чтением. Отдельное
/// перечисление со своим набором вариантов означало бы преобразование на
/// каждой `LoadConst`, а это один из самых частых опкодов.
#[derive(Debug, Clone, PartialEq)]
#[repr(transparent)]
pub struct BytecodeConst(BslValue);

impl BytecodeConst {
    /// Проверяемое преобразование из значения рантайма.
    ///
    /// # Errors
    ///
    /// Значение, которое текстовый формат не представляет, — объект или
    /// тип. Множество здесь ровно то же, на которое отвечает отказом
    /// `write_const`, и расходиться им нельзя: разошедшись, они дали бы
    /// образ, который собирается, но не печатается.
    pub fn new(value: BslValue) -> Result<Self, BslValue> {
        // Классификация ОДНА на проект и живёт у печати, потому что
        // множество представимых констант — это свойство текстового
        // формата, а не таблицы. Ветви-заглушки там нет, поэтому новый
        // вариант `BslValue` станет ошибкой сборки, а не молча пройдёт
        // сюда. Разбор с `_` здесь именно это и ломал.
        match crate::text::classify_const(&value) {
            Ok(_) => Ok(Self(value)),
            Err(_) => Err(value),
        }
    }

    /// Константа программы, которая НИКОГДА не печатается.
    ///
    /// Единственный законный случай — таблица констант как транспорт, а
    /// не литеральный пул. Так устроены фоновые задания: аргументы
    /// задания материализуются в значения рантайма (массив, структура,
    /// соответствие, таблица значений, тип) и едут в entry-программу
    /// воркера обычными `LoadConst`. Эта программа собирается в памяти и
    /// сериализуется не она, а каталог (`entry: None`), поэтому
    /// непредставимость в тексте ей ничем не грозит.
    ///
    /// Вход намеренно назван так, чтобы его было видно в поиске: пока он
    /// один, «непредставимая константа» — принятое решение в известном
    /// месте, а не свойство, доступное каждому из двух десятков
    /// сборщиков.
    ///
    /// Обязательство «только для непечатаемых программ» типами НЕ
    /// обеспечивается и обеспечено быть не может: тип не знает, дойдёт ли
    /// программа до печати. Вторая половина договорённости лежит у
    /// печати — она такую константу отвергает, — и обе половины держит
    /// `objects_in_constants_are_refused_rather_than_printed_wrong`.
    #[must_use]
    pub fn transient(value: BslValue) -> Self {
        Self(value)
    }

    /// Значение константы.
    #[must_use]
    pub fn value(&self) -> &BslValue {
        &self.0
    }
}

impl std::ops::Deref for BytecodeConst {
    type Target = BslValue;

    fn deref(&self) -> &BslValue {
        &self.0
    }
}

/// Скомпилированное тело одной функции/процедуры либо скрипта верхнего
/// уровня. `n_regs` — пиковое число регистров кадра (параметры + локалы +
/// максимум одновременно живых временных) — столько `BslValue` резервирует
/// VM при входе в кадр.
#[derive(Debug, Clone)]
pub struct Chunk {
    pub instrs: Vec<Instr>,
    pub consts: Vec<BytecodeConst>,
    /// Режимы аргументов для каждой инструкции `Call` в этом чанке,
    /// индексируются полем `arg_modes` той инструкции.
    pub call_arg_modes: Vec<Vec<ArgMode>>,
    /// Диапазоны `Попытка`/`КонецПопытки` в этом чанке — при нескольких
    /// вложенных диапазонах, содержащих один pc, VM выбирает самый узкий.
    pub exception_ranges: Vec<ExceptionRange>,
    /// Параметры занимают слоты `0..n_params` (см. `bsl-sema`), это нужно
    /// VM, чтобы отличить слоты-алиасы (параметры) от собственных слотов
    /// кадра при вычислении абсолютного индекса в стеке значений.
    pub n_params: u8,
    /// Режим передачи каждого параметра: `true` — `Знач` (по значению).
    /// Нужен компилятору ФРАГМЕНТА `Выполнить`, который компилирует вызов
    /// этой функции, не имея её резолвнутого дерева.
    pub param_by_val: Vec<bool>,
    /// Есть ли у каждого параметра значение по умолчанию — там же и затем
    /// же, что `param_by_val`: фрагмент `Выполнить`/`Вычислить` резолвит
    /// вызов этой функции, не имея её дерева, и без этого не отличил бы
    /// опущенный хвостовой необязательный аргумент (`Хвост(1, )`) от
    /// пропущенного обязательного. Прежде фрагмент подставлял заглушку
    /// «умолчаний нет», и `Вычислить("Хвост(1, )")` отвергалось при том,
    /// что тот же текст в модуле компилировался (воспроизведение 4).
    pub param_has_default: Vec<bool>,
    /// Объявлена ли `Процедура` — там же и затем же, что `param_by_val`:
    /// фрагмент `Выполнить`/`Вычислить` резолвится в рантайме и обязан
    /// отвергнуть процедуру в позиции выражения так же, как это сделал бы
    /// статический резолвер (измерено, строка «своя процедура выражением»
    /// в `measure-stmtcall.platform.txt`). В скомпилированном коде другого
    /// следа от вида объявления не остаётся: обе формы возвращают
    /// `Неопределено`, если не сказано иначе. У `chunks[0]` — `false`:
    /// верхний уровень никто не вызывает.
    pub is_procedure: bool,
    /// Объявлен ли метод с модификатором `Асинх`. У верхнего уровня всегда
    /// `false`.
    pub is_async: bool,
    pub n_locals: u8,
    pub n_regs: u8,
    /// Имена слотов `0..n_locals` — МАТЕРИАЛИЗОВАННАЯ таблица «имя ->
    /// слот» этого кадра. Заполняется ТОЛЬКО у чанков, помеченных
    /// `ResolvedFunction::uses_dynamic`, то есть содержащих
    /// `Выполнить`/`Вычислить`: фрагмент видит область видимости по
    /// именам, а после резолвинга имён не остаётся — только номера слотов.
    /// У остальных чанков (99% кода) пусто, и ничего лишнего они не несут.
    ///
    /// Порядок совпадает с раскладкой регистров кадра, поэтому индекс в
    /// этом векторе И ЕСТЬ номер слота — отдельной карты не нужно.
    pub local_names: Vec<String>,
    /// Разметка VLIW-бандлов (см. [`crate::bundle`]): `bundle_len[pc]` —
    /// ширина бандла, начинающегося на `pc`, 0 — середина бандла. Члены
    /// бандла взаимно независимы (без RAW/WAW), и VM исполняет их одним
    /// заходом диспетчера. Таблица производная: в текстовый формат не
    /// пишется и пересчитывается при разборе; пустой вектор равнозначен
    /// поинструкционному исполнению.
    pub(crate) bundle_len: Vec<u8>,
}

impl Default for Chunk {
    fn default() -> Self {
        Self::new()
    }
}

impl Chunk {
    /// Пустой чанк: ни инструкций, ни таблиц.
    ///
    /// Внешний сборщик начинает отсюда и присваивает открытые поля.
    /// Литералом `Chunk { .. }` он больше не собирается, и это цель, а не
    /// побочный эффект: производная разметка бандлов закрыта, и заполняет её
    /// только [`crate::image::finalize`]. Пока поле было открыто,
    /// рассинхронизировать его мог любой сборщик, а обнаруживалось это
    /// проверкой образа, то есть на запуске, а не на сборке.
    #[must_use]
    pub fn new() -> Self {
        Self {
            instrs: Vec::new(),
            consts: Vec::new(),
            call_arg_modes: Vec::new(),
            exception_ranges: Vec::new(),
            n_params: 0,
            param_by_val: Vec::new(),
            param_has_default: Vec::new(),
            is_procedure: false,
            is_async: false,
            n_locals: 0,
            n_regs: 0,
            local_names: Vec::new(),
            bundle_len: Vec::new(),
        }
    }

    /// Разметка бандлов: сколько инструкций исполняется за одну
    /// диспетчеризацию, начиная с этой.
    ///
    /// Только на чтение, и это не стилистика. Таблица производная, и
    /// посчитанная ДО правки инструкций она описывает уже не тот чанк —
    /// а VM исполняет бандл целиком, доверяя доказанной независимости
    /// членов. Пока поле было публичным, рассинхронизировать его мог
    /// любой сборщик, и обнаруживалось это лишь проверкой образа, то
    /// есть на запуске, а не на сборке. Писать её вправе только
    /// [`crate::image::finalize`].
    ///
    /// Пустая таблица законна и означает поинструкционное исполнение.
    #[must_use]
    #[inline(always)]
    pub fn bundle_len(&self) -> &[u8] {
        &self.bundle_len
    }
}

/// Скомпилированный фрагмент REPL или `Выполнить`/`Вычислить`: чанк вместе
/// с ПОЛНЫМИ таблицами имён и форм, на которые ссылаются его индексы.
///
/// Тип связывает то, что раньше было безымянным кортежем `(Chunk,
/// Vec<String>, Vec<Rc<Shape>>)`, инвариант которого — «`shape`-индексы
/// чанка ссылаются ИМЕННО на этот `shapes`, а `NameId` — на этот `names`» —
/// держался позицией. Класс дефекта (перепутанные списки на входе
/// исполнителя) реализовался дважды; здесь он выражен полем, а не порядком
/// аргументов.
#[derive(Debug, Clone)]
pub struct SnippetUnit {
    pub chunk: Chunk,
    /// Полная таблица имён полей: имена основной программы (для
    /// согласованности `NameId` с уже созданными объектами) плюс новые,
    /// впервые упомянутые фрагментом.
    pub names: Vec<String>,
    /// СОБСТВЕННЫЕ формы фрагмента: `shape`-индексы внутри `chunk` ссылаются
    /// именно на этот список, а не на какой-то внешний.
    pub shapes: Vec<Rc<Shape>>,
    /// Строка на каждую инструкцию `chunk`, если сведения об отладке
    /// запрошены; иначе пусто.
    ///
    /// Строки отсчитываются от начала СОБСТВЕННОГО текста фрагмента, а не
    /// файла с вызовом: текст фрагмента — значение времени исполнения и
    /// может не лежать ни в одном файле.
    pub lines: Vec<u32>,
}

/// Весь скомпилированный модуль: `chunks[0]` — скрипт верхнего уровня,
/// `chunks[1..]` — объявленные `Процедура`/`Функция` в порядке резолвинга
/// (индекс `i` в `ResolvedProgram::functions` соответствует `chunks[i+1]`).
///
/// `names`/`shapes` — общие для всего модуля таблицы, интернированные один
/// раз при компиляции (см. `bsl_rt::NameInterner`/`ShapeTable`): доступ к
/// полю ссылается на них по индексу (`NameId`/индекс формы), а не хранит
/// строку или список полей в каждой инструкции.
#[derive(Debug, Clone)]
pub struct Program {
    /// Адресуемые runtime-компоненты и их точные версии. Индекс записи —
    /// операнд `library` универсальных инструкций компонентов.
    pub requirements: Vec<LibraryRequirement>,
    pub chunks: Vec<Chunk>,
    pub names: Vec<String>,
    pub shapes: Vec<Rc<Shape>>,
    /// Слоты верхнего уровня по именам, в порядке — нужно `Выполнить`/
    /// `Вычислить` (см. `bsl-vm`), чтобы резолвить уже объявленные
    /// top-level переменные фрагмента на те же слоты, что и в статическом
    /// коде, а не заводить их заново.
    pub top_level_locals: Vec<String>,
    /// Имена переменных уровня модуля. Их номер — АБСОЛЮТНЫЙ индекс в
    /// стеке значений: они занимают первые слоты кадра верхнего уровня,
    /// который живёт всё исполнение (см. `Instr::GetModuleVar`).
    pub module_vars: Vec<String>,
    /// Имена процедур и функций: `function_names[i]` — это `chunks[i+1]`.
    ///
    /// Нужны `Выполнить`/`Вычислить`: ИЗМЕРЕНО, что фрагмент видит функции
    /// модуля (`Вычислить("Удвоить(21)")` -> 42), а резолвить вызов по
    /// имени без имён нельзя. Заодно ими подписан листинг байт-кода —
    /// раньше чанк был безымянным номером.
    pub function_names: Vec<String>,
    /// Параллельно `function_names`: метод объявлен с модификатором
    /// `Экспорт`. Только экспортные методы видны другим модулям
    /// конфигурации и годятся в цель фонового задания; внутри одного
    /// модуля признак ни на что не влияет.
    pub exported_functions: Vec<bool>,
    /// Параллельно `module_vars`: переменная объявлена с модификатором
    /// `Экспорт` и адресуема из других модулей конфигурации.
    pub exported_module_vars: Vec<bool>,
    /// Типизированная таблица связей: символы чужих модулей, разрешённые
    /// при сборке конфигурации. На неё ссылаются `CallImported`,
    /// `GetImportedVar`/`SetImportedVar` и `ArgMode::ByRefImportedVar`
    /// своим `LinkSlot`. У одиночной программы пуста.
    pub links: Vec<crate::configuration::LinkEntry>,
    /// Точное окружение разрешённых импортов для динамических фрагментов.
    /// Сохраняется независимо от фактически использованных `links`.
    pub imports: Vec<crate::configuration::ModuleImport>,
    /// Таблица строк исходника: `lines[i][pc]` — номер строки, с которой
    /// начинается оператор, породивший инструкцию `pc` чанка `i`.
    ///
    /// Пустой внешний вектор — образ собран БЕЗ сведений об отладке, и это
    /// обычный случай: платить размером за то, чем пользуется один режим
    /// запуска, незачем. Непустой обязан иметь запись на каждый чанк, а
    /// непустая запись — на каждую его инструкцию; проверяет это
    /// `image::verify`.
    ///
    /// Живёт в `Program`, а НЕ в `Chunk`, намеренно: горячий цикл её не
    /// читает никогда — её спрашивают отладчик и листинг, оба вне
    /// исполнения, — а раскладка `Chunk` в этом проекте измеримо влияет на
    /// диспетчер (см. комментарии у `step_cold` в `bsl-vm`).
    ///
    /// Строки ФРАГМЕНТА `Выполнить`/`Вычислить` отсчитываются от начала
    /// его собственного текста, а не файла с вызовом.
    pub lines: Vec<Vec<u32>>,
}
