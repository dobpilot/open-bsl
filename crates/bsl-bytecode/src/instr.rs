/// Байт-код — `enum` в стиле Lua-VM, но без битовой упаковки: 2003-й год уже
/// прошёл, а исчерпывающий `match` при добавлении опкода того стоит.
///
/// `target` у `Jump`/`JumpIfFalse` — АБСОЛЮТНЫЙ индекс инструкции в чанке, не
/// относительное смещение: в M3 чанк не переиспользуется и не релоцируется,
/// поэтому усложнять патчинг под относительные прыжки незачем.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Instr {
    Move {
        dst: u8,
        src: u8,
    },
    /// Чтение переменной уровня модуля (`Перем` в начале файла). `slot` —
    /// АБСОЛЮТНЫЙ индекс в стеке значений, а не номер регистра кадра:
    /// модульные переменные занимают первые слоты кадра верхнего уровня, а
    /// он живёт всё исполнение и стоит в самом низу стека. Поэтому доступ
    /// из любой функции — прямая индексация без `reg_index`.
    GetModuleVar {
        dst: u8,
        slot: u16,
    },
    /// Запись туда же. Видна и телу модуля, и всем остальным функциям —
    /// ради этого вариант и существует отдельно от `Move`.
    SetModuleVar {
        slot: u16,
        src: u8,
    },
    LoadConst {
        dst: u8,
        k: u16,
    },
    LoadBool {
        dst: u8,
        val: bool,
    },
    LoadUndefined {
        dst: u8,
    },
    LoadNull {
        dst: u8,
    },
    Add {
        dst: u8,
        a: u8,
        b: u8,
    },
    Sub {
        dst: u8,
        a: u8,
        b: u8,
    },
    Mul {
        dst: u8,
        a: u8,
        b: u8,
    },
    Div {
        dst: u8,
        a: u8,
        b: u8,
    },
    /// Остаток от деления, знак — по ДЕЛИМОМУ (измерено).
    Mod {
        dst: u8,
        a: u8,
        b: u8,
    },
    Neg {
        dst: u8,
        src: u8,
    },

    Not {
        dst: u8,
        src: u8,
    },

    Eq {
        dst: u8,
        a: u8,
        b: u8,
    },
    NotEq {
        dst: u8,
        a: u8,
        b: u8,
    },
    Lt {
        dst: u8,
        a: u8,
        b: u8,
    },
    Gt {
        dst: u8,
        a: u8,
        b: u8,
    },
    Le {
        dst: u8,
        a: u8,
        b: u8,
    },
    Ge {
        dst: u8,
        a: u8,
        b: u8,
    },

    Jump {
        target: i16,
    },
    /// Условие обязано быть `Булево` — VM бросает ошибку типа, если нет
    /// (строгая булевость: `Если 1 Тогда` не приводится, а падает).
    JumpIfFalse {
        cond: u8,
        target: i16,
    },
    /// Симметрична `JumpIfFalse`: прыгает, когда `cond` — `Истина`. Нужна
    /// для короткого замыкания `ИЛИ` (см. `compiler.rs`) — та же строгая
    /// проверка на `Булево`, что и у `JumpIfFalse`.
    JumpIfTrue {
        cond: u8,
        target: i16,
    },
    /// Пролог параметров по умолчанию (см. `compiler.rs`, `compile_chunk`):
    /// прыгает, если аргумент для параметра `src` на месте вызова передали
    /// по-настоящему — тогда код, вычисляющий значение по умолчанию,
    /// пропускается. Падает через, если позицию пропустили (`Ф(1, , 3)`), и
    /// следующая инструкция(и) вычисляет значение по умолчанию прямо в
    /// слот этого параметра.
    ///
    /// `src` здесь — НОМЕР ПАРАМЕТРА, а не произвольный регистр (они
    /// совпадают: параметры занимают регистры `0..n_params`). Содержимое
    /// слота инструкция не читает вовсе: пропуск — свойство места вызова,
    /// и VM узнаёт о нём из метаданных кадра (`ArgMode::Default` в таблице
    /// режимов инструкции `Call`). Отдельного значения-маркера в
    /// `bsl_rt::BslValue` для этого нет — именно поэтому явно переданное
    /// `Неопределено` и пропуск позиции различимы.
    JumpIfNotSkipped {
        src: u8,
        target: i16,
    },
    /// Back-edge числового `Для`: инкремент, сравнение с границей и
    /// условный переход к началу тела выполняются за один dispatch.
    NumericForNext {
        counter: u8,
        bound: u8,
        target: i16,
    },
    /// Вариант для доказанно пустого тела. VM держит счётчик и границу как
    /// скрытые `i64` и материализует пользовательский регистр только при
    /// выходе. Для значений вне `i64` автоматически используется общий путь.
    NumericForNextI64 {
        counter: u8,
        bound: u8,
        target: i16,
    },

    /// `func` — индекс чанка в `Program::chunks` (0 зарезервирован под
    /// чанк верхнего уровня, поэтому `func` всегда `>= 1` для настоящего
    /// вызова). Аргументы вычислены заранее и лежат в регистрах
    /// `base..base+argc`, `argc` берётся из `arg_modes` (длина списка
    /// режимов), а не хранится отдельно — она и так равна числу параметров
    /// вызываемой функции. `arg_modes` — индекс в `Chunk::call_arg_modes`:
    /// вынесен в отдельную таблицу, а не в саму инструкцию, чтобы `Instr`
    /// оставался простым `Copy`-типом фиксированного размера даже при
    /// произвольном числе аргументов вызова.
    Call {
        func: u16,
        base: u8,
        arg_modes: u16,
        ret: u8,
    },
    /// `None` — неявный возврат (нет `Возврат` или он без выражения):
    /// значение результата — `Неопределено`.
    Return {
        src: Option<u8>,
    },

    GetIndex {
        dst: u8,
        obj: u8,
        idx: u8,
    },
    SetIndex {
        obj: u8,
        idx: u8,
        src: u8,
    },
    /// `name` — интернированное имя поля, индекс в `Program::names`.
    /// Инлайн-кэш здесь есть, но не в самой инструкции: `Chunk::prop_cache`
    /// держит по ячейке на каждую позицию байт-кода, и `get_field_cached`/
    /// `set_field_cached` в `bsl-rt` используют её как моно-/полиморфный
    /// guard через `Rc::ptr_eq` на форму (см. M10). `Instr` не расширен
    /// полем `cache: u16`, потому что кэш адресуется позицией инструкции в
    /// чанке, а не хранится в самом опкоде.
    ///
    /// Для `Структура` VM резолвит через `NameId` напрямую; для
    /// `СтрокаТаблицыЗначений` (колонки которой заведены в рантайме и не
    /// могли быть интернированы на этапе компиляции) VM сама разрешает
    /// `NameId` обратно в текст через `Program::names` и идёт по
    /// `get_field_by_name` — см. `bsl-vm`, инструкция об этом не знает.
    GetProp {
        dst: u8,
        obj: u8,
        name: bsl_rt::NameId,
    },
    SetProp {
        obj: u8,
        name: bsl_rt::NameId,
        src: u8,
    },

    /// `Новый Массив(d1, d2, ...)`: регистры `base..base+count` держат
    /// размеры измерений (числа), а не готовые элементы — VM строит
    /// вложенные массивы из них (`Новый Массив(3, 4)` — массив из 3
    /// массивов по 4).
    /// Универсальный конструктор runtime-компонента. Пространство кодов
    /// конструкторов независимо от пространства кодов функций.
    CreateObject {
        dst: u8,
        library: u8,
        constructor: u16,
        base: u8,
        count: u8,
    },
    NewArray {
        dst: u8,
        base: u8,
        count: u8,
    },
    /// `shape` — индекс в `Program::shapes` (форма интернирована на
    /// этапе компиляции по списку полей константной строки конструктора,
    /// см. `bsl-sema`). Регистры `base..base+count` — значения полей в
    /// порядке формы.
    NewStructure {
        dst: u8,
        shape: u16,
        base: u8,
        count: u8,
    },
    /// `Новый ТаблицаЗначений()` — колонки заводятся отдельно.
    NewTable {
        dst: u8,
    },
    NewTypeDescription {
        dst: u8,
        names: u8,
    },
    NewValueComparison {
        dst: u8,
    },
    /// `Новый Соответствие()` — пары заводятся отдельно, через `Вставить`.
    NewMap {
        dst: u8,
    },
    /// `Новый ЗаписьТекста(Путь)`: `path` содержит строковый путь, а `dst`
    /// получает созданный объект записи.
    NewTextWriter {
        dst: u8,
        path: u8,
    },
    /// Длина коллекции — используется компиляцией `Для Каждого` (индексный
    /// цикл поверх этой длины) и `Количество()`.
    CollectionLen {
        dst: u8,
        obj: u8,
    },

    /// `ВызватьИсключение <выражение>;`. `None` — голая форма (повторно
    /// бросить пойманное исключение); VM подставляет текущее пойманное
    /// значение, а не какое-то конкретное здесь — решается в рантайме, не
    /// в компиляторе, потому что это зависит от того, что поймано ВЫШЕ по
    /// стеку кадров, а не от места, где стоит `ВызватьИсключение`.
    Raise {
        src: Option<u8>,
    },

    /// Встроенная функция (`Sqrt`, `Pow`, `Message`, ...) — всегда по
    /// значению, аргументы в регистрах `base..base+count`.
    CallBuiltin {
        dst: u8,
        builtin: bsl_rt::BuiltinFn,
        base: u8,
        count: u8,
    },
    /// Глобальная функция runtime-компонента. `library` — локальный индекс
    /// в `Program::requirements`, `function` — стабильный код внутри
    /// указанного пакета.
    CallComponent {
        dst: u8,
        library: u8,
        function: u16,
        base: u8,
        count: u8,
    },
    /// Быстрый путь методов стандартного рантайма.
    CallMethod {
        dst: u8,
        obj: u8,
        method: bsl_rt::BuiltinMethod,
        base: u8,
        count: u8,
    },
    /// `Выполнить(<строка в src>)` (`is_eval = false`, `dst` не используется
    /// осмысленно — результат всегда `Неопределено`) или
    /// `Вычислить(<строка в src>)` (`is_eval = true`, `dst` получает
    /// значение). Один и тот же движок для обоих — как и написано в
    /// брифе — компилирует строку в чанк и исполняет её ИЗОЛИРОВАННО
    /// (см. `bsl-vm::run_dynamic_snippet`): только верхний уровень,
    /// новые имена, объявленные во фрагменте, не переживают вызов —
    /// материализованный кадр с растущей таблицей имён (как в брифе)
    /// для процедур/функций пока не сделан, это дальнейшая работа.
    RunDynamic {
        src: u8,
        dst: u8,
        is_eval: bool,
    },
    /// Открытый вызов метода по имени. Новый компонент может добавить
    /// такое имя без изменения VM и формата операндов. Вариант находится в
    /// конце `Instr`, чтобы не сдвигать внутренние теги измеренных опкодов.
    CallObjectMethod {
        dst: u8,
        obj: u8,
        method: u16,
        base: u8,
        count: u8,
    },
    /// Чтение свойства в режиме открытого объектного протокола.
    GetObjectProp {
        dst: u8,
        obj: u8,
        name: u16,
    },
    /// Запись свойства в режиме открытого объектного протокола.
    SetObjectProp {
        obj: u8,
        name: u16,
        src: u8,
    },
}

/// Режим передачи одного аргумента вызова — статическое свойство и
/// параметра вызываемой функции (`Знач`/по умолчанию), и формы выражения
/// на месте вызова (голая переменная или нет), поэтому решается целиком на
/// этапе компиляции и хранится по одному списку на каждую инструкцию
/// `Call` в `Chunk::call_arg_modes`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ArgMode {
    /// Значение уже посчитано и лежит в регистре `base + i` вызывающего.
    Value,
    /// Параметр без `Знач`, а аргумент на месте вызова — голая переменная:
    /// VM алиасит слот параметра прямо на слот `slot` вызывающего (по
    /// стековому индексу, не по указателю — см. `bsl-vm`), регистр
    /// `base + i` при этом не используется.
    ByRefLocal(u8),
    /// Параметр без `Знач`, а аргумент — МОДУЛЬНАЯ переменная: VM алиасит
    /// слот параметра на абсолютный стековый индекс `module_base + slot`,
    /// а не на регистр кадра вызывающего. ИЗМЕРЕНО (`CALL.BYREF.MODULEVAR`),
    /// что 8.3.27 передаёт модульную переменную по ссылке и из тела модуля,
    /// и изнутри процедуры — `изменено|изменено`; без этого варианта
    /// `RExpr::ModuleVar` уходил бы копией (`ArgMode::Value`) и второй случай
    /// расходился с платформой. Ширина `u16`: модульные слоты адресуются
    /// шестнадцатью битами (`GetModuleVar`/`SetModuleVar`).
    ByRefModuleVar(u16),
    /// Позицию пропустили (`Ф(1, , 3)`) там, где у параметра объявлено
    /// значение по умолчанию. Вызывающий в регистр `base + i` ничего не
    /// вычисляет — его заполнит пролог умолчаний вызванной функции, а
    /// узнает он о пропуске по этому режиму (см. `JumpIfNotSkipped`).
    Default,
}

impl Instr {
    /// Цель перехода, если инструкция её несёт.
    ///
    /// ЕДИНСТВЕННОЕ место, где перечислены опкоды с полем `target`. Копия
    /// этого списка однажды уже разошлась: разбор текстового байт-кода
    /// проверял четыре опкода из шести и пропускал оба цикловых, а VM
    /// преобразует их цель тем же `as usize`, поэтому испорченный листинг
    /// завершал программу молча. Добавляя опкод с целью, дописывать надо
    /// здесь — и `bundle::leaders`, и проверка при разборе увидят его сами.
    #[must_use]
    pub fn jump_target(&self) -> Option<i16> {
        match self {
            Instr::Jump { target }
            | Instr::JumpIfFalse { target, .. }
            | Instr::JumpIfTrue { target, .. }
            | Instr::JumpIfNotSkipped { target, .. }
            | Instr::NumericForNext { target, .. }
            | Instr::NumericForNextI64 { target, .. } => Some(*target),
            _ => None,
        }
    }

    /// Обращается ли инструкция к ОБЪЕКТУ: шесть опкодов, у которых
    /// обработчик компонента получает `CallContext`.
    ///
    /// На эту классификацию опирается КОНТРАКТ JIT-шимов: открытые объектные
    /// опкоды (`GetObjectProp`/`SetObjectProp`/`CallObjectMethod`) шимятся
    /// через НАТИВНЫЙ `CallContext` без вывода и зоны, и это безопасно ровно
    /// потому, что методы и свойства объектов в stdout не пишут. `compile_instr`
    /// в `bsl-vm/src/jit` держит `debug_assert!(instr.touches_objects())` на
    /// эмиссии такого шима: нативный шим не-объектного опкода уронил бы
    /// отладочную сборку, а не проглотил бы его вывод молча.
    ///
    /// Классификация принадлежит самой инструкции, а не тому, кто её
    /// выпустил: спрашивают её двое — кодоген, заполняя
    /// `Chunk::touches_objects`, и разбор листинга, восстанавливая то же
    /// поле по прочитанным инструкциям. Ответы обязаны совпадать, иначе
    /// разобранная программа пошла бы мимо того пути исполнения, по
    /// которому шла скомпилированная.
    #[must_use]
    pub fn touches_objects(&self) -> bool {
        matches!(
            self,
            Instr::GetProp { .. }
                | Instr::SetProp { .. }
                | Instr::CallMethod { .. }
                | Instr::GetObjectProp { .. }
                | Instr::SetObjectProp { .. }
                | Instr::CallObjectMethod { .. }
        )
    }
}

#[cfg(test)]
mod tests {
    use super::Instr;

    #[test]
    fn instruction_stays_eight_bytes() {
        assert_eq!(std::mem::size_of::<Instr>(), 8);
    }

    /// Классификация всех ШЕСТИ объектных опкодов: от неё зависит, уйдёт
    /// ли чанк мимо нативного пути, а исполнением она не проверяется —
    /// потеря любой строки оставила бы embedding-тесты зелёными.
    #[test]
    fn every_object_opcode_is_classified_as_touching_objects() {
        let object = [
            Instr::GetProp {
                dst: 0,
                obj: 1,
                name: bsl_rt::NameId::from_index(0),
            },
            Instr::SetProp {
                obj: 0,
                name: bsl_rt::NameId::from_index(0),
                src: 1,
            },
            Instr::CallMethod {
                dst: 0,
                obj: 1,
                method: bsl_rt::BuiltinMethod::Add,
                base: 2,
                count: 0,
            },
            Instr::GetObjectProp {
                dst: 0,
                obj: 1,
                name: 0,
            },
            Instr::SetObjectProp {
                obj: 0,
                name: 0,
                src: 1,
            },
            Instr::CallObjectMethod {
                dst: 0,
                obj: 1,
                method: 0,
                base: 2,
                count: 0,
            },
        ];
        for instr in &object {
            assert!(
                instr.touches_objects(),
                "опкод не опознан как обращение к объекту: {instr:?}"
            );
        }
        // А соседние по смыслу — нет: индексация и поле структуры идут
        // мимо компонентного ABI.
        for instr in [
            Instr::GetIndex {
                dst: 0,
                obj: 1,
                idx: 2,
            },
            Instr::Move { dst: 0, src: 1 },
            Instr::LoadUndefined { dst: 0 },
        ] {
            assert!(
                !instr.touches_objects(),
                "лишний опкод причислен к обращениям: {instr:?}"
            );
        }
    }
}
