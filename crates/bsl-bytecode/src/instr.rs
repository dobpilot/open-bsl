/// Байт-код — `enum` в стиле Lua-VM, но без битовой упаковки: 2003-й год уже
/// прошёл, а исчерпывающий `match` при добавлении опкода того стоит.
///
/// `target` у `Jump`/`JumpIfFalse` — АБСОЛЮТНЫЙ индекс инструкции в чанке, не
/// относительное смещение: в M3 чанк не переиспользуется и не релоцируется,
/// поэтому усложнять патчинг под относительные прыжки незачем.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Instr {
    Move {
        dst: u8,
        src: u8,
    },
    /// Чтение переменной уровня модуля (`Перем` в начале файла). `slot` —
    /// АБСОЛЮТНЫЙ индекс в стеке значений, а не номер регистра кадра:
    /// модульные переменные занимают первые слоты кадра верхнего уровня, а
    /// он живёт всё исполнение и стоит в самом низу стека. Поэтому доступ
    /// из любой функции — прямая индексация без `reg_index`.
    GetModuleVar {
        dst: u8,
        slot: u16,
    },
    /// Запись туда же. Видна и телу модуля, и всем остальным функциям —
    /// ради этого вариант и существует отдельно от `Move`.
    SetModuleVar {
        slot: u16,
        src: u8,
    },
    LoadConst {
        dst: u8,
        k: u16,
    },
    LoadBool {
        dst: u8,
        val: bool,
    },
    LoadUndefined {
        dst: u8,
    },
    LoadNull {
        dst: u8,
    },
    /// Пропущенный аргумент вызова (`Ф(1, , 3)`) на месте параметра со
    /// значением по умолчанию — см. `bsl_rt::BslValue::Skipped` и
    /// `JumpIfNotSkipped` ниже.
    LoadSkipped {
        dst: u8,
    },

    Add {
        dst: u8,
        a: u8,
        b: u8,
    },
    Sub {
        dst: u8,
        a: u8,
        b: u8,
    },
    Mul {
        dst: u8,
        a: u8,
        b: u8,
    },
    Div {
        dst: u8,
        a: u8,
        b: u8,
    },
    /// Остаток от деления, знак — по ДЕЛИМОМУ (измерено).
    Mod {
        dst: u8,
        a: u8,
        b: u8,
    },
    Neg {
        dst: u8,
        src: u8,
    },

    Not {
        dst: u8,
        src: u8,
    },

    Eq {
        dst: u8,
        a: u8,
        b: u8,
    },
    NotEq {
        dst: u8,
        a: u8,
        b: u8,
    },
    Lt {
        dst: u8,
        a: u8,
        b: u8,
    },
    Gt {
        dst: u8,
        a: u8,
        b: u8,
    },
    Le {
        dst: u8,
        a: u8,
        b: u8,
    },
    Ge {
        dst: u8,
        a: u8,
        b: u8,
    },

    Jump {
        target: i16,
    },
    /// Условие обязано быть `Булево` — VM бросает ошибку типа, если нет
    /// (строгая булевость: `Если 1 Тогда` не приводится, а падает).
    JumpIfFalse {
        cond: u8,
        target: i16,
    },
    /// Симметрична `JumpIfFalse`: прыгает, когда `cond` — `Истина`. Нужна
    /// для короткого замыкания `ИЛИ` (см. `compiler.rs`) — та же строгая
    /// проверка на `Булево`, что и у `JumpIfFalse`.
    JumpIfTrue {
        cond: u8,
        target: i16,
    },
    /// Пролог параметров по умолчанию (см. `compiler.rs`, `compile_chunk`):
    /// прыгает, если `src` НЕ `BslValue::Skipped` (аргумент был передан по-
    /// настоящему — пропускаем код, вычисляющий значение по умолчанию).
    /// Падает через, если `src` — Skipped, и следующая инструкция(и)
    /// вычисляет значение по умолчанию прямо в тот же регистр.
    JumpIfNotSkipped {
        src: u8,
        target: i16,
    },
    /// Back-edge числового `Для`: инкремент, сравнение с границей и
    /// условный переход к началу тела выполняются за один dispatch.
    NumericForNext {
        counter: u8,
        bound: u8,
        target: i16,
    },
    /// Вариант для доказанно пустого тела. VM держит счётчик и границу как
    /// скрытые `i64` и материализует пользовательский регистр только при
    /// выходе. Для значений вне `i64` автоматически используется общий путь.
    NumericForNextI64 {
        counter: u8,
        bound: u8,
        target: i16,
    },

    /// `func` — индекс чанка в `Program::chunks` (0 зарезервирован под
    /// чанк верхнего уровня, поэтому `func` всегда `>= 1` для настоящего
    /// вызова). Аргументы вычислены заранее и лежат в регистрах
    /// `base..base+argc`, `argc` берётся из `arg_modes` (длина списка
    /// режимов), а не хранится отдельно — она и так равна числу параметров
    /// вызываемой функции. `arg_modes` — индекс в `Chunk::call_arg_modes`:
    /// вынесен в отдельную таблицу, а не в саму инструкцию, чтобы `Instr`
    /// оставался простым `Copy`-типом фиксированного размера даже при
    /// произвольном числе аргументов вызова.
    Call {
        func: u16,
        base: u8,
        arg_modes: u16,
        ret: u8,
    },
    /// `None` — неявный возврат (нет `Возврат` или он без выражения):
    /// значение результата — `Неопределено`.
    Return {
        src: Option<u8>,
    },

    GetIndex {
        dst: u8,
        obj: u8,
        idx: u8,
    },
    SetIndex {
        obj: u8,
        idx: u8,
        src: u8,
    },
    /// `name` — интернированное имя поля, индекс в `Program::names`.
    /// Инлайн-кэш здесь есть, но не в самой инструкции: `Chunk::prop_cache`
    /// держит по ячейке на каждую позицию байт-кода, и `get_field_cached`/
    /// `set_field_cached` в `bsl-rt` используют её как моно-/полиморфный
    /// guard через `Rc::ptr_eq` на форму (см. M10). `Instr` не расширен
    /// полем `cache: u16`, потому что кэш адресуется позицией инструкции в
    /// чанке, а не хранится в самом опкоде.
    ///
    /// Для `Структура` VM резолвит через `NameId` напрямую; для
    /// `СтрокаТаблицыЗначений` (колонки которой заведены в рантайме и не
    /// могли быть интернированы на этапе компиляции) VM сама разрешает
    /// `NameId` обратно в текст через `Program::names` и идёт по
    /// `get_field_by_name` — см. `bsl-vm`, инструкция об этом не знает.
    GetProp {
        dst: u8,
        obj: u8,
        name: bsl_rt::NameId,
    },
    SetProp {
        obj: u8,
        name: bsl_rt::NameId,
        src: u8,
    },

    /// `Новый Массив(d1, d2, ...)`: регистры `base..base+count` держат
    /// размеры измерений (числа), а не готовые элементы — VM строит
    /// вложенные массивы из них (`Новый Массив(3, 4)` — массив из 3
    /// массивов по 4).
    NewArray {
        dst: u8,
        base: u8,
        count: u8,
    },
    /// `shape` — индекс в `Program::shapes` (форма интернирована на
    /// этапе компиляции по списку полей константной строки конструктора,
    /// см. `bsl-sema`). Регистры `base..base+count` — значения полей в
    /// порядке формы.
    NewStructure {
        dst: u8,
        shape: u16,
        base: u8,
        count: u8,
    },
    /// `Новый ТаблицаЗначений()` — колонки заводятся отдельно.
    NewTable {
        dst: u8,
    },
    NewTypeDescription {
        dst: u8,
        names: u8,
    },
    NewValueComparison {
        dst: u8,
    },
    /// `Новый Соответствие()` — пары заводятся отдельно, через `Вставить`.
    NewMap {
        dst: u8,
    },
    /// `Новый ЗаписьТекста(Путь)`: `path` содержит строковый путь, а `dst`
    /// получает созданный объект записи.
    NewTextWriter {
        dst: u8,
        path: u8,
    },
    /// `Новый ДвоичныеДанные(ИмяФайла)`: `path` содержит строковый путь,
    /// `dst` — прочитанные из файла данные. Файл читается ЦЕЛИКОМ прямо
    /// здесь, поэтому инструкция, как и `NewTextWriter`, имеет побочный
    /// эффект ввода-вывода (см. `bundle.rs`).
    NewBinaryData {
        dst: u8,
        path: u8,
    },
    /// `Новый БуферДвоичныхДанных(Размер[, ПорядокБайтов])`. Пропущенный
    /// порядок приходит регистром со значением `Неопределено` — так же, как
    /// хвостовые позиции `NewJsonWriterSettings`. Ввода-вывода тут нет:
    /// буфер целиком в памяти.
    NewBinaryBuffer {
        dst: u8,
        size: u8,
        order: u8,
    },
    /// `Новый ПотокВПамяти([ЁмкостьЛибоБуфер])`. Пропущенный аргумент
    /// приходит регистром со значением `Неопределено`, как у
    /// `NewBinaryBuffer`. Ввода-вывода здесь нет: поток целиком в памяти,
    /// даже когда он заведён НАД буфером (носителем становится та же
    /// память, что у буфера, — новых байтов не выделяется).
    NewMemoryStream {
        dst: u8,
        arg: u8,
    },
    /// `Новый УникальныйИдентификатор([Строка])`. Пропущенный аргумент
    /// приходит регистром со значением `Неопределено` — тогда порождается
    /// случайный идентификатор из системного источника (см. `bsl-rt`,
    /// модуль `uuid`); строка разбирается канонической формой.
    NewUuid {
        dst: u8,
        arg: u8,
    },
    /// `Новый ФайловыйПоток(Имя, Режим[, Доступ])`. Пропущенный доступ —
    /// снова регистр с `Неопределено`. Конструктор ОТКРЫВАЕТ файл (и, в
    /// зависимости от режима, создаёт или обрезает его), поэтому порядок
    /// относительно другого ввода-вывода наблюдаем — см. `bundle.rs`.
    NewFileStream {
        dst: u8,
        path: u8,
        mode: u8,
        access: u8,
    },
    /// `Новый ЧтениеДанных(Источник[, Кодировка][, ПорядокБайтов][, Разделитель])`
    /// и парный `Новый ЗаписьДанных(...)`. Пропущенные хвостовые аргументы —
    /// регистры с `Неопределено`, как у `NewFileStream`.
    ///
    /// Ввод-вывод у обоих ЕСТЬ: источником может оказаться имя файла, и тогда
    /// конструктор его открывает, а у писателя ещё и создаёт, если файла нет
    /// (существующий писатель НЕ обрезает — измерено). Даже над потоком в
    /// памяти порядок наблюдаем: конструктор запоминает текущую позицию
    /// целевого потока, и всё дальнейшее чтение и запись сверяются с ней
    /// (см. `bsl-rt::datarw`).
    NewDataReader {
        dst: u8,
        source: u8,
        encoding: u8,
        order: u8,
        separator: u8,
    },
    NewDataWriter {
        dst: u8,
        source: u8,
        encoding: u8,
        order: u8,
        separator: u8,
    },
    /// Голое имя `ФайловыеПотоки`. Отдельная инструкция, а не константа в
    /// таблице чанка, потому что каждое обращение обязано дать НОВЫЙ
    /// объект: `ФайловыеПотоки = ФайловыеПотоки` платформа считает ложью
    /// (измерено), а `LoadConst` отдавал бы один и тот же `Rc`.
    NewFileStreamsManager {
        dst: u8,
    },
    /// `Новый ЧтениеJSON` / `Новый ЗаписьJSON` — аргументов у обоих нет:
    /// источник и приёмник назначаются отдельным вызовом
    /// (`УстановитьСтроку`/`ОткрытьФайл`), ровно как в платформе.
    NewJsonReader {
        dst: u8,
    },
    NewJsonWriter {
        dst: u8,
    },
    /// `Новый ПараметрыЗаписиJSON([ПереносСтрок][, СимволыОтступа])`.
    /// Пропущенные позиции приходят регистрами со значением
    /// `Неопределено` — резолвер добивает их так же, как хвостовые
    /// аргументы встроенных функций.
    NewJsonWriterSettings {
        dst: u8,
        line_break: u8,
        indent: u8,
    },
    /// `Новый НастройкиСериализацииJSON` — без аргументов: все три
    /// свойства выставляются отдельными `SetProp` уже после создания.
    NewJsonSerializerSettings {
        dst: u8,
    },
    /// `Новый ЧтениеXML` / `Новый ЗаписьXML` — как и у JSON, без
    /// аргументов: источник и приёмник назначаются отдельным вызовом.
    /// `Новый ТекстовыйДокумент` — без аргументов.
    NewTextDocument {
        dst: u8,
    },
    NewSpreadDocument {
        dst: u8,
    },
    NewXmlReader {
        dst: u8,
    },
    NewXmlWriter {
        dst: u8,
    },
    /// `Новый ПостроительDOM` — без аргументов: дерево строит `Прочитать`,
    /// которому и передают `ЧтениеXML`.
    NewDomBuilder {
        dst: u8,
    },
    /// `Новый ДокументDOM` — пустой документ; аргументов у него нет.
    NewDomDocument {
        dst: u8,
    },
    /// `Новый ЗаписьDOM` — сериализатор дерева; аргументов нет, узел и
    /// приёмник приходят в `Записать`.
    NewDomWriter {
        dst: u8,
    },
    /// `Новый ПостроительСхемXML` — без аргументов: схему строит
    /// `СоздатьСхемуXML` из переданного дерева.
    NewXsBuilder {
        dst: u8,
    },
    /// `Новый СхемаXML` — пустая схема; аргументов у неё нет.
    NewXmlSchema {
        dst: u8,
    },
    /// `Новый НаборСхемXML` — пустой набор; аргументов нет.
    NewXmlSchemaSet {
        dst: u8,
    },
    /// `Новый ФабрикаXDTO([НаборСхемXML])` — модель типов по набору схем.
    /// Пропущенный аргумент приходит регистром со значением
    /// `Неопределено`, как у `NewJsonWriterSettings`: фабрика без набора —
    /// это фабрика с одними встроенными типами XML Schema, а не ошибка
    /// (измерено).
    NewXdtoFactory {
        dst: u8,
        schemas: u8,
    },
    /// `Новый СериализаторXDTO(ФабрикаXDTO)` — перевод значений BSL в XML
    /// через модель типов фабрики. Аргумент обязателен, поэтому регистр
    /// `factory` всегда несёт настоящее значение, а не подставленное
    /// `Неопределено`, как `schemas` у соседа.
    NewXdtoSerializer {
        dst: u8,
        factory: u8,
    },
    /// `Новый РазыменовательПространствИменDOM(Узел)` — разыменователь
    /// пространств имён для XPath, показывающий область видимости узла.
    NewDomNsResolver {
        dst: u8,
        node: u8,
    },
    /// `Новый РасширенноеИмяXML(URI, ЛокальноеИмя)`.
    NewXmlExpandedName {
        dst: u8,
        uri: u8,
        local: u8,
    },
    /// `Новый ПараметрыЗаписиXML([Кодировка][, Версия][, ИспользоватьОтступ])`.
    NewXmlWriterSettings {
        dst: u8,
        encoding: u8,
        version: u8,
        indent: u8,
    },
    /// Длина коллекции — используется компиляцией `Для Каждого` (индексный
    /// цикл поверх этой длины) и `Количество()`.
    CollectionLen {
        dst: u8,
        obj: u8,
    },

    /// `ВызватьИсключение <выражение>;`. `None` — голая форма (повторно
    /// бросить пойманное исключение); VM подставляет текущее пойманное
    /// значение, а не какое-то конкретное здесь — решается в рантайме, не
    /// в компиляторе, потому что это зависит от того, что поймано ВЫШЕ по
    /// стеку кадров, а не от места, где стоит `ВызватьИсключение`.
    Raise {
        src: Option<u8>,
    },

    /// Встроенная функция (`Sqrt`, `Pow`, `Message`, ...) — всегда по
    /// значению, аргументы в регистрах `base..base+count`.
    CallBuiltin {
        dst: u8,
        builtin: bsl_rt::BuiltinFn,
        base: u8,
        count: u8,
    },
    /// `obj.Метод(args)` — аргументы (если есть) в регистрах
    /// `base..base+count`, как у `CallBuiltin`. Арность части методов
    /// (`Добавить`) зависит от типа получателя и проверяется в рантайме,
    /// не здесь — см. `bsl_rt::BuiltinMethod`.
    CallMethod {
        dst: u8,
        obj: u8,
        method: bsl_rt::BuiltinMethod,
        base: u8,
        count: u8,
    },
    /// Горячий путь `ЗаписьТекста.Записать(строка)`: без упаковки
    /// аргумента в `Vec` и общей диспетчеризации методов.
    WriteText {
        dst: u8,
        obj: u8,
        src: u8,
    },
    /// Горячий путь `ЗаписьТекста.Закрыть()`.
    CloseText {
        dst: u8,
        obj: u8,
    },

    /// `Выполнить(<строка в src>)` (`is_eval = false`, `dst` не используется
    /// осмысленно — результат всегда `Неопределено`) или
    /// `Вычислить(<строка в src>)` (`is_eval = true`, `dst` получает
    /// значение). Один и тот же движок для обоих — как и написано в
    /// брифе — компилирует строку в чанк и исполняет её ИЗОЛИРОВАННО
    /// (см. `bsl-vm::run_dynamic_snippet`): только верхний уровень,
    /// новые имена, объявленные во фрагменте, не переживают вызов —
    /// материализованный кадр с растущей таблицей имён (как в брифе)
    /// для процедур/функций пока не сделан, это дальнейшая работа.
    RunDynamic {
        src: u8,
        dst: u8,
        is_eval: bool,
    },
}

/// Режим передачи одного аргумента вызова — статическое свойство и
/// параметра вызываемой функции (`Знач`/по умолчанию), и формы выражения
/// на месте вызова (голая переменная или нет), поэтому решается целиком на
/// этапе компиляции и хранится по одному списку на каждую инструкцию
/// `Call` в `Chunk::call_arg_modes`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ArgMode {
    /// Значение уже посчитано и лежит в регистре `base + i` вызывающего.
    Value,
    /// Параметр без `Знач`, а аргумент на месте вызова — голая переменная:
    /// VM алиасит слот параметра прямо на слот `slot` вызывающего (по
    /// стековому индексу, не по указателю — см. `bsl-vm`), регистр
    /// `base + i` при этом не используется.
    ByRefLocal(u8),
}
