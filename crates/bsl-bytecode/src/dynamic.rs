//! Контракт динамического кода: что VM спрашивает у хоста, когда встречает
//! `Выполнить`/`Вычислить`, и что хост ей на это отдаёт.
//!
//! Граница здесь ровно одна и она узкая: VM умеет исполнять байт-код и
//! больше ничего — лексикой, разбором, резолвингом и кодогеном фрагмента
//! занимается хост, у которого для этого и так есть весь фронтенд. VM
//! отдаёт [`DynamicRequest`] — устойчивое описание контекста компиляции, в
//! котором нет ни кадра, ни стека, ни связанных компонентов, — и получает
//! [`DynamicUnit`], готовый к исполнению.
//!
//! Здесь только сам контракт — его знают обе стороны, поэтому он и лежит в
//! общем для них крейте. Фронтенд не знает ни та ни другая: разбором и
//! кодогеном фрагмента занимается `bsl_compiler::compile_dynamic_snippet`,
//! а реализация [`DynamicCompiler`] поверх него — фасад `open-bsl`. Кэш
//! скомпилированных фрагментов принадлежит хосту, а не этому модулю и не
//! VM.

use std::num::NonZeroU64;
use std::rc::Rc;

use crate::{Chunk, LibraryRequirement};

/// Что именно исполняется: оператор `Выполнить` или выражение `Вычислить`.
///
/// Разница целиком компиляционная — выражение заворачивается в
/// `Возврат (...)`, чтобы значение возвращалось тем же путём, что и у
/// обычного `Возврат`, — поэтому вид операции переезжает к хосту вместе с
/// остальной компиляцией.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum DynamicKind {
    /// `Выполнить(...)` — операторы.
    Execute,
    /// `Вычислить(...)` — выражение, значение которого возвращается.
    Eval,
}

/// Опознаватель области видимости фрагмента — ключ кэша на стороне хоста.
///
/// Один и тот же текст, исполненный в разных областях, резолвится в РАЗНЫЕ
/// номера слотов, и переиспользовать чанк между ними нельзя. Одного номера
/// чанка для этого мало: чанк с номером 0 есть и у исходного модуля, и у
/// каждого фрагмента, изнутри которого исполняется вложенный `Выполнить`, а
/// таблицы локальных у них разные. Поэтому в ключ входит ещё и то, ЧЕЙ это
/// нулевой чанк.
///
/// Идентичность здесь целиком ХОСТОВА: [`ROOT`](DynamicScope::ROOT) — это
/// сам исполняемый модуль, а всё остальное — номера, которые хост роздал
/// выпущенным им фрагментам ([`DynamicUnit::scope`]). Ни счётчика, ни иного
/// ambient state у байт-кода нет: он переносит номер, но не выдаёт его.
/// Именно поэтому повторный запуск одного модуля даёт ТЕ ЖЕ ключи и
/// пользуется уже скомпилированным, а не копит записи.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub struct DynamicScope {
    /// Чей это чанк: `ROOT` — исполняемого модуля, иначе — фрагмента с
    /// таким [`DynamicUnit::scope`].
    pub program: u64,
    /// Номер чанка внутри него.
    pub chunk: u32,
}

impl DynamicScope {
    /// Область самого исполняемого модуля: его собственные чанки и все
    /// чанки его процедур и функций.
    ///
    /// Функции при исполнении фрагмента едут в него КАК ЕСТЬ (меняется
    /// только нулевой чанк), поэтому их области остаются корневыми на любой
    /// глубине вложенности — и `Выполнить` внутри процедуры компилируется
    /// один раз, из какого бы фрагмента её ни позвали.
    pub const ROOT: u64 = 0;
}

/// Сигнатура процедуры или функции окружающего модуля глазами фрагмента.
///
/// Всё заимствовано у программы: запрос собирается на КАЖДОМ `RunDynamic`,
/// в том числе когда фрагмент уже лежит в кэше хоста, и платить за клоны
/// имён на попадании незачем.
pub struct DynamicSignature<'a> {
    pub name: &'a str,
    pub arity: usize,
    /// Процедуру фрагмент обязан отвергнуть в позиции выражения так же,
    /// как это делает статический резолвер.
    pub is_procedure: bool,
    /// Объявлен ли вызываемый метод с модификатором `Асинх`.
    pub is_async: bool,
    /// Режимы параметров: компилятору фрагмента надо знать, какой аргумент
    /// идёт по ссылке.
    pub param_by_val: &'a [bool],
    /// Есть ли у каждого параметра умолчание: без этого фрагмент не отличит
    /// опущенный хвостовой необязательный аргумент от пропущенного
    /// обязательного (воспроизведение 4).
    pub param_has_default: &'a [bool],
}

/// Контекст компиляции одного фрагмента — всё, что хосту нужно знать о
/// программе вокруг, и ничего сверх того.
///
/// Здесь нет ни `Program`, ни кадра, ни стека: фрагмент компилируется по
/// ИМЕНАМ и таблицам, а значения переменных VM переносит сама, уже после
/// того как получила артефакт.
pub struct DynamicRequest<'a> {
    /// Текст фрагмента как его увидел `Выполнить`/`Вычислить`.
    pub source: &'a str,
    /// Собирать ли фрагмент со сведениями об отладке. Берётся у ОБЪЕМЛЮЩЕЙ
    /// программы: отлаживают либо всё, либо ничего, и отдельного ключа у
    /// фрагмента быть не должно.
    pub debug_info: bool,
    pub kind: DynamicKind,
    pub scope: DynamicScope,
    /// Разрешён ли `Ждать` в текущем кадре.
    pub caller_is_async: bool,
    /// Имена локальных переменных текущего кадра В ПОРЯДКЕ СЛОТОВ:
    /// фрагмент резолвится поверх них, и раскладка обязана совпасть.
    pub locals: &'a [String],
    pub module_vars: &'a [String],
    /// Функции и процедуры модуля в порядке `Program::chunks[1..]`.
    pub functions: &'a [DynamicSignature<'a>],
    /// Таблица имён основной программы: интернер фрагмента засевается ею,
    /// чтобы уже существующие `NameId` сохранили значение.
    pub names: &'a [String],
    /// Требования основной программы: замыкание фрагмента объединяется с
    /// ними, а не заменяет их.
    pub requirements: &'a [LibraryRequirement],
}

/// Скомпилированный фрагмент.
///
/// `names` и `shapes` — СОБСТВЕННЫЕ таблицы фрагмента, а не таблицы
/// основной программы: индексы форм внутри `chunk` ссылаются именно на
/// них, а таблица имён — это таблица программы плюс имена полей, которых в
/// статическом коде не было вовсе. Старые `NameId` при этом сохраняются:
/// таблица фрагмента начинается тем же префиксом.
///
/// `requirements` — уже ОБЪЕДИНЁННЫЙ список: требования программы плюс то,
/// что затребовал сам фрагмент.
pub struct DynamicUnit {
    /// Номер, под которым область ЭТОГО фрагмента известна хосту: его
    /// нулевой чанк — уже не чанк модуля, и вложенный `Выполнить` внутри
    /// него обязан получить свой ключ кэша. Номер выдаёт хост (он же
    /// владеет кэшем и знает, сколько тот живёт), а VM только возвращает
    /// его назад в [`DynamicScope::program`] — так идентичность прогона не
    /// протекает ни в байт-код, ни в VM.
    ///
    /// Тип — [`NonZeroU64`], потому что номер, равный [`DynamicScope::ROOT`]
    /// (нулю), молча подсунул бы вложенному `Выполнить` чужой чанк с чужой
    /// раскладкой слотов: реализации трейта достаточно было вернуть `0`.
    /// Тип делает непредставимым ИМЕННО этот случай — и только его.
    /// Одинаковость номера у одного и того же фрагмента при каждом
    /// исполнении и его РАЗЛИЧИЕ у разных фрагментов тип НЕ проверяет: это
    /// обязанность реализации (см. [`DynamicCompiler`]).
    pub scope: NonZeroU64,
    pub chunk: Chunk,
    pub names: Vec<String>,
    pub shapes: Vec<Rc<bsl_rt::Shape>>,
    pub requirements: Vec<LibraryRequirement>,
    /// Строка на каждую инструкцию чанка фрагмента, если объемлющая
    /// программа собрана со сведениями об отладке; иначе пусто.
    ///
    /// Строки — в координатах СОБСТВЕННОГО текста фрагмента. Наложить их
    /// на файл с вызовом нельзя: он открылся бы не на том месте.
    pub lines: Vec<u32>,
}

/// Компилятор динамического кода на стороне хоста.
///
/// VM зовёт его на каждом `Выполнить`/`Вычислить` и сама ничего не
/// кэширует: кэш — обязанность реализации, потому что только она знает,
/// сколько живёт сессия.
pub trait DynamicCompiler {
    /// Компилирует фрагмент, описанный запросом.
    ///
    /// Каждому фрагменту реализация обязана выдать в [`DynamicUnit::scope`]
    /// номер, УНИКАЛЬНЫЙ среди живущих фрагментов и одинаковый у одного и
    /// того же фрагмента при каждом исполнении. Тип ([`NonZeroU64`])
    /// исключает лишь совпадение с корнем; повтор одного НЕнулевого номера у
    /// разных фрагментов он не ловит, и вложенный `Выполнить` тогда попал бы
    /// мимо кэша в чужой чанк. Гарантия уникальности — на реализации.
    ///
    /// # Errors
    ///
    /// Текст ошибки лексики, разбора, резолвинга или кодогена. Тип
    /// намеренно узкий: неудача компиляции фрагмента — это ВСЕГДА
    /// динамическая ошибка исполнения, ловимая `Попытка`, и решать это за
    /// VM хост не вправе.
    fn compile(&mut self, request: &DynamicRequest<'_>) -> Result<Rc<DynamicUnit>, String>;
}
