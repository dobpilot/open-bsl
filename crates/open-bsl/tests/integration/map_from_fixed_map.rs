use open_bsl::{Engine, Value};

#[test]
fn mutable_map_keeps_fixed_source_order_and_survives_independent_mutation() {
    let engine = Engine::builder().build().unwrap();
    let result = engine
        .new_state()
        .exec(
            r#"
            Источник = Новый Соответствие;
            Источник.Вставить("Третий", 3);
            Источник.Вставить("Первый", 1);
            Источник.Вставить("Второй", 2);
            Фиксированный = Новый ФиксированноеСоответствие(Источник);
            Копия = Новый Соответствие(Фиксированный);
            АнглийскаяКопия = New Map(Фиксированный);
            ПорядокИсточника = "";
            Для Каждого Пара Из Фиксированный Цикл
                ПорядокИсточника = ПорядокИсточника + Пара.Ключ + ";";
            КонецЦикла;
            ПорядокКопии = "";
            Для Каждого Пара Из Копия Цикл
                ПорядокКопии = ПорядокКопии + Пара.Ключ + ";";
            КонецЦикла;
            Копия.Вставить("Первый", 99);
            Копия.Удалить("Второй");
            Возврат ПорядокИсточника = ПорядокКопии
                И Копия.Количество() = 2
                И Копия.Получить("Первый") = 99
                И Фиксированный.Количество() = 3
                И Фиксированный.Получить("Первый") = 1
                И Фиксированный.Получить("Второй") = 2
                И АнглийскаяКопия.Количество() = 3
                И АнглийскаяКопия.Получить("Первый") = 1;
            "#,
        )
        .unwrap();
    assert_eq!(result, Value::Boolean(true));
}
