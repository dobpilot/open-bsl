use open_bsl::{Engine, Value};

fn text(value: Value) -> String {
    let Value::Str(value) = value else {
        panic!("ожидалась строка");
    };
    value.to_string()
}

#[test]
fn structured_raise_preserves_fields_cause_and_evaluation_order() {
    let engine = Engine::builder().build().unwrap();
    let mut state = engine.new_state();
    let result = state
        .exec(
            r#"
Перем Порядок;
Порядок = "";
Функция Аргумент(Метка, Значение)
    Порядок = Порядок + Метка;
    Возврат Значение;
КонецФункции

Попытка
    ВызватьИсключение("причина", КатегорияОшибки.ОшибкаКопииБазыДанных);
Исключение
    ПричинаПробы = ИнформацияОбОшибке();
КонецПопытки;

Попытка
    ВызватьИсключение(
        Аргумент("1", "внешняя"),
        Аргумент("2", КатегорияОшибки.ОшибкаКонфигурации),
        Аргумент("3", "код"),
        Аргумент("4", "дополнение"),
        Аргумент("5", ПричинаПробы));
Исключение
    ОшибкаПробы = ИнформацияОбОшибке();
КонецПопытки;

Возврат Порядок + "|" + ОшибкаПробы.Описание + "|" + ОшибкаПробы.Код
    + "|" + ОшибкаПробы.ДополнительнаяИнформация + "|" + ОшибкаПробы.Причина.Описание
    + "|" + Строка(ОшибкаПробы.ЯвляетсяОшибкойКатегории(КатегорияОшибки.ОшибкаКонфигурации))
    + "|" + Строка(ОшибкаПробы.ЯвляетсяОшибкойКатегории(КатегорияОшибки.ОшибкаКопииБазыДанных))
    + "|" + Строка(ОшибкаПробы.ЯвляетсяОшибкойКатегории(КатегорияОшибки.ОшибкаКопииБазыДанных, Ложь));
"#,
        )
        .unwrap();
    assert_eq!(
        text(result),
        "12345|внешняя|код|дополнение|причина|Да|Да|Нет"
    );
}

#[test]
fn structured_raise_uses_defaults_for_omitted_middle_positions() {
    let engine = Engine::builder().build().unwrap();
    let mut state = engine.new_state();
    let result = state
        .exec(
            r#"
Попытка
    ВызватьИсключение("ошибка", КатегорияОшибки.ОшибкаКонфигурации,,, Неопределено);
Исключение
    ОшибкаПробы = ИнформацияОбОшибке();
КонецПопытки;
Возврат ОшибкаПробы.Описание + "|" + ОшибкаПробы.Код + "|"
    + ОшибкаПробы.ДополнительнаяИнформация;
"#,
        )
        .unwrap();
    assert_eq!(text(result), "ошибка||");
}
