use open_bsl::Engine;

#[test]
fn direct_and_parameter_insert_preserve_the_procedure_boundary_with_optimizations() {
    for optimizations in [
        bsl_compiler::Optimizations::default(),
        bsl_compiler::Optimizations::all(),
    ] {
        let engine = Engine::builder()
            .optimizations(optimizations)
            .build()
            .unwrap();
        let module = engine.compile(r#"
Процедура ВставитьЧерезПараметр(Получатель)
    Получатель.Insert(1, 99);
КонецПроцедуры
Функция ОшибочноеВыражение(Получатель)
    Возврат Получатель.Вставить(0, 500);
КонецФункции
МассивПроба = Новый Массив;
МассивПроба.Добавить(10);
МассивПроба.Вставить(3, 20);
Если МассивПроба.Количество() <> 4 Или МассивПроба[1] <> Неопределено Или МассивПроба[3] <> 20 Тогда
    ВызватьИсключение "direct gap";
КонецЕсли;
ВставитьЧерезПараметр(МассивПроба);
Если МассивПроба.Количество() <> 5 Или МассивПроба[1] <> 99 Или МассивПроба[4] <> 20 Тогда
    ВызватьИсключение "parameter";
КонецЕсли;
ОшибкаБыла = Ложь;
Попытка РезультатПробы = МассивПроба.Insert(0, 500); Исключение ОшибкаБыла = Истина; КонецПопытки;
Если Не ОшибкаБыла Или МассивПроба.Количество() <> 5 Или МассивПроба[0] <> 10 Тогда
    ВызватьИсключение "direct expression mutation";
КонецЕсли;
ОшибкаБыла = Ложь;
Попытка РезультатПробы = ОшибочноеВыражение(МассивПроба); Исключение ОшибкаБыла = Истина; КонецПопытки;
Если Не ОшибкаБыла Или МассивПроба.Количество() <> 5 Или МассивПроба[0] <> 10 Тогда
    ВызватьИсключение "parameter expression mutation";
КонецЕсли;
МассивПроба.Insert(1);
Если МассивПроба[1] <> Неопределено Или МассивПроба[2] <> 99 Тогда ВызватьИсключение "default"; КонецЕсли;
СтруктураПроба = Новый Структура;
СтруктураПроба.Вставить("Контроль", 17);
СоответствиеПроба = Новый Соответствие;
СоответствиеПроба.Insert("Контроль", 18);
Если СтруктураПроба.Контроль <> 17 Или СоответствиеПроба["Контроль"] <> 18 Тогда
    ВызватьИсключение "other receivers";
КонецЕсли;
"#).unwrap();
        engine.state_builder().build().run(&module).unwrap();
    }
}
