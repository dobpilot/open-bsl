use open_bsl::{Engine, Value};

const SOURCE: &str = r#"
Перем Общая;
Процедура Изменить(Аргумент, Знач Копия, Добавка = 7) Экспорт
    Аргумент = Аргумент + Добавка;
    Копия = 999;
    Общая = Общая + 1;
КонецПроцедуры
Функция Количество(Первый, Второй = 11) Экспорт
    Возврат Первый + Второй;
КонецФункции
Процедура Скрытая()
    Общая = -100;
КонецПроцедуры
Асинх Функция Асинхронная(Знач Аргумент) Экспорт
    Возврат Аргумент + 1;
КонецФункции
Процедура Проверить()
    Число1 = 3; Число2 = 8;
    ЭтотОбъект.Изменить(Число1, Число2, );
    Если Число1 <> 10 Или Число2 <> 8 Тогда ВызватьИсключение "параметры"; КонецЕсли;
    Если ЭтотОбъект.Количество(1, ) <> 12 Тогда ВызватьИсключение "умолчание"; КонецЕсли;
    Ошибок = 0;
    Попытка ЭтотОбъект.Скрытая(); Исключение Ошибок = Ошибок + 1; КонецПопытки;
    Попытка Результат = ЭтотОбъект.Изменить(Число1, Число2); Исключение Ошибок = Ошибок + 1; КонецПопытки;
    Попытка ЭтотОбъект.Изменить(); Исключение Ошибок = Ошибок + 1; КонецПопытки;
    Попытка ЭтотОбъект.Количество(1, 2, 3); Исключение Ошибок = Ошибок + 1; КонецПопытки;
    Если Ошибок <> 4 Или Общая <> 1 Тогда ВызватьИсключение "валидация"; КонецЕсли;
    Если Вычислить("ЭтотОбъект.Количество(10)") <> 21 Тогда ВызватьИсключение "динамика"; КонецЕсли;
КонецПроцедуры
Асинх Процедура ПроверитьАсинх()
    Результат = Ждать ЭтотОбъект.Асинхронная(40);
    Если Результат <> 41 Тогда ВызватьИсключение "асинх"; КонецЕсли;
КонецПроцедуры
Общая = 0;
Проверить();
ПроверитьАсинх();
Возврат Общая;
"#;

#[test]
fn module_calls_execute_exports_with_the_current_state_and_argument_modes() {
    for optimizations in [
        bsl_compiler::Optimizations::default(),
        bsl_compiler::Optimizations::all(),
    ] {
        let engine = Engine::builder()
            .optimizations(optimizations)
            .build()
            .unwrap();
        let module = engine.compile(SOURCE).unwrap();
        for bytecode in [false, true] {
            let module = if bytecode {
                engine.load_bytecode(&module.bytecode().unwrap()).unwrap()
            } else {
                engine.compile(SOURCE).unwrap()
            };
            assert_eq!(
                engine.new_state().run(&module).unwrap(),
                Value::number_from_i64(1)
            );
        }
    }
}

#[test]
fn module_references_cross_catalog_and_entry_frames_without_changing_the_owner() {
    let common = r#"
Перем Экспортная Экспорт;
Перем Счетчик;
Функция Ссылка() Экспорт Возврат ЭтотОбъект; КонецФункции
Функция Добавить(Число) Экспорт
    Счетчик = Счетчик + Число;
    Возврат Счетчик;
КонецФункции
Функция Вызвать(Получатель) Экспорт
    Возврат Получатель.Добавить(10);
КонецФункции
Процедура Мутировать(Аргумент) Экспорт Аргумент = 7; КонецПроцедуры
Процедура Сбой(Аргумент) Экспорт Аргумент = 91; ВызватьИсключение "ошибка"; КонецПроцедуры
Асинх Функция Отложенная(Знач Число) Экспорт
    Возврат ЭтотОбъект.Добавить(Число);
КонецФункции
Счетчик = 0;
Экспортная = 0;
"#;
    let source = r#"
Перем Счетчик;
Функция Добавить(Число) Экспорт
    Счетчик = Счетчик + Число;
    Возврат Счетчик;
КонецФункции
Асинх Процедура Проверить(Ссылка)
    Результат = Ждать Ссылка.Отложенная(100);
    Если Результат <> 111 Тогда ВызватьИсключение "async owner"; КонецЕсли;
КонецПроцедуры
Счетчик = 0;
А = Первый.Ссылка(); Б = Второй.Ссылка();
А.Мутировать(Второй.Экспортная);
Если Второй.Экспортная <> 7 Тогда ВызватьИсключение "imported byref"; КонецЕсли;
Попытка А.Сбой(Второй.Экспортная); Исключение КонецПопытки;
Если Второй.Экспортная <> 91 Тогда ВызватьИсключение "imported exception writeback"; КонецЕсли;
Если А.Добавить(1) <> 1 Или Б.Добавить(2) <> 2 Тогда ВызватьИсключение "states"; КонецЕсли;
Если Б.Вызвать(А) <> 11 Тогда ВызватьИсключение "cross catalog"; КонецЕсли;
Если А.Вызвать(ЭтотОбъект) <> 10 Тогда ВызватьИсключение "entry"; КонецЕсли;
Проверить(А);
Возврат Счетчик;
"#;
    for optimizations in [
        bsl_compiler::Optimizations::default(),
        bsl_compiler::Optimizations::all(),
    ] {
        let engine = Engine::builder()
            .optimizations(optimizations)
            .common_module("Первый", common)
            .common_module("Второй", common)
            .build()
            .unwrap();
        let entry = engine.compile_entry(source).unwrap();
        for bytecode in [false, true] {
            let entry = if bytecode {
                engine.load_bytecode(&entry.bytecode().unwrap()).unwrap()
            } else {
                engine.compile_entry(source).unwrap()
            };
            let mut state = engine.new_state();
            assert_eq!(state.run(&entry).unwrap(), Value::number_from_i64(10));
            assert_eq!(state.run(&entry).unwrap(), Value::number_from_i64(10));
        }
    }
}

