use open_bsl::Engine;

fn run_modes(source: &str) {
    for optimizations in [
        bsl_compiler::Optimizations::default(),
        bsl_compiler::Optimizations::all(),
    ] {
        let engine = Engine::builder()
            .optimizations(optimizations)
            .build()
            .unwrap();
        for bytecode in [false, true] {
            let module = engine.compile(source).unwrap();
            let module = if bytecode {
                engine.load_bytecode(&module.bytecode().unwrap()).unwrap()
            } else {
                module
            };
            engine.new_state().run(&module).unwrap();
        }
    }
}

#[test]
fn measured_value_table_indexes_work_in_every_execution_mode() {
    run_modes(
        r#"
ТаблицаПробы = Новый ТаблицаЗначений;
ТаблицаПробы.Колонки.Добавить("А");
ТаблицаПробы.Колонки.Добавить("Б");
ИндексыПробы = ТаблицаПробы.Indexes;
Если ИндексыПробы <> ТаблицаПробы.Индексы Или ИндексыПробы.Count() <> 0 Тогда
    ВызватьИсключение "collection";
КонецЕсли;

ПустойИндекс = ИндексыПробы.Add();
ИндексА = ИндексыПробы.Добавить("А");
ИндексАБ = ИндексыПробы.Add("А, Б");
Если ИндексыПробы[0] <> ПустойИндекс
    Или ИндексыПробы[1] <> ИндексА
    Или ИндексыПробы[2] <> ИндексАБ Тогда
    ВызватьИсключение "item identity";
КонецЕсли;

ОшибкаБыла = Ложь;
Попытка ИндексыПробы.Add("НетКолонки"); Исключение ОшибкаБыла = Истина; КонецПопытки;
Если Не ОшибкаБыла Или ИндексыПробы.Count() <> 3 Тогда ВызватьИсключение "unknown column"; КонецЕсли;

Копия = ТаблицаПробы.Copy();
Если Копия.Indexes.Count() <> 3 Или Копия.Indexes[1] = ИндексА Тогда
    ВызватьИсключение "copy";
КонецЕсли;
Копия.Indexes.Delete(Копия.Indexes[0]);
Если Копия.Indexes.Count() <> 2 Или ИндексыПробы.Count() <> 3 Тогда
    ВызватьИсключение "copy independence";
КонецЕсли;
Если ТаблицаПробы.Copy(Неопределено, "").Indexes.Count() <> 3
    Или ТаблицаПробы.Copy(Неопределено, "А, Б").Indexes.Count() <> 0
    Или ТаблицаПробы.CopyColumns().Indexes.Count() <> 0 Тогда
    ВызватьИсключение "copy columns";
КонецЕсли;

ДругаяТаблица = Новый ТаблицаЗначений;
ДругаяТаблица.Колонки.Add("А");
ЧужойИндекс = ДругаяТаблица.Indexes.Add("А");
ОшибкаБыла = Ложь;
Попытка ИндексыПробы.Delete(ЧужойИндекс); Исключение ОшибкаБыла = Истина; КонецПопытки;
Если Не ОшибкаБыла Или ИндексыПробы.Count() <> 3 Тогда ВызватьИсключение "foreign"; КонецЕсли;

Для Каждого ИмяМетода Из СтрРазделить("Количество,Count,Добавить,Add,Удалить,Delete,Очистить,Clear", ",") Цикл
    Описание = Новый NotifyDescription(ИмяМетода, ИндексыПробы);
КонецЦикла;
Для Каждого ИмяМетода Из СтрРазделить("Count,НетМетода", ",") Цикл
    ОшибкаБыла = Ложь;
    Попытка Описание = Новый NotifyDescription(ИмяМетода, ИндексА); Исключение ОшибкаБыла = Истина; КонецПопытки;
    Если Не ОшибкаБыла Тогда ВызватьИсключение "index receiver"; КонецЕсли;
КонецЦикла;

ОшибкаБыла = Ложь;
Попытка Результат = ИндексыПробы.Clear(); Исключение ОшибкаБыла = Истина; КонецПопытки;
Если Не ОшибкаБыла Или ИндексыПробы.Count() <> 3 Тогда ВызватьИсключение "procedure"; КонецЕсли;
ИндексыПробы.Clear();
Если ИндексыПробы.Count() <> 0 Тогда ВызватьИсключение "clear"; КонецЕсли;
"#,
    );
}
