//! Модель типов XDTO поверх компонентной модели XSD: `ФабрикаXDTO`,
//! `ТипЗначенияXDTO`, `ТипОбъектаXDTO`, `СвойствоXDTO` и соответствие
//! встроенных типов XML Schema типам BSL.
//!
//! Второго разборщика схем здесь нет: на вход идёт готовая `XsSchemaData`
//! из [`bsl_rt::xsd`], а этот модуль превращает ЛЕКСИЧЕСКУЮ модель схемы в
//! РАЗРЕШЁННУЮ модель типов — ту, где ссылки уже связаны, наследование
//! сплющено, а границы вхождения посчитаны. Ровно этим две модели и
//! различаются: `ОбъявлениеЭлементаXS` показывает написанное, а
//! `СвойствоXDTO` — вычисленное.
//!
//! # Что ИЗМЕРЕНО на 8.3.27
//!
//! Всё перечисленное снято пробами (`tests/conformance/measure/measure-xdto.bsl`,
//! рядом лежит снятый `measure-xdto.platform.txt`), а не взято из справки.
//! Проб потребовалось много, потому что справка щедра на члены, которых у
//! платформы нет: у `ТипЗначенияXDTO` отвергнуты `Вариант`,
//! `ВариантПростогоТипа`, `Абстрактный`, `Длина`, `МинимальнаяДлина`,
//! `МаксимальнаяДлина`, `Образцы`, `Перечисления`, `ПробельныеСимволы`,
//! `ТипЭлемента`, `ТипыОбъединения`, `Пакет`, `Фабрика`, `Создать`,
//! `ПроверитьЗначение`, `ЭтоНаследник`, у `ТипОбъектаXDTO` — `Фабрика`,
//! `Пакет`, `Создать`, `ЭтоНаследник`, `ПолучитьСвойство`, у
//! `СвойствоXDTO` — `Владелец`, `Нулевой`, `Обязательный`, `Фиксированный`,
//! `Локальный`, `Порядок`, `ЛексическоеЗначениеПоУмолчанию`, `ФормаXML`.
//!
//! * **фабрика строится ровно двумя способами, и они не взаимозаменяемы.**
//!   `СоздатьФабрикуXDTO(Путь)` берёт ТОЛЬКО путь к файлу XSD: от схемы, от
//!   набора схем, от текста схемы, от числа и без аргументов — ошибка, от
//!   двух аргументов — тоже, и на несуществующем пути — тоже ошибка (текст
//!   отказа не снят: обвязка замеров видит только сам факт исключения).
//!   `Новый ФабрикаXDTO(...)` — наоборот, берёт ТОЛЬКО `НаборСхемXML`
//!   (или ничего): путь, схема, текст, массив и два аргумента отвергаются.
//!   Английские написания есть у обоих
//!   (`CreateXDTOFactory`, `Новый XDTOFactory`). Фабрика — СНИМОК:
//!   схема, добавленная в набор после её создания, ей не видна, а две
//!   фабрики от одного файла НЕ равны;
//! * `Строка()` фабрики — `ФабрикаXDTO`, `ТипЗнч()` — «Фабрика XDTO»;
//!   `ЗначениеЗаполнено` от неё — ошибка, посторонний член — ошибка.
//!   Методов у фабрики два, оба с английскими написаниями: `Тип`/`Type` и
//!   `Создать`/`Create`;
//! * `Создать` от типа ЗНАЧЕНИЯ без лексической формы — `Неопределено`, с
//!   формой — `ЗначениеXDTO`; третий аргумент платформа принимает
//!   (четвёртый уже нет), и что он значит — не измерено. `Создать` от типа
//!   ОБЪЕКТА даёт `ОбъектXDTO` и лексической формы не терпит, а
//!   абстрактный тип отвергает совсем. У самого экземпляра `Строка()` —
//!   `ОбъектXDTO`, свой тип он отдаёт МЕТОДОМ `Тип()` (обращение к `Тип`
//!   как к свойству — ошибка), и два экземпляра одного типа не равны;
//! * `ЗначениеXDTO` — только на ЧТЕНИЕ: присваивание и в `Значение`, и в
//!   `ЛексическоеЗначение` платформа отвергает. Свой тип оно отдаёт
//!   методом `Тип()`, а `Владелец` у него нет ни членом, ни методом
//!   (измерено все пять проб);
//! * все три типа существуют под двумя написаниями и печатаются с
//!   пробелами: `ТипЗначенияXDTO`/`XDTOValueType` -> «Тип значения XDTO»,
//!   `ТипОбъектаXDTO`/`XDTOObjectType` -> «Тип объекта XDTO»,
//!   `СвойствоXDTO`/`XDTOProperty` -> «Свойство XDTO». `Новый` ни один из
//!   них не строит (ошибка на всех трёх), а `Новый ФабрикаXDTO` —
//!   наоборот, работает;
//! * `Строка()` от типа — это `{URI}Имя` (`{urn:test}RootType`), но у
//!   АНОНИМНОГО типа, чьё имя пусто, — пустая строка, хотя `URI` у него при
//!   этом целевое пространство схемы. `Строка()` от свойства — его имя;
//! * тип ищется в фабрике парой (URI, имя) или `РасширенноеИмяXML`; одной
//!   строкой — ошибка, неизвестное имя — `Неопределено`, а объявление
//!   глобального ЭЛЕМЕНТА типом не является (`Тип("urn:test", "root")` —
//!   `Неопределено`). Два обращения к `Тип` за одним именем дают РАВНЫЕ
//!   значения, то есть тип — это ссылка на место в модели;
//! * `БазовыйТип` у типа объекта без явного базового — `{...}anyType`, а у
//!   типа значения без явного — `{...}anySimpleType`. У составного типа с
//!   ПРОСТЫМ содержимым (`xs:simpleContent`) базовый тип тоже `anyType`:
//!   простой базовый тип виден не через `БазовыйТип`, а через свойство
//!   `__content`;
//! * `Свойства` типа объекта — СПЛЮЩЕННЫЙ список: сначала свойства
//!   базового типа, потом собственные АТРИБУТЫ, потом собственные
//!   ЭЛЕМЕНТЫ. Измерено на схеме, где у базового типа четыре атрибута и
//!   девять элементов, а у наследника по одному своему:
//!   `id color opt q fx name code дата def many5 notype efx uq anon` и у
//!   наследника `… anon ea extra`;
//! * границы вхождения свойства — `НижняяГраница`/`ВерхняяГраница`,
//!   ЧИСЛА, и `unbounded` показывается числом `-1`. Лексическая модель
//!   схемы отвечает на то же самое иначе: `МаксимальноВходит` частицы с
//!   `maxOccurs="unbounded"` — это СТРОКА `unbounded` (измерено, см.
//!   [`bsl_rt::xsd`]). Границы ПЕРЕМНОЖАЮТСЯ по вложенным группам модели:
//!   `<xs:choice minOccurs="0">` превращает `1..1` вложенного элемента в
//!   `0..1`, а `<xs:sequence maxOccurs="unbounded">` — `0..1` в `0..-1`;
//! * `Форма` — член `ФормаXML` (`Элемент`, `Атрибут`, `Текст`), у
//!   `ФормаXML` есть и английские написания членов. `URIПространстваИмен`
//!   свойства подчиняется тому же правилу форм, что и в модели XSD:
//!   квалифицированное объявление даёт целевое пространство, неквалифи-
//!   цированное — пустую строку;
//! * составной тип с `xs:simpleContent` получает свойство с именем
//!   `__content`, формой `Текст`, границами `1..1`, пустым URI и типом
//!   базового простого типа. У СМЕШАННОГО типа (`mixed="true"`) такого
//!   свойства НЕТ — там только объявленные элементы;
//! * `Упорядоченный` — «Да» у последовательности, у пустого типа и у
//!   простого содержимого, «Нет» у `xs:choice` и `xs:all`;
//!   `Последовательный` во всех измеренных случаях равен «НЕ
//!   Упорядоченный ИЛИ Смешанный ИЛИ Открытый» (проверено на
//!   одиннадцати типах, включая `anyType`, у которого «Да» все три).
//!   `Открытый` — «Да» у `anyType` и у типа с МАСКОЙ: `xs:any` и
//!   `xs:anyAttribute` поодиночке дают «Да», маска во вложенной группе
//!   модели тоже, и наследник открытого типа открыт без своих масок
//!   (замер `measure-xdto-order.bsl`). Это не косметика: открытость через
//!   `Последовательный` решает ПОРЯДОК записи свойств — см.
//!   [`write_properties`];
//! * `Фасеты` типа значения — `КоллекцияФасетовXDTO`, но у типа БЕЗ
//!   фасетов это `Неопределено`, а не пустая коллекция (измерено на
//!   `xs:date`). `ФасетXDTO` отдаёт ровно два члена: `Вид` (член
//!   `ВидФасетаXDTO`) и `Значение`, причём `Значение` — всегда СТРОКА,
//!   даже у числовых фасетов (`Минимальное включающее значение=[0]`);
//! * `ЗначениеПоУмолчанию` свойства — `ЗначениеXDTO` с членами `Значение`
//!   (значение BSL) и `ЛексическоеЗначение` (строка). Заполняется и от
//!   `default`, и от `fixed`; у свойства без того и другого —
//!   `Неопределено`;
//! * встроенные типы XML Schema образуют ИЕРАРХИЮ с фасетами: `string`
//!   наследует `anySimpleType` и несёт `Пробельные символы=[preserve]`,
//!   `int` наследует `long` и несёт границы диапазона
//!   `[-2147483648, 2147483647]`, `integer` наследует `decimal` с
//!   `Количество разрядов дробной части=[0]`. Вся таблица снята поимённо —
//!   см. [`BUILTIN_TYPES`];
//! * отображение встроенного типа в тип BSL снято через
//!   `ФабрикаXDTO.Создать(Тип, Лексика).Значение`. Свой тип наследует
//!   отображение базового (`Code` от `xs:string` -> `Строка`, `Small` от
//!   `xs:decimal` -> `Число`), СПИСОК даёт `ФиксированныйМассив`, а
//!   ОБЪЕДИНЕНИЕ выбирает первый член, который принимает лексическую
//!   форму: у `union memberTypes="xs:int xs:string"` запись «5» дала
//!   `Число`, а «аб» — `Строка`.
//!
//! # Экземпляр: что ИЗМЕРЕНО про хранилище
//!
//! * **чтение свойства** идёт по СПЛЮЩЕННОМУ списку типа и регистра не
//!   различает (`О.NAME` читает `name`). Незаполненное свойство —
//!   `Неопределено`, а объявленное с `default` или `fixed` — сразу
//!   значение (`def` -> 7, `fx` -> 9, `color` -> «red», `efx` -> 3).
//!   Постороннее имя — ошибка. МНОЖЕСТВЕННОЕ свойство (верхняя граница не
//!   единица: и `0..-1`, и `1..5`) отдаёт `СписокXDTO`, а не значение,
//!   даже когда список пуст;
//! * **запись** приводит значение к типу свойства ЧЕРЕЗ ЛЕКСИЧЕСКУЮ ФОРМУ:
//!   `О.name = 5` даёт строку «5», `О.name = Дата(2026,8,13)` —
//!   «2026-08-13T00:00:00», `О.name = Истина` — «true», `О.id = "5"` —
//!   число 5, `О.дата = "2026-08-13"` — дату. Отказы — с той же стороны:
//!   `О.id = Истина` и `О.id = 1.5` — ошибка, потому что «true» и «1.5» не
//!   лексические формы `xs:int`. `Неопределено`, `Null` и посторонний
//!   объект в свойство простого типа — тоже ошибка (сброс делает
//!   `Сбросить`, а не присваивание `Неопределено`). `ЗначениеXDTO`
//!   принимается, и берётся из него ЗНАЧЕНИЕ: `Создать(xs:string, "5")` в
//!   свойство `xs:int` дало число 5. Присваивание в множественное
//!   свойство — ошибка;
//! * **свойство типа ОБЪЕКТА** принимает экземпляр своего типа и его
//!   НАСЛЕДНИКА (`ExtType` в свойство типа `RootType` прошёл), а
//!   посторонний тип — ошибка. Записанный объект остаётся ТЕМ ЖЕ (`О.anon
//!   = А; О.anon = А` — «Да») и получает владельца: `А.Владелец() = О` —
//!   «Да». Свойство типа `anyType` — исключение: оно принимает что угодно
//!   как есть (строку, число, объект);
//! * **`СписокXDTO` — окно, а не снимок.** `С = О.code; С.Добавить(...)`
//!   видно через `О.code`, а два отдельных чтения равны (`О.code = О.code`
//!   — «Да»). `Владелец` у него ЧЛЕН (`Владелец()` — ошибка). Методы:
//!   `Количество`/`Count`, `Добавить`/`Add`, `Получить`/`Get`,
//!   `Установить`/`Set`, `Вставить` (АНГЛИЙСКОГО написания у неё нет —
//!   `Insert` отвергнут), `Удалить`/`Delete` (`Remove` отвергнут),
//!   `Очистить`/`Clear`; `Индекс`, `Найти` и `ВГраница` отвергнуты.
//!   Индексация и `Для Каждого` работают, номер за границей — ошибка, как
//!   и `Установить`, `Удалить` за границей и `Добавить` без аргументов.
//!   `Вставить` требует ЗАНЯТОЙ позиции: и в пустой список, и на место
//!   сразу за последним элементом платформа вставлять отказывается, так
//!   что дописать в конец умеет только `Добавить`. Значение в списке — обычное значение BSL, не
//!   `ЗначениеXDTO`. Верхняя граница вхождения при `Добавить` НЕ
//!   проверяется: в свойство `1..5` шесть значений легли молча;
//! * **члены экземпляра**: `Получить`/`Get` и `Установить`/`Set` берут имя
//!   строкой ИЛИ `СвойствоXDTO`, но только у одиночного свойства (у
//!   множественного — ошибка, для него есть `ПолучитьСписок`/`GetList`);
//!   `Установлено`/`IsSet` показывает именно ЗАПИСЬ, а не наличие значения
//!   (у свежего объекта `Установлено("def")` — «Нет», хотя `О.def` отдаёт
//!   7); `Сбросить`/`Unset` возвращает свойство в незаполненное состояние
//!   (`Сброс` отвергнут); `Свойства()`/`Properties()` — коллекция свойств
//!   СВОЕГО ТИПА (14 и 14); `Владелец()`/`Owner()` — метод, у отдельно
//!   созданного объекта `Неопределено`; `Проверить()`/`Validate()`
//!   проверяет границы вхождения и делает это РЕКУРСИВНО (пустой тип
//!   прошёл, недозаполненный `RootType` отвергнут, объект с пустым
//!   вложенным — отвергнут, с заполненным — прошёл, шесть значений в
//!   свойстве `1..5` — отвергнут, недозаполненный объект в списке —
//!   отвергнут). Отвергнуты `ЭтоNull`, `УстановитьNull` и `Владелец` как
//!   член;
//! * **`ПоследовательностьXDTO` достижима** — методом
//!   `Последовательность()`/`Sequence()`, и только у ПОСЛЕДОВАТЕЛЬНОГО
//!   типа: `xs:choice` и `xs:all` дают объект, а тип-последовательность и
//!   простое содержимое — `Неопределено`, а не ошибку. Это порядок
//!   ЗАПОЛНЕНИЯ свойств-элементов: запись атрибута её не удлиняет,
//!   повторная запись одиночного свойства сохраняет своё место
//!   (`ca = "вг"; cb.Добавить("аб"); ca = "де"` -> `[ca=де][cb=аб]`), а
//!   `Сбросить` с последующей записью отправляет свойство в конец.
//!   `Вставить` в список кладёт значение перед тем, на чьё место оно
//!   встало (`[cb=де][cb=аб][ca=вг]`). Члены: `Количество`/`Count`,
//!   `ПолучитьЗначение`/`GetValue`, `ПолучитьСвойство`/`GetProperty`,
//!   `Добавить`/`Add` (берёт именно `СвойствоXDTO` и именно элемент —
//!   имя строкой и атрибут отвергнуты; заполнение видно и через само
//!   свойство), `Очистить`/`Clear` (чистит элементы, атрибуты уцелевают),
//!   `Владелец` членом. Отвергнуты `Получить`, `Свойство`, `ЭтоТекст`,
//!   индексация, `Для Каждого` и `ДобавитьЗначение`;
//! * **`Последовательность().Удалить(0)` РОНЯЕТ ПЛАТФОРМУ.** 8.3.27
//!   падает по сигналу сегментации — не исключение, которое ловится
//!   `Попытка`, а смерть процесса вместе со всем прогоном замеров. Эту
//!   пробу в `measure-xdto.bsl` возвращать нельзя (см. её шапку), а
//!   значит, поведение `Удалить` у последовательности не измерено и
//!   здесь его нет.
//!
//! # Проверка по фасетам: что ИЗМЕРЕНО
//!
//! Пробы — `tests/conformance/measure/measure-xdto-validation.bsl`, рядом
//! снятый `measure-xdto-validation.platform.txt`; фикстура —
//! `tests/conformance/fixtures/xdto-validation.bsl`. Схема там устроена
//! так, что на каждый вид фасета приходится СВОЙ тип: по отказу должно
//! быть видно, какой именно фасет сработал.
//!
//! * **отдельного метода проверки НЕТ ни у типа, ни у значения.**
//!   Отвергнуты все кандидаты: `Проверить` и `Validate` у
//!   `ТипЗначенияXDTO` и у `ТипОбъектаXDTO` (и с аргументом-значением, и
//!   без), `ПроверитьЗначение` у типа значения, `Проверить`/`Validate` у
//!   `ЗначениеXDTO`. Проверка живёт не в отдельном члене, а в тех местах,
//!   где значение появляется;
//! * **проверяются четыре места, и все четыре измерены**: `Создать`
//!   фабрики, ЗАПИСЬ свойства (и присваиванием, и `Установить`),
//!   наполнение списка (`Добавить`, `Установить`, `Вставить`) и ЧТЕНИЕ
//!   документа с типом. Значение приводится к лексической форме ДО
//!   проверки, поэтому `О.el = 42` в свойство длины 2..5 проходит («42» —
//!   два символа), а `О.el = 5` — нет;
//! * **пятое место — сама СХЕМА.** Умолчание, нарушающее фасет
//!   (`default="а"` у типа с `minLength="2"`), валит построение ФАБРИКИ
//!   целиком: `СоздатьФабрикуXDTO` от такой схемы отвечает ошибкой, а не
//!   отдаёт фабрику с негодным умолчанием;
//! * **чтение СЕРИАЛИЗАТОРА фасеты НЕ проверяет** —
//!   `СериализаторXDTO.ПрочитатьXML` от `<Len xmlns="urn:v">а</Len>` при
//!   `minLength="2"` отдаёт «а» без ошибки, в отличие от чтения фабрики.
//!   Здесь так же;
//! * **фасеты НАСЛЕДУЮТСЯ по всей цепочке.** У ограничения, наложенного
//!   на ограничение, работают обе границы — `minLength` от базового типа и
//!   свой `maxLength`, — а у встроенных типов — вся табличная цепочка: `int` с
//!   «3000000000», `byte` с «200», `unsignedByte` с «-1»,
//!   `positiveInteger` с «0» и `integer` с «1.5» — ошибка, а `decimal` с
//!   «1.5» — нет;
//! * **перечисление сравнивает ЗНАЧЕНИЯ, а не записи**: при перечисленных
//!   «1.0» и «2» у десятичного типа проходят и «1», и «2.00», а «3» — нет.
//!   Регистр при этом значим («RED» при перечисленном «red» — ошибка), и
//!   пустая запись сама по себе не разрешена;
//! * **длина считается по виду значения**: у строки — в символах
//!   (кириллица не удваивается), у `base64Binary` — в БАЙТАХ
//!   (`maxLength="2"` пропускает «0LA=» и отвергает «0LDQsQ==»), у
//!   списочного типа — в ЭЛЕМЕНТАХ, причём сами элементы проверяются
//!   типом элемента;
//! * **границы сравниваются не только у чисел**: у ограничения `xs:date`
//!   `minInclusive="2020-01-01"` отвергает «2019-01-01», а
//!   `maxExclusive="2030-01-01"` — саму «2030-01-01»;
//! * **разряды считаются по ЗНАЧЕНИЮ**: `totalDigits="4"` пропускает
//!   «12.34» и «1234», но не «123.45» и не «12345», а `fractionDigits="2"`
//!   пропускает «1.200» (хвостовые нули в значение не входят) и отвергает
//!   «1.234»;
//! * **`whiteSpace` платформа не применяет**: `Создать` от `xs:token` и от
//!   `xs:string` с « аб  вг » отдаёт строку с теми же пробелами, хотя
//!   фасет у `token` — `collapse`;
//! * **член объединения выбирается С УЧЁТОМ фасетов**: у `union
//!   memberTypes="t:Col xs:int"`, где `Col` — перечисление `red|green`,
//!   запись «5» даёт ЧИСЛО, хотя строкой она разбирается первым членом;
//! * **`Проверить()` экземпляра проверять фасетами нечего**: значение,
//!   нарушающее фасет, в экземпляр не попадает ни одним измеренным путём
//!   (суррогатная проба перебирает их все и отвечает «закрыто»). Отсюда
//!   `НЕ ИЗМЕРЕНО(XDTO.VALIDATION.VALIDATE_FACETS)`.
//!
//! # Сознательные расхождения и незакрытые углы
//!
//! * **Фасет `pattern` — честная ошибка, и расхождение двустороннее.**
//!   Движка регулярных выражений в дереве нет (это отдельная задача), а
//!   частично истолкованный образец хуже названной вслух неподдержки:
//!   проверка значения по типу СХЕМЫ с образцом отвечает ошибкой «не
//!   поддерживается» — в том числе на значении, которое платформа
//!   принимает. Образцы ВСТРОЕННЫХ типов, наоборот, пропускаются: отказ по
//!   ним съел бы любую запись в `xs:int`, чей предок `xs:integer` несёт
//!   образец `[\-+]?[0-9]+`. Лексическое пространство целых и без образца
//!   задаёт разбор, а вот `xs:Name`, `xs:NCName` и `xs:language`
//!   отображаются в `Строка` и потому терпят то, что платформа отвергает
//!   (измерено: `Создать` от `Name` с «1имя» и с «имя два», от `NCName` с
//!   «а:б» — ошибка). Расходятся ровно эти шесть строк
//!   `measure-xdto-validation.bsl`, и они перечислены в её шапке. В
//!   конформанс-фикстуре типов с образцом нет вовсе, а поведение закрыто
//!   тестом `pattern_facet_is_an_honest_unsupported_error`;
//! * **Двоичные лексические формы.** `base64Binary` и `hexBinary`
//!   отображаются в `ДвоичныеДанные` (измерено), и разбор обеих записей
//!   здесь есть, но обратной операции — двоичные данные в лексическую
//!   форму — нет: она нужна записи XML, а не модели типов.
//! * **QName с префиксом.** Платформа принимает только запись БЕЗ
//!   префикса (`Создать` от `xs:string` — ошибка, от `просто` —
//!   расширенное имя с пустым URI). Здесь так же: префикс — ошибка, а не
//!   попытка разрешить его по объявлениям схемы.
//! * **Лексическая форма — только строка.** Платформа принимает и число
//!   (`Создать(Тип, 42)` отдаёт `ЗначениеXDTO`), но какую именно запись она
//!   из числа делает — не измерено, а разница видна сразу: `Строка(12.75)`
//!   в 1С — это «12,75» с запятой, а лексическая форма `xs:decimal` — с
//!   точкой. Гадать здесь дороже, чем отказать, поэтому нестроковый
//!   аргумент — ошибка.
//! * **`Пакеты` фабрики не поддержаны.** Платформа отдаёт
//!   `КоллекциюПакетовXDTO` (у фабрики от нашей схемы их два: своё
//!   пространство имён и пространство XML Schema), но пакет — это отдельная
//!   сущность со своим содержимым, и она сюда не входит.
//! * **Цена образца видна на `measure-xdto.bsl`.** Пять расхождений его
//!   экземплярной части, которые объяснялись непроверяемыми фасетами,
//!   закрылись: `О.color = "синий"` (перечисление `red|green`),
//!   `code.Добавить(5)` и `О.hl = 5` (длина 2..5 у элемента и у элемента
//!   списочного типа), `О.id = 1.5` («разрядов дробной части» — ноль у
//!   `xs:integer`) и `code.Добавить("аб")` — последнее отказом «образец не
//!   поддерживается», то есть по другой причине, чем у платформы, но с тем
//!   же наблюдаемым фактом. Заодно закрылись `Создать` от `Small` с «1000»
//!   и от `Code` с «аб». Плата — 21 строка ТОЙ ЖЕ пробы, где через
//!   `Code` проверялось совсем другое: окно списка, `Получить`/`Установить`
//!   /`Вставить`/`Удалить`, обход и `Установлено`. Все они теперь отвечают
//!   отказом по образцу. Схема того скрипта не трогалась намеренно — она
//!   контракт платформы, снятый её же прогоном, — а списочная семантика не
//!   потерялась: она измерена заново на `ml` в
//!   `measure-xdto-validation.bsl`, где тип элемента без образца, и
//!   проверена юнит-тестами. Шестое расхождение к фасетам отношения не
//!   имело, а теперь его не видно вовсе: проба «объект запись в список
//!   строкой» пишет «AB CD» в `hl` списочного типа `Codes` над образцовым
//!   `Code`, и раньше платформенному `ФиксированныйМассив` отвечал здесь
//!   обычный `Массив`, а теперь — отказ по образцу. В плату в 21 строку
//!   она не вошла: расходилась и до проверки фасетов, сменилась лишь
//!   причина, и ровно так же сменила её «вст своего типа Codes» — это две
//!   строки, которые отказ поглотил, ничего не добавив к счёту. Сам факт
//!   при этом остался, он просто больше не виден ни на одной пробе этого
//!   файла: своего неизменяемого вида массива в реализации нет, см.
//!   `value_from_lexical_at`.
//! * **Английские написания разбираются по имени, а не по получателю.**
//!   Таблица `BUILTIN_METHOD_NAMES` — одна на весь рантайм, и «Вставить»
//!   делит вариант с `Insert`, поэтому `Список.Insert(...)` здесь имя
//!   находит и дальше идёт тем же путём, что `Вставить`, тогда как
//!   платформа у `СписокXDTO` английского написания не знает вовсе.
//!   Ошибка в сторону разрешённого: программа, которая работает на
//!   платформе, работает и здесь. `Remove` в таблице нет ни у одного
//!   получателя, так что `Список.Remove(...)` отвергается и здесь — это
//!   совпадение с платформой, а не разбор по получателю. В самих пробах
//!   расхождения не видно: «список Insert» вставляет в ПУСТОЙ список и
//!   потому ошибка с обеих сторон.
//! * **Порядок обхода `Для Каждого` по списку** — порядок заполнения, тот
//!   же, что у индексации. Отдельной пробы на «список после `Вставить` в
//!   середину» нет: измерено только, куда `Вставить` встаёт в
//!   ПОСЛЕДОВАТЕЛЬНОСТИ.
//!
//! # Ввод-вывод: что ИЗМЕРЕНО про `ПрочитатьXML`/`ЗаписатьXML`
//!
//! Пробы — `tests/conformance/measure/measure-xdto-io.bsl`, рядом снятый
//! `measure-xdto-io.platform.txt`; круговая фикстура —
//! `tests/conformance/fixtures/xdto-xml-io.bsl`.
//!
//! * **арности.** `ПрочитатьXML(ЧтениеXML[, Тип])` — один или два
//!   аргумента, третий платформа отвергает; `ЗаписатьXML(ЗаписьXML,
//!   Значение[, Имя[, УРИ]])` — от двух до четырёх, ПЯТЫЙ отвергает, так
//!   что «ТипXML» и «ФормаXML» из справки пятым и шестым параметрами не
//!   существуют. Английские написания есть у обоих (`ReadXML`, `WriteXML`).
//!   Тип чтения берётся только значением `ТипЗначенияXDTO`/`ТипОбъектаXDTO`:
//!   имя строкой и `РасширенноеИмяXML` вторым аргументом — ошибка;
//! * **чтение БЕЗ типа — это не поиск по объявлению элемента.** Платформа
//!   разбирает документ в ОТКРЫТОЕ содержимое `anyType`: `Тип()` результата
//!   — `{...}anyType`, у самого типа свойств ноль, а у ЭКЗЕМПЛЯРА их
//!   одиннадцать — заведённых по ходу разбора, с формой и URI каждого
//!   (`[id Атрибут ][name Элемент urn:test]…[uq Элемент ]`). Значения при
//!   этом остаются СТРОКАМИ («12.50», «true», «2026-08-13»), повторяющийся
//!   элемент даёт `СписокXDTO`, вложенный — снова `anyType`, а посторонний
//!   корень (`<чужой xmlns="urn:иное"/>`) читается без ошибки. Текст
//!   элемента при этом ТЕРЯЕТСЯ: у `<голый>42</голый>` свойств ноль.
//!   Открытого содержимого здесь нет, поэтому вызов с одним аргументом
//!   отвечает отказом — см. «Сознательные расхождения» ниже;
//! * **чтение С ТИПОМ типизирует значения и ПРОВЕРЯЕТ документ.**
//!   `xs:int` -> `Число`, `xs:decimal` -> `Число` (12.50 -> 12,5),
//!   `xs:date` -> `Дата`, `xs:boolean` -> `Булево`, `xs:base64Binary` ->
//!   `ДвоичныеДанные`, множественное свойство -> `СписокXDTO`, вложенный
//!   элемент -> `ОбъектXDTO`. Отвергаются: элемент и атрибут, которых у
//!   типа нет; лексическая форма, не разбирающаяся объявленным типом;
//!   повтор одиночного свойства; отсутствие обязательного свойства. У
//!   УПОРЯДОЧЕННОГО типа проверяется и ПОРЯДОК — `<num>` перед `<name>`
//!   отвергается, как и второе вхождение `<tag>` после `<nested>`, —
//!   а необязательное свойство пропускать можно;
//! * **пробельный текст между элементами пропускается**, значащий текст в
//!   составном типе — ошибка; комментарии, секции CDATA, ссылки на
//!   сущности и объявление XML перед корнем разбор не смущают. Текст
//!   ВНУТРИ простого элемента сохраняется как есть, включая краевые
//!   пробелы;
//! * **`xsi:nil="true"`** заполняет свойство ПУСТЫМ значением:
//!   `Установлено` — «Да», само свойство — `Неопределено`, и обратная
//!   запись даёт тот же `<nilt xsi:nil="true"/>`;
//! * **`xsi:type` действует у СВОЙСТВА, но не у элемента, с которого
//!   начинается чтение.** Имя типа разрешается как QName в содержимом
//!   атрибута — и с префиксом (`t:InnerExt`), и без него по
//!   умолчательному объявлению (`InnerExt`), — а неизвестное имя
//!   платформа молча игнорирует и читает объявленным типом. На самом
//!   читаемом элементе пометка не действует вовсе: `<точка
//!   xsi:type="InnerExt">` с типом `Inner` даёт `Inner`;
//! * **пустая лексическая форма** у десятичных чисел — это НОЛЬ (`<num/>`
//!   -> 0, и `Создать(xs:int, "")` — тоже 0), у `base64Binary` — пустые
//!   двоичные данные, а у `xs:double`, даты, времени и булева — ошибка;
//! * **позиция читателя.** Разбор начинается с первого начального тега (и
//!   свежий читатель, и читатель после `Прочитать()`, и после
//!   `ПерейтиКСодержимому()` дают одно и то же), а заканчивается на
//!   СЛЕДУЮЩЕМ узле за прочитанным элементом: два соседних элемента
//!   читаются двумя вызовами без `Прочитать()` между ними, а на документе
//!   из одного корня читатель после разбора исчерпан («Ничего»,
//!   `Прочитать()` — «Нет»);
//! * **запись: имя и пространства имён.** Имя по умолчанию — ИМЯ ТИПА
//!   значения (`<RootType …>`), а не имя объявленного в схеме элемента; у
//!   анонимного типа имя пусто и вызов без имени — ошибка, как и вызов с
//!   пустым именем. На элементе, с которого начинается запись, объявляются
//!   умолчательное пространство (URI из аргумента либо пространство типа),
//!   `xmlns:xs` и `xmlns:xsi`; `xs` не объявляется, если пространство XML
//!   Schema и так стало умолчательным. Внутри объявления не повторяются, а
//!   свойство с ДРУГИМ URI объявляет своё (`<name xmlns="urn:test">`,
//!   `<uq xmlns="">`);
//! * **квалифицированный атрибут требует префикса** — умолчательное
//!   объявление на атрибуты не распространяется. Префикс порождается как
//!   `d<глубина>p<номер>`, где глубина — глубина элемента у писателя:
//!   `d1p1` у корня документа, `d2p1` у второго уровня, `d3p1` у третьего.
//!   Выбор имени элемента подчиняется одному правилу: побеждает САМОЕ
//!   ВНУТРЕННЕЕ объявление, а внутри одного элемента умолчательное идёт
//!   перед префиксным. Отсюда и `<к xmlns="urn:test" xmlns:d1p1="urn:test"
//!   … d1p1:qa="де">` с обычным `<name>`, и `<d2p1:nested
//!   xmlns:d2p1="urn:test" d2p1:qi="х">` с `<d2p1:in>` внутри;
//! * **лексические формы записи.** `xs:date` — `2026-08-13` (время
//!   отбрасывается), `xs:dateTime` — всегда с секундами
//!   (`2026-08-13T00:00:00`), `xs:time` — `10:20:30`, десятичное — с
//!   точкой и без хвостовых нулей (12,50 -> `12.5`, 1/3 ->
//!   `0.333333333333333333333333333`), `xs:double` — тоже без показателя
//!   степени (1E20 -> `100000000000000000000`), булево — `true`/`false`,
//!   `hexBinary` — ЗАГЛАВНЫМИ и одной строкой, `base64Binary` — строками
//!   по 64 символа через CR LF (48 байт дают ровно 64 символа без
//!   переноса, 49 — уже с переносом), значение списочного простого типа —
//!   формы элементов через пробел (`1 2 3`). Пустая строка даёт
//!   схлопнутый `<name/>`;
//! * **порядок свойств при записи** зависит от типа: у УПОРЯДОЧЕННОГО он
//!   модельный (заполненные как `num`, потом `name`, вышли как `name`,
//!   потом `num`), у ПОСЛЕДОВАТЕЛЬНОГО — порядок заполнения (у
//!   `xs:choice` `cb`, `ca`, `cb` вышли ровно так). Незаполненное свойство
//!   не пишется вовсе, и значение по умолчанию за него не подставляется:
//!   пустой экземпляр даёт `<к …/>`. Проверок при записи нет никаких —
//!   недозаполненный объект пишется молча;
//! * **`xsi:type` при записи** появляется там, где объявленный тип —
//!   ОБЪЕКТНЫЙ, а фактический другой: наследник в свойстве
//!   (`<nested xsi:type="InnerExt">`) и любое значение в свойстве
//!   `anyType`, где тип берётся у самого значения BSL — строка ->
//!   `xs:string`, число -> `xs:decimal`, булево -> `xs:boolean`, дата ->
//!   `xs:dateTime`, двоичные данные -> `xs:base64Binary`, экземпляр ->
//!   его собственный тип. У свойства ПРОСТОГО типа пометки не бывает
//!   никогда: число в свойстве `xs:int` пишется как `<num>42</num>`;
//! * **круг устойчив со второго прохода**: чтение с типом и обратная
//!   запись дают документ, который читается и пишется уже без изменений
//!   («Да» на платформе). Первый проход канонизует лексику — `12.50`
//!   становится `12.5`.
//!
//! Отдельная сознательная граница ввода-вывода — ЧТЕНИЕ БЕЗ ТИПА. Оно
//! измерено полностью (см. выше), но открытое содержимое `anyType`
//! потребовало бы свойств, заводимых на самом экземпляре, а вся модель
//! здесь неизменяема и разделяется фабрикой. Молчаливая подмена открытого
//! разбора разбором по схеме дала бы ДРУГОЙ результат — строки вместо
//! чисел и терпимость к постороннему элементу, — поэтому вызов с одним
//! аргументом отвечает честной ошибкой. То же и с элементом типа
//! `anyType` внутри документа: измеренный случай (текст, читаемый строкой)
//! поддержан, а вложенные элементы и атрибуты в нём — отказ.
//!
//! # `СериализаторXDTO`: что ИЗМЕРЕНО
//!
//! Пробы — `tests/conformance/measure/measure-xdto-serializer.bsl`, рядом
//! снятый `measure-xdto-serializer.platform.txt`; фикстура —
//! `tests/conformance/fixtures/xdto-serializer.bsl`. Всё снято через
//! фабрику из ФАЙЛА XSD, то есть без единого типа конфигурации.
//!
//! * **конструктор берёт ровно фабрику.** `Новый СериализаторXDTO(Фаб)`
//!   (и `Новый XDTOSerializer(Фаб)`) — единственная работающая форма: без
//!   аргумента платформа отвечает «Конструктор не найден», а два
//!   аргумента, строку, число и тип XDTO отвергает. `Тип(
//!   "СериализаторXDTO")` и `Тип("XDTOSerializer")` дают «Сериализатор
//!   XDTO», `Строка()` — `СериализаторXDTO`, `ЗначениеЗаполнено` от него —
//!   ошибка («Проверка мутабельных значений на заполненность не
//!   поддерживается»), два сериализатора над одной фабрикой НЕ равны;
//! * **свойства `ФабрикаXDTO` у него НЕТ.** Ни русского, ни английского:
//!   «Поле объекта не обнаружено (ФабрикаXDTO)». Справка называет такой
//!   член, платформа — нет; тот же случай, что `ФорматСериализацииДаты` в
//!   этапе 0. Наружу торчат только методы;
//! * **`ЗаписатьXML(ЗаписьXML, Значение[, Имя[, УРИ]])`** — от двух до
//!   четырёх аргументов (`WriteXML` тоже есть), пятый отвергается. Имя и
//!   URI ведут себя НЕ как у фабрики: пустое имя и `Неопределено` вместо
//!   него значат «имя по умолчанию» (а не ошибку), пустое имя отбрасывает
//!   ЗАОДНО и заданный URI, заданное имя без URI сбрасывает пространство
//!   имён в пустое (`<мой xmlns="">`), а имя с двоеточием пишется как
//!   есть — `<t:мой xmlns="">` с необъявленным префиксом, там, где
//!   фабрика двоеточие отвергает. Нестроковые имя и URI — ошибка. Ровно
//!   одно сочетание выпадает из этой сетки: имя `Неопределено` ВМЕСТЕ с
//!   URI-строкой платформа отвергает — «Несоответствие типов (параметр
//!   номер '4')», — притом что пустое имя с тем же URI проходит, а
//!   `Неопределено` в обоих аргументах сразу снова даёт умолчание;
//! * **`xmlns:xsi` объявляется всегда, кроме одного случая**: когда
//!   умолчательным стало само пространство экземпляров XML Schema
//!   (`ЗаписатьXML(Зп, 42, "мой", "…XMLSchema-instance")` ->
//!   `<мой xmlns="…instance" xmlns:xs="…">42</мой>`). Если при этом нужна
//!   пометка `nil`, платформа заводит для ТОГО ЖЕ URI порождённый префикс
//!   и метит атрибут им — `xmlns:d1p1="…instance" d1p1:nil="true"`, а на
//!   втором уровне `d2p1`, то есть по общему правилу `d<глубина>p<номер>`;
//! * **элемент значения** — это локальное имя его типа XML в
//!   умолчательном пространстве имён этого типа: число ->
//!   `<decimal xmlns="…XMLSchema" xmlns:xsi="…instance">42</decimal>`,
//!   строка -> `<string>`, дата -> `<dateTime>` (всегда с секундами),
//!   булево -> `<boolean>`, двоичные данные -> `<base64Binary>` строками
//!   по 64 символа. Правило объявлений то же, что у записи фабрики: `xs`
//!   не объявляется, когда пространство XML Schema и так умолчательное.
//!   Лексические формы — те же, что у фабрики (`12.50` -> `12.5`, `1/3` ->
//!   27 знаков, пустая строка -> схлопнутый `<string/>`);
//! * **`Неопределено` и `Null` пишутся, а коллекции — нет.**
//!   `Неопределено` -> `<Undefined xmlns="" … xsi:nil="true"/>` (именно с
//!   ПУСТЫМ пространством имён, хотя `Тип("Неопределено")` та же платформа
//!   пишет как `{http://v8.1c.ru/8.2/data/types}Undefined`), `Null` ->
//!   `<Null xmlns="http://v8.1c.ru/8.1/data/core"/>`. А `Массив`,
//!   `Структура`, `Соответствие` и `ТаблицаЗначений` через фабрику из XSD
//!   она уже отвергает — «Несоответствие типов (параметр номер '2')», —
//!   притом что ГЛОБАЛЬНЫЙ сериализатор конфигурации пишет тот же массив
//!   как `<Array xmlns="http://v8.1c.ru/8.1/data/core">` со вложенными
//!   `<Value xsi:type="xs:decimal">`. Разница — ровно в метаданных
//!   конфигурации, и отказ здесь называет её вслух;
//! * **`ПрочитатьXML(ЧтениеXML[, Тип])`** — один или два аргумента
//!   (`ReadXML` тоже есть), третий отвергается («Слишком много фактических
//!   параметров»). Второй аргумент — значение `Тип` (тип BSL), и он
//!   отменяет имя элемента: `<int>42</int>` с `Тип("Число")` даёт 42.
//!   Отображения нет у `Тип("Массив")`, `Тип("УникальныйИдентификатор")` и
//!   `Тип("Неопределено")` — «Отсутствует отображение для типа»;
//! * **без типа решает имя элемента**, и всё, чего в модели фабрики нет,
//!   читается СТРОКОЙ: `<чужой>привет</чужой>` -> «привет», `<decimal>` БЕЗ
//!   пространства имён -> «42», а `{…/data/core}UUID`, `Null` и `Type` ->
//!   свои тексты строкой. Отсюда и несимметричный круг: `Null`,
//!   `УникальныйИдентификатор` и `Тип` записываются, но обратно приходят
//!   строками (измерено). Составной тип схемы, наоборот, ошибка:
//!   `<RootType xmlns="urn:test">` -> «Отсутствует отображение для типа
//!   '{urn:test}RootType'», и то же самое у типа с ПРОСТЫМ содержимым
//!   (`{urn:test}SimpContent`). А вот СВОЙ простой тип схемы читается
//!   своим отображением: `<Code xmlns="urn:test">аб</Code>` (ограничение
//!   `xs:string`) даёт строку, и через `xsi:type="t:Code"` — тоже. Одно
//!   расхождение здесь не новое: списочный простой тип платформа отдаёт
//!   `ФиксированныйМассив`, а тут получается обычный `Массив` — то же, что
//!   описано у `value_from_lexical_at`;
//! * **`xsi:nil="true"` перевешивает имя** — и у известного типа, и у
//!   чужого — и даёт `Неопределено`; без пометки тот же `<Undefined/>` —
//!   просто пустая строка. **`xsi:type` у сериализатора действует ПРЯМО на
//!   читаемом элементе** (в отличие от фабрики, где на нём он не значит
//!   ничего), а неизвестное имя типа платформа молча игнорирует;
//! * **позиция читателя та же, что у фабрики**: разбор идёт с первого
//!   начального тега и оставляет читателя на следующем узле, так что два
//!   соседних элемента читаются двумя вызовами без `Прочитать()` между
//!   ними, а после корня читатель исчерпан.
//!
//! Сознательно за бортом этой задачи — четыре измеренных члена и один тип
//! значений:
//!
//! * `XMLТип`/`XMLType`, `XMLТипЗнч`/`XMLTypeOf` и
//!   `ВозможностьЧтенияXML`/`CanReadXML` существуют, но упираются в
//!   РАЗНОЕ. Первые два отдают `ТипДанныхXML` (у строки — `string`
//!   пространства XML Schema, у числа — `decimal`, у даты — `dateTime`),
//!   и реализовать их — значит сперва завести этот тип, а это отдельная
//!   работа. Третий отдаёт БУЛЕВО: «Да» на `<decimal>` этого пространства,
//!   «Нет» на чужое имя и на читателя, ещё не сделавшего `Прочитать()`, —
//!   нового типа ему не нужно, и не поддержан он по объёму задачи: трёх
//!   точек мало, чтобы знать, когда именно платформа отвечает «Да». Вызов
//!   любого из трёх даёт перехватываемую ошибку «не поддерживается» с той
//!   причиной, которая у него настоящая, а не тишину;
//! * `XMLСтрока`/`XMLString`, `XMLЗначение`/`XMLValue`,
//!   `ЗаписатьJSON`/`WriteJSON` и `ПрочитатьJSON`/`ReadJSON` у
//!   сериализатора тоже есть (измерено: `XMLСтрока(Дата(2026,8,13,10,20,30))`
//!   — `2026-08-13T10:20:30`, `XMLСтрока(12.50)` — `12.5`,
//!   `ЗаписатьJSON(Зп, 42)` — `{"#value": 42}`). В таблицу методов они не
//!   заводились: в отличие от трёх названных выше, задача их не касается,
//!   и имя, которого в таблице нет, отвергается на разборе;
//! * значение `Тип` платформа пишет как `<Type
//!   xmlns="http://v8.1c.ru/8.1/data/core">xs:decimal</Type>`, порождая
//!   при надобности префикс для чужого пространства (`Тип("Неопределено")`
//!   -> `d1p1:Undefined` при `xmlns:d1p1="http://v8.1c.ru/8.2/data/types"`).
//!   Здесь его нет: полное отображение типов BSL в имена XML замером не
//!   снято, а угадывать дороже, чем отказать. `УникальныйИдентификатор`
//!   пишется как `<UUID xmlns="…/data/core">`, но такого типа в этом
//!   рантайме пока нет вовсе, так что писать нечего.
//!
//! Единственное, что тут осталось неизмеренным, — нумерация ВТОРОГО
//! порождённого префикса на одном элементе, `НЕ ИЗМЕРЕНО(XDTO.IO.PREFIX)`:
//! чтобы её увидеть, нужен тип с двумя квалифицированными атрибутами из
//! РАЗНЫХ пространств имён, а это требует межсхемной ссылки, которой у
//! `СоздатьФабрикуXDTO` (один файл XSD) взять неоткуда.

