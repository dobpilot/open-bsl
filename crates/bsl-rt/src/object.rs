/// Объекты BSL — `enum`, а не vtable: тонкий указатель (`Rc<BslObject>`) и
/// исчерпывающий `match` вместо динамической диспетчеризации. Управление
/// памятью — счётчик ссылок (`Rc`), не GC: `Clone` — retain, `Drop` —
/// release, и это совместимость с 1С (там утечки циклов наблюдаемы), а не
/// компромисс производительности.
///
/// Мутабельность — через `RefCell`: массивы/структуры в BSL — ссылочные
/// типы (`b = a` делает `b` тем же объектом, что и `a`, а не копией), и
/// методы `BslValue::get_index`/`set_index`/... поэтому берут `&self`, а не
/// `&mut self`.
#[derive(Debug)]
pub enum BslObject {
    Array(RefCell<Vec<BslValue>>),
    Structure(RefCell<StructureStorage>),
    ValueTable(Rc<RefCell<ValueTableData>>),
    /// `Таблица.Колонки` — отдельный объект-обёртка над теми же данными
    /// (тот же `Rc<RefCell<...>>`), только чтобы `.Добавить(имя)` на нём
    /// означало "добавить колонку", а не "добавить строку" — то же имя
    /// метода, разное поведение в зависимости от того, что за объект.
    TableColumns(Rc<RefCell<ValueTableData>>),
    /// Элемент `Таблица.Колонки`. Имя служит устойчивым идентификатором:
    /// добавление соседних колонок не должно менять уже полученный объект.
    TableColumn(Rc<RefCell<ValueTableData>>, String),
    /// Живёт независимо от текущей позиции строки в колонках — см.
    /// `ValueTableData::pos_of`. `row_id` может перестать резолвиться
    /// после `Удалить`/`Очистить`.
    TableRow(Rc<RefCell<ValueTableData>>, u64),
    /// `ОписаниеТипов` в поддержанном подмножестве хранит перечисленные
    /// зарегистрированные типы. Ограничение значений колонки пока не
    /// применяется: объект нужен метаданным колонки и её конструктору.
    TypeDescription(Vec<crate::TypeId>),
    /// `СравнениеЗначений` — стратегия стандартного сравнения платформы,
    /// передаваемая вторым аргументом в `ТаблицаЗначений.Сортировать`.
    ValueComparison,
    /// `Соответствие`. Ключ — любое значение (см. `impl Hash for
    /// BslValue`), а не только `Строка`/`Число` — как и в самой 1С.
    Map(RefCell<MapData>),
    /// Элемент `Для Каждого` по `Соответствие` (`КлючИЗначение.Ключ`/
    /// `.Значение`). Не структура с интернированной формой: поля здесь
    /// всегда ровно эти два и известны только рантайму, резолвятся строкой
    /// через `get_field_by_name` — тем же путём, что и колонки
    /// `СтрокаТаблицыЗначений`, а не через `Shape`/`NameId`.
    KeyValuePair(BslValue, BslValue),
    /// Буферизованный `ЗаписьТекста`; `None` после `Закрыть()`.
    TextWriter(RefCell<Option<BufWriter<File>>>),

    /// `ДвоичныеДанные` — ИММУТАБЕЛЬНЫЙ буфер байтов, поэтому без
    /// `RefCell`: менять содержимое платформа не даёт, всякая операция
    /// (`РазделитьДвоичныеДанные`, `СоединитьДвоичныеДанные`) отдаёт новое
    /// значение. `Rc<[u8]>` вместо `Vec<u8>` ровно за этим: раз содержимое
    /// не меняется, копия значения — это счётчик ссылок, а не копия байтов.
    ///
    /// Равенство ПО СОДЕРЖИМОМУ, а не по тождеству объекта — измерено:
    /// два `Новый ДвоичныеДанные` от одного файла равны, от разных файлов
    /// нет. Отсюда же и хэш по байтам (см. `impl Hash for BslValue`).
    BinaryData(Rc<[u8]>),

    /// `БуферДвоичныхДанных` — ПРОТИВОПОЛОЖНОСТЬ соседа сверху: изменяемый
    /// буфер фиксированного размера, поэтому `Rc<RefCell<..>>`, а не
    /// `Rc<[u8]>`. Равенство здесь ПО ТОЖДЕСТВУ, а не по содержимому
    /// (измерено: два свежих нулевых буфера одного размера не равны), и
    /// потому отдельной ветки в `PartialEq`/`Hash` у него нет — работает
    /// общий путь через `Rc::ptr_eq`.
    BinaryBuffer(Rc<RefCell<crate::binbuf::BinBufData>>),
    /// `УникальныйИдентификатор` — шестнадцать байтов UUID. Иммутабельное
    /// значение: равенство по байтам, печать канонической формой нижнего
    /// регистра (см. `crate::uuid`).
    Uuid([u8; 16]),

    /// `ПотокВПамяти` и `ФайловыйПоток` — состояние у них ОБЩЕЕ
    /// (`StreamData`: носитель, позиция, три признака доступности), а
    /// различает их только тег объекта: у платформы это разные типы
    /// (`Тип("ПотокВПамяти") = Тип("ФайловыйПоток")` — «Нет», измерено), и
    /// держать различие здесь дешевле, чем читать поле через `RefCell` в
    /// каждом `ТипЗнч`. Равенство — по тождеству, общим путём через
    /// `Rc::ptr_eq`, как у буфера.
    MemoryStream(Rc<RefCell<crate::stream::StreamData>>),
    FileStream(Rc<RefCell<crate::stream::StreamData>>),
    /// Менеджер `ФайловыеПотоки` — значение БЕЗ состояния: все его методы
    /// открывают новый поток по имени файла. Каждое обращение к голому
    /// имени строит новый такой объект, потому что `ФайловыеПотоки =
    /// ФайловыеПотоки` платформа считает ложью (измерено).
    FileStreamsManager,

    /// `ЧтениеДанных` и `ЗаписьДанных` — состояние у них ОБЩЕЕ
    /// (`DataRwState`: целевой поток, ожидаемая позиция, кодировка, порядок
    /// байтов, разделитель строк), а различает их только тег объекта: у
    /// платформы это разные типы (`Тип("ЧтениеДанных") = Тип("ЗаписьДанных")`
    /// — «Нет», измерено), и от стороны зависят и набор методов, и текст
    /// ошибки при постороннем сдвиге целевого потока. Равенство — по
    /// тождеству, общим путём через `Rc::ptr_eq`, как у потоков.
    DataReader(Rc<RefCell<crate::datarw::DataRwState>>),
    DataWriter(Rc<RefCell<crate::datarw::DataRwState>>),
    /// `РезультатЧтенияДанных` — то, что отдаёт `ЧтениеДанных.Прочитать`.
    /// Иммутабельный снимок прочитанных байтов, поэтому `Rc<[u8]>` без
    /// `RefCell`, как у `ДвоичныеДанные`: у него есть только свойство
    /// `Размер` и два геттера, ни один из которых его не меняет.
    DataReadResult(Rc<[u8]>),

    /// Непрозрачное значение внутреннего формата (`ЗначениеИзСтрокиВнутр`):
    /// вид, который эта реализация не материализует — ссылки объектов базы
    /// (`СправочникСсылка`, `ДокументСсылка`, `ПеречислениеСсылка`),
    /// `СписокЗначений`, `УникальныйИдентификатор`, неизвестные `{"T",…}`.
    /// Хранится КАНОНИЧЕСКИ ОТРИСОВАННОЕ поддерево исходного текста и при
    /// обратной сериализации возвращается байт в байт — так значения
    /// неподдержанных типов переживают транзит 1С -> open-bsl -> 1С без
    /// потерь. Никаких операций над таким значением нет: только хранение,
    /// сравнение на равенство (по тексту) и обратная запись.
    VstrOpaque(String),

    /// `ЧтениеJSON`. Разборщик появляется только после
    /// `УстановитьСтроку`/`ОткрытьФайл` — до этого читать нечего, и
    /// платформа на попытку тоже отвечает ошибкой.
    JsonReader(RefCell<JsonReaderState>),
    /// `ЗаписьJSON`. Так же: приёмник назначается отдельным вызовом.
    JsonWriter(RefCell<Option<crate::json::JsonWriter>>),
    /// `ПараметрыЗаписиJSON` — простой набор значений, менять его после
    /// создания незачем, поэтому без `RefCell`.
    JsonWriterSettings(crate::json::JsonWriterSettings),
    /// `НастройкиСериализацииJSON` (третий аргумент `ЗаписатьJSON`) —
    /// в отличие от `JsonWriterSettings` её поля ЧИТАЮТСЯ И ПИШУТСЯ через
    /// точку (`Настройки.ФорматСериализацииДат = ...`) уже после создания
    /// объекта, поэтому под `RefCell`.
    JsonSerializerSettings(RefCell<crate::json::JsonSerializerSettings>),

    /// `ЧтениеXML`. Как и у JSON, разборщик появляется только после
    /// `УстановитьСтроку`/`ОткрытьФайл`.
    XmlReader(RefCell<XmlReaderState>),
    /// `ЗаписьXML`.
    XmlWriter(RefCell<Option<crate::xml::XmlWriter>>),
    /// `ПараметрыЗаписиXML`.
    XmlWriterSettings(crate::xml::XmlWriterSettings),

    /// `ПостроительDOM` — состояния у него нет: документ строится из
    /// переданного `ЧтениеXML`, а сам построитель переиспользуется
    /// (измерено: два `Прочитать` с РАЗНЫМИ читателями дают два дерева).
    DomBuilder,
    /// Любой узел дерева DOM: документ, элемент, атрибут, текст,
    /// комментарий, инструкция обработки. Вид узла и, значит, имя типа
    /// решает `DomNode::kind`. Обёртка каждый раз новая, но равенство
    /// узлов идёт по первому `Rc` — так же, как у платформы.
    ///
    /// Второй `Rc` — ДОКУМЕНТ этого узла (у самого документа — тот же
    /// `Rc` дважды). Он держит дерево живым, пока жив хоть один узел из
    /// него: внутри дерева ссылки вверх слабые, поэтому без этой сильной
    /// ссылки функция вида `Возврат Док.ЭлементДокумента` возвращала бы
    /// корень с уже освобождённым документом, а `РодительскийУзел` и
    /// `ДокументВладелец` у него молча становились бы `Неопределено`.
    /// Цикла `Rc` тут нет: ссылка лежит в ЗНАЧЕНИИ, снаружи дерева.
    DomNode(Rc<crate::dom::DomNode>, Rc<crate::dom::DomNode>),
    /// `ЗаписьDOM` — состояния у него, как и у построителя, нет: приёмник
    /// (`ЗаписьXML`) и узел приходят аргументами `Записать`, а сам писатель
    /// переиспользуется.
    DomWriter,
    /// `СписокУзловDOM`, `КоллекцияАтрибутовDOM` и `СписокЭлементовDOM` —
    /// разные ОБЪЕКТЫ на каждое обращение
    /// (`Э.ДочерниеУзлы = Э.ДочерниеУзлы` — «Нет», измерено), но не
    /// обязательно снимки: см. `dom::DomListKind`, где измерено, что
    /// дети и атрибуты — живые окна, а результат поиска — снимок. Третье поле — документ, по той же причине, что и у
    /// `DomNode`: пустой список тоже обязан помнить, из какого он дерева.
    DomList(crate::dom::DomListKind, Rc<crate::dom::DomNode>),

    /// `РазыменовательПространствИменDOM` — узел, чью область видимости он
    /// показывает, вместе с документом. Область видимости берётся с узла в
    /// момент ЗАПРОСА, а не запоминается: объявления `xmlns` — обычные
    /// атрибуты, и дерево между запросами могло измениться.
    XPathResolver(Rc<crate::xpath::XPathResolver>),
    /// `ВыражениеXPath` — разобранный текст выражения со своим
    /// разыменователем. Разбор происходит один раз, при создании: измерено,
    /// что негодный синтаксис платформа ловит именно там.
    XPathExpression(Rc<crate::xpath::XPathExpression>),
    /// `РезультатXPath` — СНИМОК вычисления: набор узлов (либо число,
    /// строка, булево) плюс курсор обхода. Снимок, а не живое окно:
    /// измерено, что добавленный после вычисления узел в обход не попадает.
    XPathResult(Rc<crate::xpath::XPathResult>),

    /// `РезультатПоискаПоРегулярномуВыражению` — СНИМОК одного совпадения
    /// вместе с его группами. Снимок, а не окно в исходную строку: объект
    /// платформы переживает её и сериализуется, а `Значение` у него —
    /// обычная строка.
    RegexMatch(Rc<crate::regex_api::RegexMatchData>),
    /// `ГруппаРезультатаПоискаПоРегулярномуВыражению` — номер группы
    /// внутри того же снимка, а не отдельная копия: у платформы группа
    /// живёт ровно столько, сколько результат, из которого она получена, и
    /// пары «данные + номер» для этого достаточно.
    RegexGroup(Rc<crate::regex_api::RegexMatchData>, usize),

    /// `ПостроительСхемXML` — состояния у него нет, как и у построителя
    /// DOM: схему целиком строит `СоздатьСхемуXML` из переданного дерева.
    XsBuilder,
    /// `НаборСхемXML` — схемы по одной на пространство имён (измерено:
    /// вторая схема того же пространства — ошибка, а та же самая повторно
    /// — молча ничего).
    XsSchemaSet(Rc<RefCell<Vec<Rc<crate::xsd::XsSchemaData>>>>),
    /// Любая компонента схемы: сама схема (номер 0), объявление, тип,
    /// фрагмент, группа модели, использование атрибута, фасет, аннотация.
    /// Схема держится целиком одним `Rc`, а компонента — это номер узла в
    /// ней; отсюда и тождество компонент (измерено: два `Получить("root")`
    /// равны), и то, что дерево живо, пока жива хоть одна компонента.
    XsComponent(Rc<crate::xsd::XsSchemaData>, usize),
    /// `ФиксированныйСписокКомпонентXS`, `СписокКомпонентXS` и
    /// `КоллекцияИменованныхКомпонентXS` — вид решает `XsListKind`.
    XsList(Rc<crate::xsd::XsSchemaData>, crate::xsd::XsListKind),
    /// `РасширенноеИмяXML` — тип ЗНАЧЕНИЯ: два имени с одинаковыми URI и
    /// локальным именем равны (измерено).
    XmlExpandedName(Rc<crate::xsd::XName>),
    /// `СписокРасширенныхИменXML` — `ИменаТиповОбъединения` простого типа.
    XmlExpandedNameList(Rc<Vec<crate::xsd::XName>>),

    /// `ТипЗначенияXDTO` или `ТипОбъектаXDTO` — модель типов целиком плюс
    /// номер типа в ней. Разницу между двумя типами несёт сама модель, а
    /// не вариант: тождество типа — это пара «та же модель, тот же
    /// номер» (измерено: два обращения к `Тип` за одним именем равны).
    XdtoType(Rc<crate::xdto::XdtoModel>, usize),
    /// `СвойствоXDTO` — номер свойства в той же модели.
    XdtoProperty(Rc<crate::xdto::XdtoModel>, usize),
    /// `КоллекцияСвойствXDTO` — свойства одного типа объекта.
    XdtoProperties(Rc<crate::xdto::XdtoModel>, usize),
    /// `КоллекцияФасетовXDTO` — фасеты одного типа значения.
    XdtoFacets(Rc<crate::xdto::XdtoModel>, usize),
    /// `ФасетXDTO` — номер фасета внутри типа значения.
    XdtoFacet(Rc<crate::xdto::XdtoModel>, usize, usize),
    /// `ЗначениеXDTO` — значение вместе с лексической формой, из которой
    /// оно построено. Модель нужна ему собственным членом: свой тип оно
    /// отдаёт методом `Тип()` (измерено), а сама пара «значение,
    /// лексическая форма» лежит и в свойстве типа как значение по
    /// умолчанию, куда модель ещё не построена.
    XdtoValue(Rc<crate::xdto::XdtoModel>, Rc<crate::xdto::XdtoValueData>),
    /// `ФабрикаXDTO` — разрешённая модель типов целиком. Именно СНИМОК, а
    /// не ссылка на набор схем: схема, добавленная в набор после создания
    /// фабрики, ей уже не видна (измерено). Равенство — по тождеству, общим
    /// путём через `Rc::ptr_eq`: две фабрики от одного файла платформа
    /// равными не считает (измерено).
    XdtoFactory(Rc<crate::xdto::XdtoModel>),
    /// `СериализаторXDTO` — та же модель типов, взятая с другой стороны:
    /// фабрика отвечает про типы и экземпляры XDTO, а сериализатор
    /// переводит через неё значения BSL. Модель здесь тоже СНИМОК, потому
    /// что фабрика в конструкторе обязательна и другой у сериализатора
    /// уже не будет (измерено: `Новый СериализаторXDTO` без аргумента —
    /// «Конструктор не найден»). Своей фабрики он не показывает: члена
    /// `ФабрикаXDTO` у 8.3.27 нет (измерено — «Поле объекта не
    /// обнаружено»), поэтому наружу торчат только два метода.
    XdtoSerializer(Rc<crate::xdto::XdtoModel>),
    /// `ОбъектXDTO` — экземпляр типа объекта: модель, номер типа и
    /// ХРАНИЛИЩЕ заполненных свойств (см. [`crate::XdtoObjectData`]).
    /// Равенство идёт по `Rc` этого хранилища, а не по обёртке: чтение
    /// свойства строит новое значение каждый раз, а измерено, что
    /// `О.anon = А; О.anon = А` — «Да».
    XdtoObject(Rc<crate::xdto::XdtoObjectData>),
    /// `СписокXDTO` — ОКНО в хранилище владельца: экземпляр плюс номер
    /// множественного свойства. Не снимок: `С = О.code; С.Добавить(...)`
    /// видно через `О.code` (измерено), а два отдельных чтения
    /// `О.code = О.code` дают «Да» — отсюда пара «то же хранилище, то же
    /// свойство» вместо собственных данных.
    XdtoList(Rc<crate::xdto::XdtoObjectData>, usize),
    /// `ПоследовательностьXDTO` — тоже окно в хранилище владельца, но по
    /// всем свойствам-ЭЛЕМЕНТАМ сразу, в порядке заполнения. Есть только у
    /// последовательного типа: у упорядоченного `Последовательность()` —
    /// это `Неопределено` (измерено).
    XdtoSequence(Rc<crate::xdto::XdtoObjectData>),

    /// `ТабличныйДокумент`.
    SpreadDocument(Rc<RefCell<crate::spreadsheet::SpreadDocData>>),
    /// `ОбластьЯчеекТабличногоДокумента` — ССЫЛКА на прямоугольник в том же
    /// документе, а не копия: `Область(1,1,1,1).Текст = "A"` меняет сам
    /// документ (измерено). Копию отдаёт только `ПолучитьОбласть`.
    SpreadArea(
        Rc<RefCell<crate::spreadsheet::SpreadDocData>>,
        crate::spreadsheet::Rect,
    ),

    /// `КоллекцияРисунковТабличногоДокумента` — обёртка над теми же
    /// данными, как `Таблица.Колонки`.
    SpreadDrawings(Rc<RefCell<crate::spreadsheet::SpreadDocData>>),
    /// `РисунокТабличногоДокумента` — документ и НОМЕР рисунка в нём.
    SpreadDrawing(Rc<RefCell<crate::spreadsheet::SpreadDocData>>, usize),

    /// `ТекстовыйДокумент`.
    TextDocument(Rc<RefCell<crate::textdoc::TextDocData>>),
    /// `Документ.Параметры` — отдельный объект-обёртка над ТЕМИ ЖЕ данными
    /// (тот же `Rc`), как `Таблица.Колонки`: присваивание в его поле
    /// означает «задать параметр макета», а не «положить поле объекта».
    TextDocParams(Rc<RefCell<crate::textdoc::TextDocData>>),

    /// `ДокументPDF` — разобранный файл PDF либо пусто, пока не было
    /// `Прочитать`. Три вида ниже делят ОДНО состояние: коллекция и
    /// страница — окна в тот же документ, как `Таблица.Колонки`, поэтому
    /// перечитанный документ меняет и их.
    PdfDocument(Rc<RefCell<crate::pdf::PdfDocState>>),
    /// `КоллекцияСтраницPDF` — окно в тот же документ.
    PdfPages(Rc<RefCell<crate::pdf::PdfDocState>>),
    /// `СтраницаPDF` — то же состояние плюс НОМЕР страницы с нуля, как у
    /// `SpreadDrawing`. Равенство — по паре «тот же документ, тот же
    /// номер» (измерено: `Страницы[0] = Страницы[0]` — «Да», а
    /// `Страницы[0] = Страницы[1]` — «Нет»).
    PdfPage(Rc<RefCell<crate::pdf::PdfDocState>>, usize),
    /// `КоллекцияВложенийPDF` — вектор вложений, ОБЩИЙ с документом, если
    /// коллекция получена из него. Отдельным `Rc` она бывает и сама по
    /// себе: `Новый КоллекцияВложенийPDF` платформа строит (измерено), а
    /// присоединить готовую коллекцию к документу нечем.
    PdfAttachments(Rc<RefCell<Vec<crate::pdf::PdfAttachment>>>),
    /// `ВложениеPDF` — тот же вектор плюс НОМЕР вложения с нуля, как у
    /// `PdfPage`. Значение изменяемое: все четыре свойства пишутся.
    PdfAttachment(Rc<RefCell<Vec<crate::pdf::PdfAttachment>>>, usize),

    /// `ЧтениеZipФайла` либо `ЧтениеФайлаАрхива` — состояние у них ОБЩЕЕ
    /// ([`crate::zip::ArchiveState`]: байты архива, комментарий и
    /// разобранные элементы), а различает их тег: у платформы это разные
    /// типы с разными именами коллекции и элемента, но с одной
    /// поверхностью (измерено). Равенство — по тождеству, общим путём
    /// через `Rc::ptr_eq`.
    ArchiveReader(
        crate::zip::ArchiveKind,
        Rc<RefCell<crate::zip::ArchiveState>>,
    ),
    /// `ЭлементыZipФайла` / `ЭлементыФайлаАрхива` — обёртка над ТЕМ ЖЕ
    /// состоянием, как `Таблица.Колонки`: коллекция не снимок, а окно в
    /// открытый архив, и после `Закрыть` она отвечает той же ошибкой, что
    /// и сам читатель.
    ArchiveEntries(
        crate::zip::ArchiveKind,
        Rc<RefCell<crate::zip::ArchiveState>>,
    ),
    /// `ЭлементZipФайла` / `ЭлементФайлаАрхива` — то же состояние плюс
    /// НОМЕР записи в каталоге, как у `SpreadDrawing`, и номер открытия, при
    /// котором элемент выдан. Номер записи устойчив только внутри ОДНОГО
    /// открытия: `Закрыть` с последующим `Открыть` оставляют то же
    /// состояние, но состав архива меняется целиком, поэтому элемент от
    /// предыдущего открытия отвергается по несовпадению номера открытия, а
    /// не обслуживается по номеру записи.
    ArchiveEntry(
        crate::zip::ArchiveKind,
        Rc<RefCell<crate::zip::ArchiveState>>,
        usize,
        u64,
    ),
    /// `ЗаписьZipФайла` либо `ЗаписьФайлаАрхива` — тот же приём с тегом,
    /// что у читателей: типы у платформы разные (`Тип("ЗаписьZipФайла") =
    /// Тип("ЗаписьФайлаАрхива")` — «Нет»), а поверхность одна, и тег решает
    /// имя типа и хвост аргументов конструктора. Коллекции элементов у
    /// писателя НЕТ: свойства `Элементы` и `Комментарий` платформа у него
    /// не знает вовсе (измерено).
    ArchiveWriter(
        crate::zip::ArchiveKind,
        Rc<RefCell<crate::zip::WriterState>>,
    ),
}

/// Состояние `ЧтениеXML`.
///
/// Кроме текущего события хранится ещё две вещи, и обе — из-за того, что у
/// платформы курсор один на две сущности. `attr_cursor` — позиция обхода
/// `ПрочитатьАтрибут`: пока он стоит на атрибуте, `ТипУзла`, `Имя` и
/// `Значение` показывают АТРИБУТ, а не сам элемент (измерено). `depth` —
/// глубина открытых элементов на момент текущего события: по ней
/// `Пропустить` понимает, до какого закрывающего тега глотать, и она обязана
/// быть снята ДО того, как разборщик уйдёт вперёд.
#[derive(Debug, Default)]
pub struct XmlReaderState {
    pub parser: Option<crate::xml::XmlParser>,
    pub current: Option<crate::xml::XmlEvent>,
    pub attr_cursor: Option<usize>,
    pub depth: usize,
}

impl XmlReaderState {
    /// Свежее состояние над готовым разборщиком.
    pub fn over(parser: crate::xml::XmlParser) -> Self {
        XmlReaderState {
            parser: Some(parser),
            current: None,
            attr_cursor: None,
            depth: 0,
        }
    }

    /// Атрибуты текущего узла; у неэлементного узла их нет.
    pub fn attrs(&self) -> &[crate::xml::XmlAttr] {
        match &self.current {
            Some(crate::xml::XmlEvent::ElementStart { attrs, .. }) => attrs.as_slice(),
            _ => &[],
        }
    }

    /// Атрибут, на котором стоит курсор `ПрочитатьАтрибут`.
    pub fn current_attr(&self) -> Option<&crate::xml::XmlAttr> {
        self.attr_cursor.and_then(|i| self.attrs().get(i))
    }
}

/// Состояние `ЧтениеJSON`: сам разборщик и последнее прочитанное событие.
///
/// Событие хранится, потому что `ТипТекущегоЗначения` и `ТекущееЗначение`
/// — СВОЙСТВА, а не результат `Прочитать()`: читатель обязан помнить, где
/// он стоит, между двумя обращениями к нему.
#[derive(Debug, Default)]
pub struct JsonReaderState {
    pub parser: Option<crate::json::JsonParser>,
    pub current: Option<crate::json::JsonEvent>,
}

/// Хранение полей `Структура` — двухрежимное, как в V8.
///
/// `Shaped` — быстрый путь: имя поля резолвится в номер слота через
/// разделяемую `Rc<Shape>`, а инлайн-кэш на месте вызова (`GetProp`/
/// `SetProp`) сравнивает форму указателем и читает слот напрямую.
///
/// `Dictionary` — путь деградации: объект, чья форма ушла глубже
/// `MAX_SHAPE_TRANSITIONS` шагов по цепочке переходов, перестаёт заводить
/// формы совсем (см. doc comment на константе — там же про то, почему
/// выселять формы нельзя). Платит поиском по `HashMap` и промахом
/// инлайн-кэша, зато `Вставить` в цикле с динамическими именами больше не
/// растит `ShapeTable`.
///
/// Переход ТОЛЬКО в одну сторону, `Shaped` -> `Dictionary`. Обратная
/// деградация после `Удалить` выглядит соблазнительно (набор полей ведь
/// снова короткий), но сделала бы поведение инлайн-кэша непредсказуемым:
/// один и тот же сайт вызова то попадал бы, то нет, в зависимости от
/// истории мутаций конкретного объекта.
#[derive(Debug)]
pub enum StructureStorage {
    Shaped {
        shape: Rc<Shape>,
        slots: Vec<BslValue>,
    },
    /// Порядок вставки хранится отдельно от таблицы поиска — ровно как
    /// в `MapData`, и по той же причине: `Для Каждого` обязан быть
    /// детерминированным.
    Dictionary {
        order: Vec<NameId>,
        values: HashMap<NameId, BslValue>,
    },
}

impl StructureStorage {
    pub fn new(shape: Rc<Shape>, slots: Vec<BslValue>) -> Self {
        StructureStorage::Shaped { shape, slots }
    }

    pub fn len(&self) -> usize {
        match self {
            StructureStorage::Shaped { slots, .. } => slots.len(),
            StructureStorage::Dictionary { order, .. } => order.len(),
        }
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    pub fn get(&self, field: NameId) -> Option<BslValue> {
        match self {
            StructureStorage::Shaped { shape, slots } => {
                shape.index.get(&field).map(|&s| slots[s as usize].clone())
            }
            StructureStorage::Dictionary { values, .. } => values.get(&field).cloned(),
        }
    }

    /// `false` — поля нет; заводить его здесь нельзя (это `а.Поле = ...`,
    /// а не `Вставить`: в 1С присваивание несуществующему полю структуры
    /// ошибка, а не создание поля).
    pub fn set(&mut self, field: NameId, val: BslValue) -> bool {
        match self {
            StructureStorage::Shaped { shape, slots } => match shape.index.get(&field) {
                Some(&s) => {
                    slots[s as usize] = val;
                    true
                }
                None => false,
            },
            StructureStorage::Dictionary { values, .. } => match values.get_mut(&field) {
                Some(slot) => {
                    *slot = val;
                    true
                }
                None => false,
            },
        }
    }

    /// `Вставить`: поле уже есть — перезапись значения, нет — расширение
    /// набора полей (сменой формы либо, если порог переходов исчерпан,
    /// с переключением объекта в словарный режим).
    pub fn insert(&mut self, field: NameId, val: BslValue, shapes: &mut ShapeTable) {
        match self {
            StructureStorage::Shaped { shape, slots } => {
                if let Some(&slot) = shape.index.get(&field) {
                    slots[slot as usize] = val;
                    return;
                }
                if let Some(next) = shapes.add_field(shape, field) {
                    slots.push(val);
                    *shape = next;
                    return;
                }
            }
            StructureStorage::Dictionary { order, values } => {
                if values.insert(field, val).is_none() {
                    order.push(field);
                }
                return;
            }
        }
        // Сюда доходит только `Shaped`, которому `add_field` отказал:
        // порог переходов исчерпан. Переключаемся на словарь и повторяем
        // вставку уже в нём — рекурсия ровно на один уровень, `degrade`
        // гарантированно оставляет `Dictionary`.
        self.degrade();
        self.insert(field, val, shapes);
    }

    /// `Удалить`: поля нет — no-op (см. `BslValue::structure_delete`).
    /// В словарном режиме порядок ОСТАЛЬНЫХ полей сохраняется — `order`
    /// теряет ровно один элемент, как `slots` в шейповом режиме.
    pub fn remove(&mut self, field: NameId, shapes: &mut ShapeTable) {
        match self {
            StructureStorage::Shaped { shape, slots } => {
                if let Some(&slot) = shape.index.get(&field) {
                    slots.remove(slot as usize);
                    *shape = shapes.remove_field(shape, field);
                }
            }
            StructureStorage::Dictionary { order, values } => {
                if values.remove(&field).is_some() {
                    order.retain(|&n| n != field);
                }
            }
        }
    }

    /// `Очистить()` — сбрасывает НАБОР полей, не только значения.
    /// Словарный объект остаётся словарным: деградация в одну сторону (см.
    /// doc comment на типе), даже когда полей снова ноль.
    pub fn clear(&mut self, shapes: &mut ShapeTable) {
        match self {
            StructureStorage::Shaped { shape, slots } => {
                slots.clear();
                *shape = shapes.empty();
            }
            StructureStorage::Dictionary { order, values } => {
                order.clear();
                values.clear();
            }
        }
    }

    /// i-я по порядку вставки пара (имя поля, значение) — протокол `Для
    /// Каждого`, тот же позиционный обход, что и у `MapData::entry_at`.
    pub fn entry_at(&self, i: usize) -> Option<(NameId, BslValue)> {
        match self {
            StructureStorage::Shaped { shape, slots } => {
                Some((*shape.names.get(i)?, slots.get(i)?.clone()))
            }
            StructureStorage::Dictionary { order, values } => {
                let n = *order.get(i)?;
                Some((n, values.get(&n)?.clone()))
            }
        }
    }

    /// Переключение на словарное хранение с сохранением порядка полей.
    fn degrade(&mut self) {
        let StructureStorage::Shaped { shape, slots } = std::mem::replace(
            self,
            StructureStorage::Dictionary {
                order: Vec::new(),
                values: HashMap::new(),
            },
        ) else {
            return;
        };
        let order = shape.names.clone();
        let values = order.iter().copied().zip(slots).collect();
        *self = StructureStorage::Dictionary { order, values };
    }
}
