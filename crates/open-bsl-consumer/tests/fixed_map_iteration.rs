use open_bsl::{Engine, Value};

#[test]
fn fixed_map_iteration_matches_native_snapshot_and_pair_controls() {
    let engine = Engine::builder().build().unwrap();
    let mut state = engine.state_builder().build();
    assert_eq!(
        state
            .exec(
                r#"
                ИсточникПробы = Новый Соответствие;
                ПустойПробы = Новый ФиксированноеСоответствие(ИсточникПробы);
                ЧислоПробы = 0;
                Для Каждого ПараПробы Из ПустойПробы Цикл
                    ЧислоПробы = ЧислоПробы + 1;
                КонецЦикла;
                Если ЧислоПробы <> 0 Тогда Возврат Ложь; КонецЕсли;
                ИсточникПробы.Вставить("alpha", 17);
                ИсточникПробы.Вставить("beta", 23);
                СнимокПробы = Новый ФиксированноеСоответствие(ИсточникПробы);
                ИсточникПробы.Вставить("alpha", 99);
                ИсточникПробы.Вставить("gamma", 31);
                НайденныеПробы = Новый Соответствие;
                Для Каждого ПараПробы Из СнимокПробы Цикл
                    ЧислоПробы = ЧислоПробы + 1;
                    Если ТипЗнч(ПараПробы) <> Тип("КлючИЗначение") Тогда Возврат Ложь; КонецЕсли;
                    НайденныеПробы.Вставить(ПараПробы.Ключ, ПараПробы.Значение);
                КонецЦикла;
                Попытка
                    ПараПробы.Значение = 42;
                    Возврат Ложь;
                Исключение
                КонецПопытки;
                Возврат ЧислоПробы = 2 И НайденныеПробы.Получить("alpha") = 17
                    И НайденныеПробы.Получить("beta") = 23 И СнимокПробы.Количество() = 2;
                "#,
            )
            .unwrap(),
        Value::Boolean(true)
    );
}
