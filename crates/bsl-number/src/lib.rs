/// Схема округления `Округл(Число, Разряды, Режим)`.
///
/// НЕ ИЗМЕРЕНО, всё в этом типе: ни какая схема действует по умолчанию, ни
/// какими числами платформа кодирует режимы, ни даже то, что вторая схема
/// — именно half-even (у 1С режимы называются `Окр15как10`/`Окр15как20`, и
/// «как10» может оказаться округлением половины ВНИЗ, а не к чётному).
/// Замеры, которые это закрывают, перечислены в README, раздел
/// «Замеры для человека».
///
/// Что ИЗМЕРЕНО и потому здесь не участвует: деление — half-up от нуля,
/// подтверждено точной ничьей 1/2²⁸ (см. `div_half_up_i128`). Режим
/// `Округл` может от него отличаться, поэтому это отдельный параметр, а не
/// общая настройка на весь крейт.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RoundMode {
    /// Половина от нуля: 2,5 -> 3, -2,5 -> -3.
    HalfUp,
    /// Половина к чётному: 2,5 -> 2, 3,5 -> 4.
    HalfEven,
}

/// Режим `Округл`, когда третий аргумент не указан.
///
/// НЕ ИЗМЕРЕНО. Взят half-up — та же схема, что у подтверждённого замером
/// деления; это ПРЕДПОЛОЖЕНИЕ о том, что платформа не разводит две схемы,
/// а не факт. Проверяется замером `Округл(2.5)`/`Округл(3.5)` из README.
pub const DEFAULT_ROUND_MODE: RoundMode = RoundMode::HalfUp;

/// Знаков после запятой в результате деления. Замер: `1/3` → 27 троек.
pub const DIV_SCALE: i32 = 27;

/// Значащих разрядов на возврате из f64. Замер: `Sqrt(2)` → 1,4142135623731.
pub const F64_SIG: usize = 15;

/// Предел масштаба. В 1С границы нет, но неограниченный рост съедает память,
/// поэтому здесь стоит защитный барьер с внятной ошибкой вместо OOM.
pub const MAX_SCALE: i32 = 100_000;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum NumError {
    /// Деление на ноль.
    DivideByZero,
    /// Аргумент вне области определения (`Sqrt(-1)`, `Log(0)`).
    Domain(&'static str),
    /// Значение не переводится в f64 без потери в бесконечность.
    NotFinite,
    /// Превышен защитный предел масштаба.
    ScaleOverflow,
    /// Строка не разбирается как число.
    BadLiteral,
}

impl std::fmt::Display for NumError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            NumError::DivideByZero => write!(f, "деление на ноль"),
            NumError::Domain(op) => write!(f, "аргумент вне области определения: {op}"),
            NumError::NotFinite => write!(f, "значение не представимо в f64"),
            NumError::ScaleOverflow => write!(f, "превышен предел масштаба"),
            NumError::BadLiteral => write!(f, "некорректный числовой литерал"),
        }
    }
}

impl std::error::Error for NumError {}

pub type NumResult<T> = Result<T, NumError>;
