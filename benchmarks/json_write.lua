-- Двойник json_write.bsl.
--
-- ВАЖНО ПРО СОПОСТАВИМОСТЬ, и здесь она хуже, чем у json_parse. Версия на
-- BSL зовёт потоковую `ЗаписьJSON`: та на каждое значение ЭКРАНИРУЕТ строку
-- и проверяет структуру документа (значение в объекте без имени свойства —
-- ошибка). Двойник ничего этого не делает: у Lua нет сериализатора JSON,
-- а писать его здесь значило бы мерить не Lua, а мою реализацию — ровно то,
-- за что двойник json_parse уже приходится оговаривать.
--
-- Поэтому колонки Lua здесь меряют НИЖНЮЮ ГРАНИЦУ: сборку той же строки
-- конкатенацией, без единой проверки. Читать их как «Lua пишет JSON быстрее»
-- нельзя — Lua вообще не пишет JSON, он склеивает заранее известный текст.
-- Осмысленная тройка та же: bsl-cli, OneScript и 1С.
--
-- Текст при этом обязан совпасть с тем, что порождает ЗаписьJSON, иначе
-- сравнивать нечего: совпадение проверено побайтово (см. README).

local concat = table.concat

local RECORDS = 10000
local PASSES = 3

local started = os.clock()
local length = 0
for _ = 1, PASSES do
    local parts = { '[' }
    local flag = false
    for i = 1, RECORDS do
        if i > 1 then
            parts[#parts + 1] = ','
        end
        flag = not flag
        local num = tostring(i)
        parts[#parts + 1] = '{"ид":' .. num
            .. ',"имя":"запись номер ' .. num .. '"'
            .. ',"активен":' .. (flag and 'true' or 'false')
            .. ',"цена":' .. num .. '.75'
            .. ',"теги":["альфа","бета","гамма"]'
            .. ',"вложенное":{"ключ":"значение","число":' .. num .. '}'
            .. ',"контрагент":{"инн":"77010' .. num .. '"'
            .. ',"кпп":"770101001"'
            .. ',"наименование":"ООО Ромашка ' .. num .. '"'
            .. ',"банковскийСчет":{"номер":"4070281090000000' .. num .. '"'
            .. ',"банк":"АО Банк ' .. num .. '"'
            .. ',"бик":"044525225"'
            .. ',"коррсчет":"30101810400000000225"}'
            .. ',"юрАдрес":{"регион":"Москва","город":"Москва","индекс":"101000"'
            .. ',"адрес":"ул. Тверская, д. ' .. num .. '"}'
            .. ',"фактическийАдрес":{"регион":"Московская область","город":"Химки"'
            .. ',"индекс":"141400","адрес":"ул. Победы, д. ' .. num .. '"}}}'
    end
    parts[#parts + 1] = ']'
    length = #concat(parts)
end
local elapsed_ms = (os.clock() - started) * 1000

print(string.format('длина документа (байт): %d, проходов: %d', length, PASSES))
print(string.format('%.3f', elapsed_ms))
