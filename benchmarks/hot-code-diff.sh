#!/bin/bash
# Сравнение МАШИННОГО КОДА диспетчерского цикла VM между базовым
# коммитом и рабочим деревом.
#
# Зачем это рядом с чередующимся A/B. Горячий цикл `bsl-vm` живёт на
# грани uop-кэша процессора, и в этом проекте уже случалось, что сдвиг
# раскладки менял сценарий на десятки процентов при НЕИЗМЕННОМ числе
# инструкций (см. комментарии у `step_cold`). Значит счётчика инструкций
# мало. Такты же требуют тихой машины: на загруженной разброс базовых
# прогонов доходил до 102 %, и вердикт по ним не выносится вовсе.
# Сравнение кода от загрузки не зависит и отвечает на предшествующий
# вопрос: изменилось ли то, что исполняет процессор.
#
# ЧТО ЭТОТ СКРИПТ ДОКАЗЫВАЕТ И ЧЕГО НЕ ДОКАЗЫВАЕТ.
#
# Сравниваются размер функции и полная последовательность инструкций
# ВМЕСТЕ С ОПЕРАНДАМИ И ДЛИНАМИ КОДИРОВОК. Снимается только то, что
# уникально для конкретной сборки и о коде ничего не говорит:
#
#   * адрес в начале строки и байтовая кодировка (несут абсолютные
#     адреса; сама функция встаёт по разным адресам, потому что
#     изменился посторонний код);
#   * смещение RIP-относительного операнда — цель его objdump печатает
#     символом в комментарии, и сравнивается именно символ;
#   * суффикс `.llvm.<число>` у внутренних символов и смещение в
#     `_DYNAMIC` — уникальные для прогона идентификаторы при том же
#     символе.
#
# Имена вызываемых функций сохраняются дословно, поэтому `call foo`
# вместо `call bar` расхождением БУДЕТ.
#
# Остаётся одна слепая зона, и она названа честно: обращение к
# анонимному пулу констант нормализуется до `<anon>` без смещения.
# Пул перекладывается от любого постороннего изменения, так что
# смещение в нём — шум; ценой этого чтение ДРУГОЙ константы из пула
# скрипт не различит. Поэтому совпадение здесь — сильный экран, а не
# доказательство: оно снимает подозрение на изменившийся код, но не
# отменяет чередующегося A/B там, где выигрыш или регрессию требуется
# показать числом.
#
#   ./benchmarks/hot-code-diff.sh [базовый-коммит]
#
# По умолчанию база — HEAD, то есть незакоммиченное дерево сравнивается
# с последним коммитом. Код возврата: 0 — обе функции сравнены и
# совпали, 1 — расхождение ЛИБО функцию не удалось сравнить.
set -euo pipefail

BASE="${1:-HEAD}"
ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"

# Всё своё — в каталоге этого прогона, включая ОБА каталога сборки.
# Общий `target/` не годится: в том же чекауте может работать другой
# агент, и его бинарник оказался бы в `target/release/bsl-cli` ровно
# между нашей сборкой и копированием — сравнивался бы чужой код.
# Общий фиксированный каталог не годится по той же причине во втором
# лице: два прогона этого скрипта смешали бы базу одного с кандидатом
# другого и снесли бы друг другу worktree.
#
# Платой идут две полные release-сборки на прогон: кэш между прогонами
# не переиспользуется. Для ворот, которые запускают перед изменением
# горячего пути, а не в цикле, это верный размен.
OUT="$(mktemp -d "${TMPDIR:-/tmp}/open-bsl-hot-code.XXXXXXXX")"
cleanup() {
    git worktree remove --force "$OUT/base-worktree" 2>/dev/null || true
    rm -rf "$OUT"
}
trap cleanup EXIT

# `.cargo/config.toml` задаёт `-align-all-functions=5` — это гигиена
# измерения, и обе сборки обязаны идти с ней. `RUSTFLAGS` её перекрывает
# целиком, поэтому он снимается для обеих сборок, а не игнорируется
# молча: с ним сравнивались бы две раскладки, ни одна из которых не та,
# по которой живёт проект. `CARGO_ENCODED_RUSTFLAGS` — второй вход к
# тому же, и снимается тоже.
if [ -n "${RUSTFLAGS:-}${CARGO_ENCODED_RUSTFLAGS:-}" ]; then
    echo "  RUSTFLAGS задан и снимается для обеих сборок:" >&2
    echo "  он перекрывает -align-all-functions=5 из .cargo/config.toml," >&2
    echo "  без которого сравнение раскладки недействительно." >&2
fi
unset RUSTFLAGS CARGO_ENCODED_RUSTFLAGS

build_here() {
    CARGO_TARGET_DIR="$OUT/cand-target" cargo build --release -q -p bsl-cli
    cp "$OUT/cand-target/release/bsl-cli" "$OUT/cli-candidate"
}

# Нормализованный текст функции: мнемоники И операнды, без уникального
# для сборки шума. Возвращает 1, если символ не найден или objdump не
# дал ни строки, — «не сравнили» обязано быть отказом, а не пропуском.
dump() {
    local bin="$1" fn="$2" out="$3" sym
    sym=$(nm "$bin" 2>/dev/null | grep -oE "_RNvCs[A-Za-z0-9_]*_6bsl_vm${fn}\$" | head -1) || true
    if [ -z "$sym" ]; then
        echo "  ${fn}: символ не найден в $(basename "$bin")" >&2
        return 1
    fi
    objdump -t "$bin" | grep -E "$sym\$" | awk '{print $5}' > "$out.size"
    # Длина кодировки каждой инструкции идёт в строку первым полем.
    # Без неё одинаковые дизассемблированные команды при одинаковом
    # общем размере ещё не значат одинаковую внутреннюю раскладку:
    # переход к той же цели кодируется и коротко, и длинно, и от этого
    # сдвигается всё, что за ним. Длины в том же порядке при том же
    # размере функции — это уже утверждение о раскладке.
    objdump -d --disassemble="$sym" "$bin" |
        awk -F'\t' 'NF>=3{n=split($2,b," "); printf "%d\t%s\n", n, $3}' |
        sed -E 's/\b[0-9a-f]{4,16} </</g
                s/-?0x[0-9a-f]+\(%rip\)/RIP/g
                s/<anon\.[0-9a-f]+\.[0-9]+\.llvm\.[0-9]+\+0x[0-9a-f]+>/<anon>/g
                s/\.llvm\.[0-9]+//g
                s/<_DYNAMIC\+0x[0-9a-f]+>/<_DYNAMIC>/g' > "$out.code"
    if [ ! -s "$out.code" ] || [ ! -s "$out.size" ]; then
        echo "  ${fn}: objdump не дал кода для $(basename "$bin")" >&2
        return 1
    fi
}

echo "== сравнение горячего кода: $BASE против рабочего дерева =="
build_here

# База собирается в ОТДЕЛЬНОМ worktree, а не переключением текущего.
# Причина не стилистическая: `git stash` с `checkout` тронул бы общее
# рабочее дерево, а в нём может идти чужая работа — и, оборвись скрипт
# посередине, вернуть его было бы некому. Worktree не трогает ничего.
WT="$OUT/base-worktree"
git worktree add -q --detach "$WT" "$BASE"
(
    cd "$WT"
    CARGO_TARGET_DIR="$OUT/base-target" cargo build --release -q -p bsl-cli
    cp "$OUT/base-target/release/bsl-cli" "$OUT/cli-base"
)

status=0
for fn in 4step 9step_cold; do
    if ! dump "$OUT/cli-base" "$fn" "$OUT/base-$fn" ||
        ! dump "$OUT/cli-candidate" "$fn" "$OUT/cand-$fn"; then
        printf '  %-12s НЕ СРАВНЕНА\n' "$fn"
        status=1
        continue
    fi
    size_a=$(cat "$OUT/base-$fn.size")
    size_b=$(cat "$OUT/cand-$fn.size")
    n=$(wc -l < "$OUT/base-$fn.code")
    if [ "$size_a" = "$size_b" ] && cmp -s "$OUT/base-$fn.code" "$OUT/cand-$fn.code"; then
        printf '  %-12s размер 0x%s, %s инструкций с операндами и длинами — СОВПАДАЕТ\n' \
            "$fn" "$size_a" "$n"
    else
        printf '  %-12s размер 0x%s -> 0x%s, расхождений строк %s — ИЗМЕНИЛСЯ\n' \
            "$fn" "$size_a" "$size_b" \
            "$(diff "$OUT/base-$fn.code" "$OUT/cand-$fn.code" | grep -c '^<' || true)"
        status=1
    fi
done

if [ "$status" = 0 ]; then
    echo "  код горячего пути не изменился — подозрение на регрессию раскладки снято"
    echo "  (это экран, а не замер: выигрыш или регрессию по-прежнему показывает A/B)"
else
    echo "  сравнение не прошло — нужен чередующийся A/B на тихой машине"
fi
exit "$status"
