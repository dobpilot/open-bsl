#!/bin/bash
# Цена ОБЩИХ ПРОВЕРОК периметра образа, в инструкциях, чередующимся A/B.
#
# Что меряется. ОДИН общий проход `image::verify` — границы регистров,
# номеров констант и модульных слотов. Не весь периметр: длины
# инлайн-кэшей, свежесть разметки бандлов и поопкодные проверки остаются в
# ОБЕИХ сторонах и в разницу не входят. Проверка идёт один раз на
# программу, до первой инструкции, но идёт на КАЖДОМ запуске; диспетчер
# она не трогает вовсе, поэтому `hot-code-diff.sh` о ней ничего не
# говорит — нужен отдельный замер.
#
# Как меряется. Сторона «без проверок» получается вырезанием блока между
# якорями «НАЧАЛО/КОНЕЦ ОБЩИХ ПРОВЕРОК» в `crates/bsl-bytecode/src/image.rs`.
# Переключателя для этого в продукте нет намеренно: выключаемая проверка
# образа — это способ однажды выключить её случайно. Обе стороны
# собираются в отдельных worktree и своих каталогах сборки, поэтому
# рабочее дерево не трогается и параллельный агент не может подменить
# бинарник между сборкой и копированием.
#
# Метрика — `instructions:u`, а не такты: замер идёт на рабочей машине,
# где load average бывает и семь, и такты вердикта не выдерживают.
# Счётчик инструкций к планированию менее чувствителен, чем такты, но
# безразличным к обстановке его считать нельзя: путь программы и число
# исполненных инструкций сами меняются от таймингов, сети и прочих
# условий запуска. Поэтому печатается не одно число, а наблюдённый
# диапазон пар, и пересечение нуля отмечается явно.
#
#   ./benchmarks/perimeter-cost.sh [коммит] [пар]
#   ./benchmarks/perimeter-cost.sh --self-test [коммит] [пар]
#
# По умолчанию коммит — HEAD, пар — 5. Прогоны ЧЕРЕДУЮТСЯ: база, кандидат,
# база, кандидат — а не блоками, иначе разница блоков смешалась бы с
# разницей конфигураций.
set -euo pipefail

# Числа ходят через текст: `awk` их печатает, `sort -n` упорядочивает,
# `awk` читает обратно. В русской локали разделителем стала бы запятая, и
# круг разошёлся бы сам с собой — сортировка и обратный разбор её не
# понимают, дробная часть терялась бы, а минимум оказывался бы больше
# максимума. Замечено на этой самой машине.
export LC_ALL=C

SELF_TEST=0
if [ "${1:-}" = "--self-test" ]; then
    SELF_TEST=1
    shift
fi
BASE_REF="${1:-HEAD}"
PAIRS="${2:-5}"
PERF="${PERF:-perf}"
ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"

# Ноль пар прошёл бы весь скрипт молча: цикл не исполнился бы, агрегатор
# напечатал бы нули, код возврата остался бы нулевым. Замер, не сделавший
# ни одного прогона, обязан быть отказом, а не красивой таблицей.
case "$PAIRS" in
    '' | *[!0-9]*) echo "число пар должно быть целым: «$PAIRS»" >&2; exit 2 ;;
esac
[ "$PAIRS" -ge 1 ] || { echo "число пар должно быть не меньше одного" >&2; exit 2; }

OUT="$(mktemp -d "${TMPDIR:-/tmp}/open-bsl-perimeter.XXXXXXXX")"
# Каталог остаётся жить, а путь восстановления печатается целиком.
cleanup_failed() {
    {
        echo "уборка не удалась: $1"
        echo "каталог НАМЕРЕННО не удалён, чтобы запись не осталась без него: $OUT"
        echo "снять вручную:"
        echo "  git worktree remove -f -f $OUT/with"
        echo "  git worktree remove -f -f $OUT/without"
        echo "  rm -rf $OUT"
    } >&2
}

cleanup() {
    local registered
    # `-f -f`, а не `--force`: `git worktree add` держит новый worktree
    # ЗАБЛОКИРОВАННЫМ, пока инициализирует его, и одинарного не хватает —
    # «cannot remove a locked working tree, lock reason: initializing».
    # Двойной снимает и блокировку; это документированный способ, а не
    # обход.
    git worktree remove -f -f "$OUT/with" 2>/dev/null || true
    git worktree remove -f -f "$OUT/without" 2>/dev/null || true
    # Каталог сносится, ТОЛЬКО если git отпустил обе записи. Проверяется
    # состояние, а не код возврата снятия: причина отказа может быть
    # любой, а опасен один исход — снести каталог, оставив запись. Это
    # ровно то, от чего заведена вся уборка, и молча так уже случалось.
    #
    # Список берётся ОТДЕЛЬНОЙ командой, а не конвейером прямо в условии.
    # `git worktree list | grep -q` под `pipefail` врёт ровно в опасную
    # сторону: `grep -q` закрывает канал на ПЕРВОМ совпадении, git
    # получает SIGPIPE, конвейер отдаёт 141 — и найденная живая запись
    # читается как «не найдено», после чего каталог сносится. Проверено:
    # grep — 0, конвейер — 141. Отказ самого `list` уходил туда же, хотя
    # состояние регистраций после него попросту неизвестно.
    #
    # И здесь `grep` без `-q`, с выводом в `/dev/null`: раз опасность в
    # раннем закрытии канала, дешевле дочитать вход до конца, чем
    # рассуждать, чем bash подаёт строку — файлом или каналом.
    if ! registered=$(git worktree list --porcelain 2>/dev/null); then
        cleanup_failed "не удалось получить список worktree, состояние неизвестно"
    elif grep -F "$OUT" > /dev/null <<< "$registered"; then
        cleanup_failed "git не отпустил worktree под $OUT"
    else
        rm -rf "$OUT"
    fi
}

# EXIT — общий путь уборки; ловушки сигналов сводятся к нему, а не
# заводят себе второй.
#
# Без явных ловушек сигнал, посланный ТОЛЬКО оболочке (`kill <pid>` от
# супервизора или обёртки с таймаутом), убивает bash немедленно, посреди
# работающего потомка. Ловушка EXIT при этом ИСПОЛНЯЕТСЯ — спотыкается
# уборка: если потомком был `git worktree add`, он ещё держит worktree
# заблокированным («lock reason: initializing»), и `git worktree remove
# --force` на такой не срабатывает. Каталог затем уносит `rm -rf`, а
# запись остаётся в репозитории насовсем. Измерено: три прогона из трёх
# оставляли зарегистрированный worktree без каталога.
#
# Явная ловушка это и закрывает: bash откладывает её до конца текущего
# потомка, `git worktree add` успевает снять блокировку, и уборка
# проходит — шесть прогонов из шести чисто. Сигнал, посланный ГРУППЕ
# (Ctrl-C, обрыв терминала), утечки не давал и раньше: он приходит и
# потомку тоже. Сами ловушки только выходят с кодом 128 + номер сигнала:
# уборку запускает всё та же EXIT, ровно один раз, — второго пути к ней
# нет.
#
# Оговорка про SIGINT: пока работает потомок, bash его отбрасывает — и с
# ловушкой, и без неё, измерено. Ctrl-C в терминале этим не задет, он
# приходит всей группе; а `kill -INT <pid>` в одиночку такой прогон
# просто не остановит, и код будет не 130. Свойство оболочки, не скрипта.
#
# SIGKILL не перехватывается ничем — ловушки для него нет в ядре, — так
# что `kill -9` по-прежнему оставит и worktree, и каталог. Убирать тогда
# руками, и обычного `--force` может не хватить по той же причине:
#
#   git worktree remove -f -f <каталог> && rm -rf <каталог>
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
trap 'exit 129' HUP

# Каждый сценарий сперва прогоняется НАСУХО и его вывод проверяется на
# признак раннего выхода. Молча измерить не то — главный способ получить
# красивое число ни о чём.
check_runs() {
    local out
    out=$( cd "$OUT/with" && "$OUT/cli-with" "benchmarks/$1.bsl" 2>&1 ) || {
        echo "  $1: прогон завершился ошибкой" >&2
        return 1
    }
    if printf '%s' "$out" | grep -qiE "не открыл|не найден|гоняется из корня"; then
        echo "  $1: сценарий не выполнился — $(printf '%s' "$out" | head -1)" >&2
        return 1
    fi
}

# Один прогон одной стороны. Печатает РОВНО одно положительное целое или
# отказывает с диагностикой.
#
# Проверяется каждое значение ОТДЕЛЬНО. Прежняя запись сверяла склейку
# `"$a$c"`: пустой ответ одной стороны прятался за цифрами другой, и
# дельта считалась из нуля. Пустой, многострочный (перевод строки — не
# цифра) и нечисловой ответ `perf` — это не результат, а отказ.
one() {                                  # one <сторона> <сценарий>
    local v
    if ! v=$(
        cd "$OUT/with" &&
            "$PERF" stat -x, -e instructions:u -- \
                "$OUT/cli-$1" "benchmarks/$2.bsl" 2>&1 >/dev/null |
            awk -F, '/instructions:u/{print $1}'
    ); then
        echo "  $2 [$1]: perf завершился с ошибкой" >&2
        return 1
    fi
    case "$v" in
        '')       echo "  $2 [$1]: perf не дал числа" >&2; return 1 ;;
        *[!0-9]*) echo "  $2 [$1]: perf дал не одно целое: «$v»" >&2; return 1 ;;
        *[1-9]*)  ;;                     # хотя бы одна ненулевая цифра
        *)        echo "  $2 [$1]: ноль инструкций" >&2; return 1 ;;
    esac
    printf '%s\n' "$v"
}

# Пары пишутся в файл, а не текут в конвейер внутри условия `if !`: там
# `set -e` не действует, и отказ одной стороны до кода возврата скрипта
# не доходил. Здесь код возврата КАЖДОГО вызова `one` проверяется явно.
#
# Порядок внутри пары ЧЕРЕДУЕТСЯ (AB, BA, AB, ...): при одном и том же
# порядке систематическая разница «первый запуск дороже второго» целиком
# легла бы на одну сторону.
measure_pairs() {                        # measure_pairs <сценарий> <файл пар>
    local i a c
    : > "$2"
    for ((i = 0; i < PAIRS; i++)); do
        if ((i % 2 == 0)); then
            a=$(one without "$1") || return 1
            c=$(one with "$1") || return 1
        else
            c=$(one with "$1") || return 1
            a=$(one without "$1") || return 1
        fi
        printf '%s %s\n' "$a" "$c" >> "$2"
    done
}

# Парные дельты, а не два средних. На этих сценариях прогонный разброс
# сопоставим с самим эффектом, и одно среднее читалось бы точнее, чем
# оно есть. Печатается медиана пар и их диапазон.
#
# Дельты СОРТИРУЮТСЯ внешним `sort -n`, а не `asort` внутри awk:
# последний — расширение GNU, и на mawk, который стоит по умолчанию в
# части систем, скрипт бы просто упал.
summarize() {                            # summarize <сценарий> <файл пар>
    awk '{printf "%.6f\n", ($2 - $1) * 100 / $1}' "$2" | sort -n |
        awk -v n="$1" -v want="$PAIRS" '
            {d[NR] = $1}
            END {
                # Пар обязано быть ровно столько, сколько заказано:
                # потерянная пара — это замер, о котором никто не узнал.
                if (NR != want + 0) {
                    printf "  %s: пар %d вместо %d\n", n, NR, want > "/dev/stderr"
                    exit 1
                }
                m = (NR % 2) ? d[(NR + 1) / 2] : (d[NR / 2] + d[NR / 2 + 1]) / 2
                crosses = (d[1] < 0 && d[NR] > 0) ? " (диапазон пересекает ноль)" : ""
                printf "  %-24s %+9.3f%% %+9.3f%% %+9.3f%%   %d%s\n", n, m, d[1], d[NR], NR, crosses
            }'
}

# Весь замер. Именно код возврата этой функции скрипт отдаёт наружу —
# поэтому проверка «зубов» гоняет её, а не что-то похожее на неё.
run_scenarios() {
    local status=0 b pairs
    printf '  %-24s %10s %10s %10s   %s\n' "сценарий" "медиана" "минимум" "максимум" "пар"
    for b in "${SCENARIOS[@]}"; do
        [ -f "$BENCH/$b.bsl" ] || { echo "  $b: сценарий не найден" >&2; status=1; continue; }
        check_runs "$b" || { status=1; continue; }
        pairs="$OUT/pairs-$b"
        measure_pairs "$b" "$pairs" || { status=1; continue; }
        summarize "$b" "$pairs" || { status=1; continue; }
    done
    return "$status"
}

# Проверка «зубов»: что скрипт действительно ОТКАЗЫВАЕТ, когда померить
# не удалось. Дефект с проглоченным отказом одной стороны нашли чтением,
# а не прогоном, — значит, нужен прогон.
#
# Ничего не собирается: `perf` и оба бинарника подменяются заглушками,
# сценарий пустой. Занимает доли секунды, поэтому её не жалко запускать
# при каждой правке скрипта.
self_test() {
    local failed=0 keep got
    PERF="$OUT/perf"
    BENCH="$OUT/with/benchmarks"
    SCENARIOS=(stub)
    mkdir -p "$BENCH"
    : > "$BENCH/stub.bsl"
    printf '#!/bin/sh\necho ок\n' > "$OUT/cli-with"
    chmod +x "$OUT/cli-with"
    cp "$OUT/cli-with" "$OUT/cli-without"

    # Заглушка `perf stat -x,`: счётчик пишется в stderr, как у настоящей,
    # а что именно написать — берётся из файла `case`, чтобы случай
    # задавался снаружи, а сама заглушка оставалась одна.
    cat > "$OUT/perf" <<'STUB'
#!/bin/bash
say() { printf '%s,,instructions:u,1234,100.00,,\n' "$1" >&2; }
side=with
case "$*" in *cli-without*) side=without ;; esac
read -r what < "$(dirname "$0")/case"
case "$what:$side" in
    ok:*)                  say 1000000 ;;
    empty-without:without) : ;;
    empty-without:with)    say 1000000 ;;
    empty-with:with)       : ;;
    empty-with:without)    say 1000000 ;;
    multi:without)         say 1000000; say 1000001 ;;
    multi:with)            say 1000000 ;;
    text:without)          say "нет" ;;
    text:with)             say 1000000 ;;
    zero:without)          say 0 ;;
    zero:with)             say 1000000 ;;
    crash:*)               say 1000000; exit 1 ;;
    *) echo "заглушка: неизвестный случай «$what»" >&2; exit 2 ;;
esac
STUB
    chmod +x "$OUT/perf"

    expect() {                           # expect <случай> <ok|fail> <описание>
        local rc=0
        printf '%s\n' "$1" > "$OUT/case"
        run_scenarios > /dev/null 2>&1 || rc=$?
        if { [ "$2" = ok ] && [ "$rc" -eq 0 ]; } || { [ "$2" = fail ] && [ "$rc" -ne 0 ]; }; then
            printf '  зубы: %s — %s\n' "$3" "$2"
        else
            printf '  ЗУБЫ НЕ ВЗЯЛИ: %s — код %d, ожидалось «%s»\n' "$3" "$rc" "$2" >&2
            failed=1
        fi
    }

    expect ok            ok   "обе стороны дали по числу"
    expect empty-without fail "пусто у стороны без проверок"
    expect empty-with    fail "пусто у стороны с проверками"
    expect multi         fail "две строки вместо одной"
    expect text          fail "нечисловой ответ"
    expect zero          fail "ноль инструкций"
    expect crash         fail "perf завершился с ошибкой"

    # Арифметика агрегатора — на заведомых парах: дельты +1 %, +3 %, −1 %,
    # значит медиана +1 %, минимум −1 %, максимум +3 %, и диапазон
    # пересекает ноль.
    keep="$PAIRS"
    PAIRS=3
    printf '100 101\n100 103\n100 99\n' > "$OUT/pairs-known"
    got=$(summarize stub "$OUT/pairs-known" 2>/dev/null)
    if [ "$(printf '%s' "$got" | awk '{print $2, $3, $4, $5}')" = "+1.000% -1.000% +3.000% 3" ] &&
        printf '%s' "$got" | grep -q "пересекает ноль"; then
        printf '  зубы: %s — ok\n' "медиана, минимум, максимум, пересечение нуля"
    else
        printf '  ЗУБЫ НЕ ВЗЯЛИ: агрегатор дал «%s»\n' "$got" >&2
        failed=1
    fi

    # Зубы уборки. `cleanup` гоняется как есть, но со своим каталогом и
    # подставным `git`. Два случая обязаны каталог СОХРАНИТЬ: большой
    # вывод `worktree list` с совпадением в первой строке (прежняя форма
    # `list | grep -q` получала там SIGPIPE и сносила каталог при живой
    # записи) и отказ самого `list` (состояние регистраций неизвестно).
    # Третий, без совпадения, обязан каталог снести — иначе проверка
    # доказывала бы только то, что уборка ничего не делает.
    mkdir -p "$OUT/gitstub"
    cat > "$OUT/gitstub/git" <<GITSTUB
#!/bin/sh
[ "\$1" = worktree ] || exec $(command -v git) "\$@"
case "\$2" in
    remove) exit 0 ;;
    list)
        case "\$(cat "\$(dirname "\$0")/case")" in
            # Совпадение ПЕРВОЙ строкой, дальше много вывода: потребитель,
            # закрывающий канал на первом совпадении, оставит producer с
            # SIGPIPE.
            big)  echo "worktree \$OUT/with"
                  awk 'BEGIN{for(i=0;i<200000;i++) print "worktree /tmp/чужой-" i}' ;;
            fail) echo "fatal: подставной отказ list" >&2; exit 128 ;;
            none) echo "worktree /tmp/чужой" ;;
        esac ;;
    *) exec $(command -v git) "\$@" ;;
esac
GITSTUB
    chmod +x "$OUT/gitstub/git"
    check_cleanup() {                    # check_cleanup <случай> <keep|drop> <описание>
        local dir stubpath
        dir="$OUT/cleanup-$1"
        stubpath="$OUT/gitstub"
        mkdir -p "$dir"
        printf '%s\n' "$1" > "$stubpath/case"
        ( PATH="$stubpath:$PATH"; export OUT="$dir"; cleanup ) > /dev/null 2>&1
        if { [ "$2" = keep ] && [ -d "$dir" ]; } || { [ "$2" = drop ] && [ ! -d "$dir" ]; }; then
            printf '  зубы: %s — %s\n' "$3" "$2"
        else
            printf '  ЗУБЫ НЕ ВЗЯЛИ: %s — каталог %s\n' "$3" \
                "$( [ -d "$dir" ] && echo "остался" || echo "снесён" )" >&2
            failed=1
            rm -rf "$dir"
        fi
    }
    check_cleanup big  keep "живая запись в большом выводе list"
    check_cleanup fail keep "worktree list отказал"
    check_cleanup none drop "записей не осталось"

    # Недостача пар обязана быть отказом, а не таблицей по тому, что дошло.
    printf '100 101\n100 103\n' > "$OUT/pairs-short"
    if summarize stub "$OUT/pairs-short" > /dev/null 2>&1; then
        printf '  ЗУБЫ НЕ ВЗЯЛИ: две пары вместо трёх приняты\n' >&2
        failed=1
    else
        printf '  зубы: %s — fail\n' "пар меньше заказанного"
    fi
    PAIRS="$keep"

    return "$failed"
}

if [ "$SELF_TEST" = 1 ]; then
    echo "== проверка зубов измерительного скрипта: пар $PAIRS =="
    rc=0
    self_test || rc=$?
    if [ "$rc" -eq 0 ]; then
        echo "  зубы на месте: несостоявшийся замер — это отказ скрипта"
    else
        echo "  ЗУБЫ ВЫПАЛИ: скрипт способен отчитаться, ничего не измерив" >&2
    fi
    exit "$rc"
fi

# `.cargo/config.toml` задаёт `-align-all-functions=5`; чужие флаги
